using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Dues
{
    public partial class Defualters_Dues : DevExpress.XtraEditors.XtraForm
    {
        Area_Code_Wise_Defaulters_Report area_code_wise_defaulters_report;
        public Defualters_Dues()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            area_code_wise_defaulters_report = null;
            area_code_wise_defaulters_report = new Area_Code_Wise_Defaulters_Report(-1);
            area_code_wise_defaulters_report.RequestParameters = false;
            documentViewer1.DocumentSource = area_code_wise_defaulters_report;
            area_code_wise_defaulters_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            area_code_wise_defaulters_report = null;
            if(store_cmb.Text == "")
            {
                area_code_wise_defaulters_report = new Area_Code_Wise_Defaulters_Report(-1);
            }
            else
            {
                area_code_wise_defaulters_report = new Area_Code_Wise_Defaulters_Report(Convert.ToInt32(store_cmb.EditValue));
            }
            area_code_wise_defaulters_report.RequestParameters = false;
            documentViewer1.DocumentSource = area_code_wise_defaulters_report;
            area_code_wise_defaulters_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(area_code_wise_defaulters_report);
            print_tool.Print();
        }
    }
}