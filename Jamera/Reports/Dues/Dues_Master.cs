using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Dues
{
    public partial class Dues_Master : DevExpress.XtraEditors.XtraForm
    {
        Dues_Master_Report_Curr_Mon dues_master_report;
        public Dues_Master()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            dues_master_report = null;
            dues_master_report = new Dues_Master_Report_Curr_Mon(-1);
            dues_master_report.RequestParameters = false;
            documentViewer1.DocumentSource = dues_master_report;
            dues_master_report.CreateDocument();

            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            dues_master_report = null;
            int store_id = -1;
            if(store_cmb.Text != "")
            {
                store_id = Convert.ToInt32(store_cmb.EditValue);
            }
            dues_master_report = new Dues_Master_Report_Curr_Mon(store_id);
            dues_master_report.RequestParameters = false;
            documentViewer1.DocumentSource = dues_master_report;
            dues_master_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(dues_master_report);
            print_tool.Print();
        }
    }
}