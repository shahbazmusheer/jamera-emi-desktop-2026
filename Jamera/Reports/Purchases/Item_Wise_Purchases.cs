using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Purchases
{
    public partial class Item_Wise_Purchases : DevExpress.XtraEditors.XtraForm
    {
        Item_Purchases_Report item_purchases_report;
        public Item_Wise_Purchases()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            item_purchases_report = null;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();

            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
            item_purchases_report = new Item_Purchases_Report(from_date_picker.Text, to_date_picker.Text,-1);
            item_purchases_report.RequestParameters = false;
            documentViewer1.DocumentSource = item_purchases_report;
            item_purchases_report.CreateDocument();
        }

        private void As_Item_Purchases_Load(object sender, EventArgs e)
        {
            
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(item_purchases_report);
            print_tool.Print();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            item_purchases_report = null;
            if(item_cmb.Text == "")
            {
                item_purchases_report = new Item_Purchases_Report(from_date_picker.Text, to_date_picker.Text,-1);
            }
            else
            {
                item_purchases_report = new Item_Purchases_Report(from_date_picker.Text, to_date_picker.Text,Convert.ToInt32(item_cmb.EditValue));
            }
            item_purchases_report.RequestParameters = false;
            documentViewer1.DocumentSource = item_purchases_report;
            item_purchases_report.CreateDocument();
        }
    }
}