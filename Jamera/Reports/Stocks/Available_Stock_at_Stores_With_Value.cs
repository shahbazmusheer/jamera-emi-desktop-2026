using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Stocks
{
    public partial class Available_Stock_at_Stores_With_Value : DevExpress.XtraEditors.XtraForm
    {
        Stock_Inventory_Report_With_Value stores_inventory_report_with_value;
        public Available_Stock_at_Stores_With_Value()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            stores_inventory_report_with_value = null;
            stores_inventory_report_with_value = new Stock_Inventory_Report_With_Value(-1);
            stores_inventory_report_with_value.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_report_with_value;
            stores_inventory_report_with_value.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            stores_inventory_report_with_value = null;
            if(store_cmb.Text == "")
            {
                stores_inventory_report_with_value = new Stock_Inventory_Report_With_Value(-1);
            }
            else
            {
                stores_inventory_report_with_value = new Stock_Inventory_Report_With_Value(Convert.ToInt32(store_cmb.EditValue));
            }
            stores_inventory_report_with_value.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_report_with_value;
            stores_inventory_report_with_value.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(stores_inventory_report_with_value);
            print_tool.Print();
        }
    }
}