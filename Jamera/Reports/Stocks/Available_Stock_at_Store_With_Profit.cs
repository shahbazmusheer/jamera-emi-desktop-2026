namespace Jamera.Reports.Stocks
{
    public partial class Available_Stock_at_Store_With_Profit : DevExpress.XtraEditors.XtraForm
    {
        Available_Stock_Stores_Profit_Report stores_inventory_profit_report;
        public Available_Stock_at_Store_With_Profit()
        {
            InitializeComponent();
            stores_inventory_profit_report = null;
            stores_inventory_profit_report = new Available_Stock_Stores_Profit_Report(-1, -1);
            stores_inventory_profit_report.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_profit_report;
            stores_inventory_profit_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            stores_inventory_profit_report = null;
            //here we will change
            int store_id = -1;
            string store_name = "All Stores";
            int item_id = -1;
            if(store_cmb.Text != "")
            {
                store_id = Convert.ToInt32(store_cmb.EditValue);
                store_name = store_cmb.Text;
            }

            if(item_cmb.Text != "")
            {
                item_id = Convert.ToInt32(item_cmb.EditValue);
            }
            stores_inventory_profit_report = new Available_Stock_Stores_Profit_Report(store_id, item_id, store_name);
            
            stores_inventory_profit_report.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_profit_report;
            stores_inventory_profit_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(stores_inventory_profit_report);
            print_tool.Print();
        }
    }
}