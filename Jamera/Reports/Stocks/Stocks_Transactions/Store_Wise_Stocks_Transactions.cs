using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Stocks.Stocks_Transactions
{
    public partial class Store_Wise_Stocks_Transactions : XtraForm
    {
        To_Store_Transactions_Report to_store_transactions_report;
        public Store_Wise_Stocks_Transactions()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            to_store_transactions_report = null;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();
            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
            to_store_transactions_report = new To_Store_Transactions_Report(from_date_picker.Text, to_date_picker.Text,-1);
            to_store_transactions_report.RequestParameters = false;
            documentViewer1.DocumentSource = to_store_transactions_report;
            to_store_transactions_report.CreateDocument();
            
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            to_store_transactions_report = null;
            if(store_cmb.Text == "")
            {
                to_store_transactions_report = new To_Store_Transactions_Report(from_date_picker.Text, to_date_picker.Text,-1);
            }
            else
            {
                to_store_transactions_report = new To_Store_Transactions_Report(from_date_picker.Text, to_date_picker.Text, Convert.ToInt32(store_cmb.EditValue));
            }
            to_store_transactions_report.RequestParameters = false;
            documentViewer1.DocumentSource = to_store_transactions_report;
            to_store_transactions_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(to_store_transactions_report);
            print_tool.Print();
        }
    }
}