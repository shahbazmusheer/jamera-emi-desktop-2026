using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using Jamera.Properties;
using System.IO;

namespace Jamera.Reports.Stocks
{
    public partial class Low_Stock_at_Stores : DevExpress.XtraEditors.XtraForm
    {
        Low_Stock_At_Stores_Report low_stock_at_stores_report;
        public Low_Stock_at_Stores()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            low_stock_at_stores_report = null;
            low_stock_at_stores_report = new Low_Stock_At_Stores_Report(-1);
            low_stock_at_stores_report.RequestParameters = false;
            documentViewer1.DocumentSource = low_stock_at_stores_report;
            low_stock_at_stores_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            low_stock_at_stores_report = null;
            //here we will change
            if (store_cmb.Text == "")
            {
                low_stock_at_stores_report = new Low_Stock_At_Stores_Report(-1);
            }
            else
            {
                low_stock_at_stores_report = new Low_Stock_At_Stores_Report(Convert.ToInt32(store_cmb.EditValue));
            }
            low_stock_at_stores_report.RequestParameters = false;
            documentViewer1.DocumentSource = low_stock_at_stores_report;
            low_stock_at_stores_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(low_stock_at_stores_report);
            print_tool.Print();
        }
    }
}