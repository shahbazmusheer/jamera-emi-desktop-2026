namespace Jamera.Reports.Stocks
{
    public partial class Available_Stock_at_Stores : DevExpress.XtraEditors.XtraForm
    {
        Stores_Inventory_Report stores_inventory_report;
        public Available_Stock_at_Stores()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            stores_inventory_report = null;
            stores_inventory_report = new Stores_Inventory_Report(-1, -1);
            stores_inventory_report.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_report;
            stores_inventory_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
           
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            stores_inventory_report = null;
            //here we will change
            if(store_cmb.Text == "" && item_cmb.Text == "")
            {
                stores_inventory_report = new Stores_Inventory_Report(-1,-1);
            }
            else if (store_cmb.Text != "" && item_cmb.Text == "")
            {
                stores_inventory_report = new Stores_Inventory_Report(Convert.ToInt32(store_cmb.EditValue),-1);
            }
            else if (store_cmb.Text == "" && item_cmb.Text != "")
            {
                stores_inventory_report = new Stores_Inventory_Report(-1,Convert.ToInt32(item_cmb.EditValue));
            }
            else
            {
                stores_inventory_report = new Stores_Inventory_Report(Convert.ToInt32(store_cmb.EditValue), Convert.ToInt32(item_cmb.EditValue));
            }
            stores_inventory_report.RequestParameters = false;
            documentViewer1.DocumentSource = stores_inventory_report;
            stores_inventory_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(stores_inventory_report);
            print_tool.Print();
        }
    }
}