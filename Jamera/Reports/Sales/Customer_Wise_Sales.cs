using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;
using System.IO;
using Jamera.Properties;
namespace Jamera.Reports.Sales
{
    public partial class Customer_Wise_Sales : DevExpress.XtraEditors.XtraForm
    {
        Customer_Wise_Sales_Report customer_wise_sales_report;
        public Customer_Wise_Sales()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            customer_wise_sales_report = null;
            customer_wise_sales_report = new Customer_Wise_Sales_Report(-1);
            customer_wise_sales_report.RequestParameters = false;
            documentViewer1.DocumentSource = customer_wise_sales_report;
            customer_wise_sales_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            customer_wise_sales_report = null;
            if(customer_cmb.Text == "")
            {
                customer_wise_sales_report = new Customer_Wise_Sales_Report(-1);
            }
            else
            {
                customer_wise_sales_report = new Customer_Wise_Sales_Report(Convert.ToInt32(customer_cmb.EditValue));
            }
            customer_wise_sales_report.RequestParameters = false;
            documentViewer1.DocumentSource = customer_wise_sales_report;
            customer_wise_sales_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(customer_wise_sales_report);
            print_tool.Print();
        }
    }
}