using Jamera.Properties;
namespace Jamera.Reports.Sales
{
    public partial class Sales_Master : DevExpress.XtraEditors.XtraForm
    {
        Sales_Master_Report aggrements_master_report;
        public Sales_Master()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            aggrements_master_report = null;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();
            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            aggrements_master_report = new Sales_Master_Report(-1, from_date_picker.Text, to_date_picker.Text);
            aggrements_master_report.RequestParameters = false;
            documentViewer1.DocumentSource = aggrements_master_report;
            aggrements_master_report.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(aggrements_master_report);
            print_tool.Print();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            aggrements_master_report = null;
            int store_id = -1;
            if(store_cmb.Text != "")
            {
                store_id = Convert.ToInt32(store_cmb.EditValue);
            }
            aggrements_master_report = new Sales_Master_Report(store_id,from_date_picker.Text, to_date_picker.Text);
            aggrements_master_report.RequestParameters = false;
            documentViewer1.DocumentSource = aggrements_master_report;
            aggrements_master_report.CreateDocument();
        }

        private void Sales_Master_Load(object sender, EventArgs e)
        {

        }
    }
}