using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.XtraReports.UI;

namespace Jamera.Reports.Sales.Profit_Reports
{
    public partial class Profit_Report : DevExpress.XtraEditors.XtraForm
    {
        Sales_Profit_Report sale_profit_rpt;
        public Profit_Report()
        {
            InitializeComponent();
            sale_profit_rpt = null;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();
            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            sale_profit_rpt = new Sales_Profit_Report(-1, from_date_picker.Text, to_date_picker.Text, -1);
            sale_profit_rpt.RequestParameters = false;
            documentViewer1.DocumentSource = sale_profit_rpt;
            sale_profit_rpt.CreateDocument();
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            sale_profit_rpt = null;
            int store_id = -1;
            int item_id = -1;
            if (stores_cmb.Text != "")
            {
                store_id = Convert.ToInt32(stores_cmb.EditValue);
            }
            if(item_cmb.Text != "")
            {
                item_id= Convert.ToInt32(item_cmb.EditValue);
            }
            sale_profit_rpt = new Sales_Profit_Report(store_id, from_date_picker.Text, to_date_picker.Text,item_id);
            sale_profit_rpt.RequestParameters = false;
            documentViewer1.DocumentSource = sale_profit_rpt;
            sale_profit_rpt.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(sale_profit_rpt);
            print_tool.Print();

        }
    }
}