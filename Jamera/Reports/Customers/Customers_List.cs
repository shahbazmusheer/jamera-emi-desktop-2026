using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using System.IO;
using Jamera.Properties;
using DevExpress.XtraReports.UI;

namespace Jamera.Reports.Customers
{
    public partial class Customers_List : DevExpress.XtraEditors.XtraForm
    {
        Customers customers_report;
        public Customers_List()
        {
            InitializeComponent();
            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
            customers_report = new Customers(-1);
            customers_report.RequestParameters = false;
            documentViewer1.DocumentSource = customers_report;
            customers_report.CreateDocument();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            customers_report = null;
            if (store_cmb.Text == "")
            {
                customers_report = new Customers(-1);
            }
            else
            {
                customers_report = new Customers(Convert.ToInt32(store_cmb.EditValue));
            }
            customers_report.RequestParameters = false;
            documentViewer1.DocumentSource = customers_report;
            customers_report.CreateDocument();
        }

        private void print_report_btn_Click(object sender, EventArgs e)
        {
            ReportPrintTool print_tool = new ReportPrintTool(customers_report);
            print_tool.Print();
        }
    }
}