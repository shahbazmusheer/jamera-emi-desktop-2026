        private void store_cmb_EditValueChanged(object sender, EventArgs e)
        {
            if (store_cmb.Text != "")
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["customers_query"]);
                CustomSqlQuery customersQuery = new CustomSqlQuery();
                customersQuery.Sql = @"
                select stores.area_code as 'Area Code',accounts.id as 'Code', accounts.name as 'Name',       
                accounts.father_name as 'Father Name',accounts.id_card_no as 'CNIC',  
                accounts.phone as 'Office Phone', accounts.home_phone as 'Home Phone',accounts.balance as 'Balance'
                from (dbo.accounts accounts left join dbo.stores stores
                on (stores.id = accounts.store_id)) WHERE accounts.account_group_id='1002'
                and accounts.store_id = '" + Convert.ToInt32(store_cmb.EditValue) + "'";
                customersQuery.Name = "customers_query";
                sqlDataSource1.Queries.Add(customersQuery);

                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                customers_cmb.Refresh();
            }
        }

        private void load_report_Btn_Click_1(object sender, EventArgs e)
        {
            loadLateCustomersReport();
        }

        private void loadLateCustomersReport()
        {
            late_Customers = null;
            int store_id = -1;
            int customer_id = -1;
            DateTime date = DateTime.Now;
            int frequency = 3;

            if (date_picker.Text != "")
            {
                date = date_picker.DateTime;
            }

            if (store_cmb.Text != "")
            {
                store_id = Convert.ToInt32(store_cmb.EditValue);
            }

            if (customers_cmb.Text != "")
            {
                customer_id = Convert.ToInt32(customers_cmb.EditValue);
            }

            if (!string.IsNullOrEmpty(frequency_inp.Text))
            {
                frequency = Convert.ToInt32(frequency_inp.Text);
            }

            late_Customers = new Late_Customers(date, frequency, store_id, customer_id);

            late_Customers.RequestParameters = false;
            documentViewer1.DocumentSource = late_Customers;
            late_Customers.CreateDocument();
        }

