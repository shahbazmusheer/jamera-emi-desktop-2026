using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using System.IO;
using Jamera.Properties;

namespace Jamera.Reports.Salaries
{
    public partial class Employee_Wise_Salary : DevExpress.XtraEditors.XtraForm
    {
        Employee_Wise_Salary_Report employee_wise_salary_report;
        public Employee_Wise_Salary()
        {
            InitializeComponent();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            employee_wise_salary_report = null;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();

            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
            employee_wise_salary_report = new Employee_Wise_Salary_Report(from_date_picker.Text, to_date_picker.Text, -1);
            employee_wise_salary_report.RequestParameters = false;
            documentViewer1.DocumentSource = employee_wise_salary_report;
            employee_wise_salary_report.CreateDocument();
        }

        private void load_report_btn_Click(object sender, EventArgs e)
        {
            employee_wise_salary_report = null;
            if (employee_cmb.Text == "")
            {
                employee_wise_salary_report = new Employee_Wise_Salary_Report(from_date_picker.Text, to_date_picker.Text, -1);
            }
            else
            {
                employee_wise_salary_report = new Employee_Wise_Salary_Report(from_date_picker.Text, to_date_picker.Text, Convert.ToInt32(employee_cmb.EditValue));
            }
            employee_wise_salary_report.RequestParameters = false;
            documentViewer1.DocumentSource = employee_wise_salary_report;
            employee_wise_salary_report.CreateDocument();
        }
    }
}