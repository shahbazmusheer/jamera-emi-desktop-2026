        private void ref_no_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            double itemCount = 0;
            if (e.KeyChar == 13) // Enter Key
            {
                if (string.IsNullOrEmpty(ref_no_inp.Text))
                {
                    XtraMessageBox.Show("Please enter Ref.No of agreement!");
                    ref_no_inp.Focus();
                    return;
                }


                if (If_Ref_No_Exists_In_Cart(ref_no_inp.Text))
                {
                    XtraMessageBox.Show("Ref No already exists in current list.");
                    ref_no_inp.Focus();
                    return;
                }

                aggrement = aggrements_controller.Get_Aggrement_By_Ref_No(ref_no_inp.Text);

                if (aggrement.Aggrement_Id <= 0)
                {
                    XtraMessageBox.Show("Ref.No is not valid!");
                    ref_no_inp.Focus();
                    return;
                }
                else
                {
                    customers_cmb.EditValue = aggrement.Customer_Id;
                    // Balance logic anchor
                    customer_entry_current_balance = aggrement.Current_Balance;
                    remaining_balance_inp.Text = customer_entry_current_balance.ToString();

                    // Load Items in Items CMB
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_2"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT s_i.item_id as 'Code',items.name as 'Item',s_i.sale_rate as 'Sale Rate',s_i.sold_qty as 'Qty' from sale_items as s_i left join items on s_i.item_id=items.id left join aggrements as ag on s_i.agreement_id=ag.id  WHERE ag.ref_no='" + ref_no_inp.Text + "'";
                    query.Name = "Query_2";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                    items_cmb.Refresh();

                    // Load items for this specific agreement
                    DataTable agreementItems = aggrements_controller.Get_Aggrement_Items_Table(aggrement.Aggrement_Id);

                    if (agreementItems.Rows.Count > 1)
                    {
                        // Calculate real-time total quantity
                        double totalQty = agreementItems.Rows.Count;
                        itemCount = totalQty;
                        //foreach (DataRow row in agreementItems.Rows)
                        //    totalQty += Convert.ToDouble(row["Quantity"]);

                        items_cmb.EditValue = null;
                        items_cmb.Properties.NullText = $"Multiple ({totalQty})"; // Show 'Multiple (3)'
                        items_cmb.Tag = "MULTIPLE";
                    }
                    else if (agreementItems.Rows.Count == 1)
                    {
                        items_cmb.Properties.NullText = "";
                        items_cmb.EditValue = Convert.ToDecimal(agreementItems.Rows[0]["Code"]);
                        items_cmb.Tag = "SINGLE";
                        items_cmb.Focus();
                        itemCount = 1;
                    }

                    // Auto-populate Due Date and Amount from first unpaid installment
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["agreement_dues"]);
                    CustomSqlQuery dues_query = new CustomSqlQuery();

                    string dueDate = date_picker.Text != "" ? "__-"+ date_picker.Text.Split('-')[1] + "-" + date_picker.Text.Split('-')[2] : "%"; 
                    dues_query.Sql = @"SELECT id as 'Code',emi_date as 'Due Date',emi_amount as 'Due Amount' FROM aggrement_dues as ad WHERE ad.aggrement_id='"+aggrement.Aggrement_Id+"' AND ad.emi_date LIKE '"+dueDate+"' AND (ad.paid_amount <= 0 or (ad.balance > 0 AND ad.is_return_fixed < 1))";
                    dues_query.Name = "agreement_dues";
                    sqlDataSource1.Queries.Add(dues_query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                    //var dues = sqlDataSource1.Result["agreement_dues"].ToList();
                    //if (dues.Count > 0)
                    //{
                    //    due_date_picker.EditValue = dues[0]["emi_date"];
                    //    due_amt_inp.Text = dues[0]["emi_amount"].ToString();
                    //}
                    List<IRow> dues_list = sqlDataSource1.Result["agreement_dues"].ToList();
                    List<IRow> list = sqlDataSource1.Result["Query_2"].ToList();
                    if (dues_list.Count >= 1)
                    {
                        foreach (IRow row in dues_list)
                        {
                            due_date_picker.EditValue = row[0];
                            due_amt_inp.Text = row[2].ToString();
                            break;
                        }
                    }

                    recieved_amount_total_inp.Focus();
                }
            }
