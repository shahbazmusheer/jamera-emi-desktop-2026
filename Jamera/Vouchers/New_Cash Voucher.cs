        private void due_date_picker_EditValueChanged(object sender, EventArgs e)
        {
            if (due_date_picker.EditValue != null && due_date_picker.ContainsFocus)
            {
                // 1. Set the Due Amount dynamically based on the current plan (Return fixed logic)
                double currentEmiRate = v_controller.Get_Active_EMI_Amount(aggrement.Aggrement_Id);
                due_amt_inp.Text = currentEmiRate.ToString("0.00");

                // 2. Handle Date Auto-Generation
                if (due_date_picker.Text == "" || due_date_picker.Text == null)
                {
                    // Get the 'Day' from the last due date or start date
                    string lastDueDate = aggrement.Start_Date; // Default
                    if (agreement_duesBindingSource.Count > 0)
                    {
                        // Get the very last row's date
                        var lastRow = (agreement_duesBindingSource.List as DataView)[agreement_duesBindingSource.Count - 1];
                        lastDueDate = lastRow["Due Date"].ToString();
                    }

                    int day = DateTime.ParseExact(lastDueDate, "dd-MM-yyyy", null).Day;
                    DateTime generatedDate = new DateTime(date_picker.DateTime.Year, date_picker.DateTime.Month, day);

                    // If that date already passed in the current month, suggest next month
                    if (generatedDate < date_picker.DateTime) generatedDate = generatedDate.AddMonths(1);

                    due_date_picker.Text = generatedDate.ToString("dd-MM-yyyy");
                }
            }
        }

