        public void Set_Item_To_Cart()
        {
            try
            {
                // 1. Basic UI Validation
                if (store_cmb.EditValue == null)
                {
                    XtraMessageBox.Show("Please select a store!"); return;
                }
                if (string.IsNullOrEmpty(emi_serial_inp.Text))
                {
                    XtraMessageBox.Show("Please enter EMI Serial!"); return;
                }

                int currentSerial = Convert.ToInt32(emi_serial_inp.Text);
                int storeId = Convert.ToInt32(store_cmb.EditValue);
                DateTime vDate = date_picker.DateTime;

                // Validate EMI No
                if (helper_Class.IfEMINoExists(Convert.ToInt32(emi_serial_inp.Text), Convert.ToInt32(store_cmb.EditValue), date_picker.DateTime, true, cash_voucher_emi_items_table))
                {
                    return;
                }

                // --- STEP 4: PROCEED TO ADD ---
                double recAmt = 0; double.TryParse(recieved_amount_total_inp.Text, out recAmt);
                double dueAmt = 0; double.TryParse(due_amt_inp.Text, out dueAmt);

                if (recAmt <= 0) { XtraMessageBox.Show("Amount must be > 0"); return; }

                int item_code = -1;
                string item_name = items_cmb.Properties.NullText;
                if (items_cmb.Tag?.ToString() == "SINGLE")
                {
                    item_code = Convert.ToInt32(items_cmb.EditValue);
                    item_name = items_cmb.Text;
                }
                if (recAmt != dueAmt)
                {
                    // Open Over-payment Adjustment Form
                    Receipts_Adjustment form = new Receipts_Adjustment(storeId, store_cmb.Text, Convert.ToInt32(customers_cmb.EditValue), customers_cmb.Text, ref_no_inp.Text, date_picker.Text, due_date_picker.Text, dueAmt, customer_entry_current_balance,item_code, item_name);
                    form.reciepts_entry = this;
                    form.ShowDialog(this);
                }
                else
                {
                    // Standard Add to Cart
                    DataRow dr = cash_voucher_emi_items_table.NewRow();
                    dr["Code"] = Convert.ToInt32(due_date_picker.EditValue);
                    dr["Date"] = date_picker.Text;
                    dr["Ref.No"] = ref_no_inp.Text;
                    dr["EMI #"] = currentSerial;
                    dr["Customer Code"] = Convert.ToInt32(customers_cmb.EditValue);
                    dr["Customer"] = customers_cmb.Text;
                    dr["Due Date"] = due_date_picker.Text;
                    dr["Due Amount"] = due_amt_inp.Text;
                    dr["Recieved Amt"] = recAmt;
                    dr["Balance"] = Convert.ToDouble(remaining_balance_inp.Text);

                    if (items_cmb.Tag?.ToString() == "MULTIPLE")
                    {
                        dr["Item Code"] = -1;
                        dr["Item"] = items_cmb.Properties.NullText;
                    }
                    else
                    {
                        dr["Item Code"] = Convert.ToInt32(items_cmb.EditValue);
                        dr["Item"] = items_cmb.Text;
                    }

                    cash_voucher_emi_items_table.Rows.Add(dr);
                    Reset_Emi_Item_Entries();
                    Refresh_Final_Values();
                    
                    ref_no_inp.Focus();
                }
            }
            catch (Exception ex)
            {
                XtraMessageBox.Show("Error: " + ex.Message);
            }
        }

