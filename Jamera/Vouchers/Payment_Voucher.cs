        public void Reset_Fields()
        {
            payment_type_cmb.SelectedIndex = 0;
            account_cmb.Text = null;
            balance_inp.Text = "0.00";
            description_inp.Text = null;
            amount_inp.Text = null;
            Refresh_Lists();
            account_cmb.Focus();
        }

        public void Refresh_Lists()
        {
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            account_cmb.Update();
        }

        private void date_picker_EditValueChanged(object sender, EventArgs e)
        {
            
        }

        private void account_title_cmb_EditValueChanged(object sender, EventArgs e)
        {
            if (account_cmb.Text != "")
            {
                Double debit_ac_balance = Convert.ToDouble(account_cmb.Properties.View.GetFocusedRowCellValue("Balance"));
                balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(debit_ac_balance.ToString()));
            }
            else
            {
                balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(0.ToString()));
            }
        }

        private void description_inp_KeyDown(object sender, KeyEventArgs e)
        {
           
        }

        private void amount_inp_KeyPress(object sender, KeyPressEventArgs e)
        {

            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            if (e.KeyChar == 13)
            {
                if (amount_inp.Text == "" || amount_inp.Text == "0")
                {
                    XtraMessageBox.Show("Please enter the amount!");
                    amount_inp.Focus();
                }
                else
                {
                    Save();
                }
            }
        }

