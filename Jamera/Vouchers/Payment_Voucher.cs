        {
            
        }
        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(account_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select account !");
                account_cmb.ShowPopup();
            }else if(amount_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter amount !");
                amount_inp.Focus();
            }
            else
            {
                Vouchers_Controller vouchers_controller = new Vouchers_Controller();
                int voucher_id = vouchers_controller.Store_Payment_Voucher(Convert.ToDateTime(date_picker.Text), Convert.ToInt32(account_cmb.EditValue), account_cmb.Text, Convert.ToDouble(amount_inp.Text),description_inp.Text,payment_type_cmb.Text);
                if (voucher_id > 0)
                {
                    Reset_Fields();
                }
            }
        }
        private void save_btn_Click(object sender, EventArgs e)
        {
            this.Save();
        }

        private void account_cmb_EditValueChanged(object sender, EventArgs e)
        {
            GridView view = account_cmb.Properties.View;
            string fieldName = "Balance"; // or other field name  
            Double balance = Convert.ToDouble(view.GetRowCellValue(account_cmb.Properties.GetIndexByKeyValue(account_cmb.EditValue), fieldName));
            balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(balance.ToString()));
        }
