    public partial class Issue_EMI_Voucher : DevExpress.XtraEditors.XtraForm
    {
        public Issue_EMI_Voucher(DateTime date, int store_id = -1, int serial = -1)
        {
            InitializeComponent();
            date_picker.EditValue = Convert.ToDateTime("01-" + date.Month + "-" + date.Year).ToShortDateString();
            if(store_id > -1)
            {
                store_search_cmb.EditValue = store_id;
                start_serial.Focus();
            }

            if(serial > 0)
            {
                start_serial.Text = ((serial/100)*100+1).ToString();
                end_serial.Text = ((serial / 100) * 100 + 100).ToString();
                save_btn.Focus();
            }
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();

            string icon_path = Settings.Default.company_icon;
            string img_name = Settings.Default.db_name;
            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }

            sqlDataSource1.Fill();
        }
        public void Reset_Fields()
        {
            store_search_cmb.Text = null;
            start_serial.Text = null;
            end_serial.Text = null;
            description_inp.Text = null;
            Refresh_Lists();
            store_search_cmb.Focus();
        }

        public void Refresh_Lists()
        {
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            store_search_cmb.Update();
        }


        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(store_search_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select store !");
                store_search_cmb.ShowPopup();
            }else if(start_serial.Text == "")
            {
                XtraMessageBox.Show("Please enter start serial !");
                start_serial.Focus();
            }else if(end_serial.Text == "")
            {
                XtraMessageBox.Show("Please enter end serial !");
                end_serial.Focus();
            }
            else
            {
                Vouchers_Controller vouchers_controller = new Vouchers_Controller();
                int valid_start_serial = vouchers_controller.Get_Valid_Emi_Start_Serial();
                //if(valid_start_serial < Convert.ToInt32(start_serial.Text))
                //{
                    int emi_voucher_id= vouchers_controller.Store_EMI_Voucher(Convert.ToDateTime(date_picker.Text),Convert.ToInt32(store_search_cmb.EditValue),start_serial.Text,end_serial.Text,description_inp.Text);
                    if(emi_voucher_id > 0)
                    {
                        Reset_Fields();
                    }
                //}
            }
        }

        private void save_btn_Click(object sender, EventArgs e)
        {
            this.Save();
            this.Close();
        }

        private void cancel_btn_Click(object sender, EventArgs e)
        {
            //Reset_Fields();
            this.Close();
        }

        private void start_serial_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }
        }

        private void end_serial_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }
        }

        private void Issue_EMI_Voucher_Load(object sender, EventArgs e)
        {

        }

        private void Issue_EMI_Voucher_KeyDown(object sender, KeyEventArgs e)
        {
           
        }

        private void end_serial_KeyDown(object sender, KeyEventArgs e)
        {
            if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
                this.Close();
            }

            if (e.KeyCode == Keys.Escape)
            {
                this.Close();
            }
        }

        private void Issue_EMI_Voucher_Shown(object sender, EventArgs e)
        {
            if (end_serial.Text != "")
            {
                save_btn.Focus();
            }
        }
    }
