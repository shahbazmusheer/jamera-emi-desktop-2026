        private void total_messages_count_btn_Click(object sender, EventArgs e)
        {
            DataTable tmp_table = Contacts_Table.Copy();
            int deleted_entries_counter = 0;
            for (int i = 0; i < Contacts_Table.Rows.Count; i++)
            {
                if (!(gridView3.IsRowSelected(i) == true))
                {
                    int INDEX_TO_DEL = i - deleted_entries_counter;
                    tmp_table.Rows.RemoveAt(INDEX_TO_DEL);
                    deleted_entries_counter = deleted_entries_counter + 1;
                }
            }
            var office_phones_count = tmp_table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Office Phone") != "")
            .Count();
            var home_phones_count = tmp_table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Home Phone") != "")
            .Count();
            String Phone_Option = phones_options_cmb.Text;
            int total_phone_numbers_count = 0;
            if (Phone_Option == "Both")
            {
                total_phone_numbers_count = office_phones_count + home_phones_count;
            }
            else if (Phone_Option == "Office Phone")
            {
                total_phone_numbers_count = office_phones_count;
            }
            else if (Phone_Option == "Home Phone")
            {
                total_phone_numbers_count = home_phones_count;
            }
            total_phone_numbers_count = (total_phone_numbers_count * 2);
            XtraMessageBox.Show("Total messages count:"+ total_phone_numbers_count, "",MessageBoxButtons.OK,MessageBoxIcon.Information);
        }
