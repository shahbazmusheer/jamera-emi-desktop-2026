namespace Jamera.Vouchers
{
    public partial class EMI_Vouchers_History : DevExpress.XtraEditors.XtraUserControl
    {
        public EMI_Vouchers_History()
        {
            InitializeComponent();
            store_search_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void by_store_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_store_check.Checked)
            {
                store_search_cmb.Enabled = true;
            }
            else
            {
                store_search_cmb.Enabled = false;
                store_search_cmb.Text = null;
            }
        }
        public void Search_By_Store()
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = @"select emi_vouchers.date as 'Date',stores.name as 'Store Name',stores.area_code as 'Area Code',emi_vouchers.start_serial as 'Start Serial',emi_vouchers.end_serial as 'End Serial',emi_vouchers.description as 'Description'  from (dbo.emi_vouchers emi_vouchers  inner join dbo.stores stores  on (stores.id = emi_vouchers.store_id)) WHERE emi_vouchers.store_id='"+store_search_cmb.EditValue+"'  ORDER BY emi_vouchers.id DESC";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
        }
        public void Search_By_Store_And_Date()
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            String end_date = Convert.ToDateTime(to_date_picker.Text).AddDays(1).ToString("dd-MM-yyyy");
            query.Sql = @"select TOP 1000 emi_vouchers.date as 'Date',stores.name as 'Store Name',stores.area_code as 'Area Code',emi_vouchers.start_serial as 'Start Serial',emi_vouchers.end_serial as 'End Serial',emi_vouchers.description as 'Description'  from (dbo.emi_vouchers emi_vouchers  inner join dbo.stores stores  on (stores.id = emi_vouchers.store_id)) WHERE emi_vouchers.store_id='"+store_search_cmb.EditValue+"' and DATEADD(dd,0,DATEDIFF(dd,0,Convert(DATETIME,emi_vouchers.date,103))) >= DATEADD(dd,0,Convert(DATETIME,'"+from_date_picker.Text+"',103)) and DATEADD(dd,0,DATEDIFF(dd,0,Convert(DATETIME,emi_vouchers.date,103))) <= DATEADD(dd,0,Convert(DATETIME,'"+to_date_picker.Text+"',103)) ORDER BY emi_vouchers.id DESC;";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
        }
        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_date_check.Checked)
            {
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
            }
            else
            {
                from_date_picker.Enabled = false;
                to_date_picker.Enabled = false;
                from_date_picker.Text = null;
                to_date_picker.Text = null;
            }
        }

        private void create_new_btn_Click(object sender, EventArgs e)
        {
            Issue_EMI_Voucher form = new Issue_EMI_Voucher(DateTime.Now);
            form.ShowDialog(this);
        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            if (by_store_check.CheckState == CheckState.Checked && by_date_check.CheckState != CheckState.Checked)
            {
                if (store_search_cmb.Text == "")
                {
                    XtraMessageBox.Show("Please select store !");
                    store_search_cmb.ShowPopup();
                }
                else
                {
                    Search_By_Store();
                }
            }
            else if (by_store_check.CheckState == CheckState.Checked && by_date_check.CheckState == CheckState.Checked)
            {
                if (store_search_cmb.Text == "" && from_date_picker.Text == "" && to_date_picker.Text == "")
                {
                    XtraMessageBox.Show("please select store first then from date and to date !");
                    store_search_cmb.ShowPopup();
                }
                else if (store_search_cmb.Text == "")
                {
                    XtraMessageBox.Show("please select store !");
                    store_search_cmb.ShowPopup();
                }
                else if (from_date_picker.Text == "" && to_date_picker.Text == "")
                {
                    XtraMessageBox.Show("Please select from date and to date !");
                    from_date_picker.ShowPopup();
                }
                else if (from_date_picker.Text == "")
                {
                    XtraMessageBox.Show("Please select from date !");
                    from_date_picker.ShowPopup();
                }
                else if (to_date_picker.Text == "")
                {
                    XtraMessageBox.Show("Please select to date !");
                    to_date_picker.ShowPopup();
                }
                else
                {
                    Search_By_Store_And_Date();
                }
            }
        }

        private void refresh_btn_Click(object sender, EventArgs e)
        {
            by_date_check.Checked = false;
            by_store_check.Checked = false;
            store_search_cmb.Text = null;
            from_date_picker.Text = null;
            to_date_picker.Text = null;
            store_search_cmb.Enabled = false;
            from_date_picker.Enabled = false;
            to_date_picker.Enabled = false;
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = @"select TOP 1000 emi_vouchers.date as 'Date',stores.name as 'Store Name',stores.area_code as 'Area Code',emi_vouchers.start_serial as 'Start Serial',emi_vouchers.end_serial as 'End Serial',emi_vouchers.description as 'Description'  from (dbo.emi_vouchers emi_vouchers  inner join dbo.stores stores  on (stores.id = emi_vouchers.store_id)) ORDER BY emi_vouchers.id DESC";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
        }

        private void EMI_Vouchers_History_SizeChanged(object sender, EventArgs e)
        {
            store_search_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
        }
    }
