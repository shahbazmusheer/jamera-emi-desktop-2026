        private void by_store_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_store_check.Checked)
            {
                store_search_cmb.Enabled = true;
            }
            else
            {
                store_search_cmb.Enabled = false;
                store_search_cmb.Text = null;
            }
        }

        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_date_check.Checked)
            {
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
            }
            else
            {
                from_date_picker.Enabled = false;
                to_date_picker.Enabled = false;
                from_date_picker.Text = null;
                to_date_picker.Text = null;
            }
        }

        private void cash_voucher_id_inp_EditValueChanged(object sender, EventArgs e)
        {

        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            if(by_date_check.Checked == false && by_store_check.Checked == false)
            {
                if(cash_voucher_id_inp.Text == "")
                {
                    XtraMessageBox.Show("Please enter cah voucher code !");
                    cash_voucher_id_inp.Focus();
                }
                else
                {
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT cv.date as 'Date',cv.id as 'Code',stores.id as 'Store.Code',stores.name as 'Store',stores.area_code as 'Area Code',cv.field_worker as 'Field Worker',cv.area_name as 'Area Name',cv.vehicle_number as 'Vehicle No',cv.voucher_balance as 'Voucher Balance' FROM cash_vouchers as cv left join stores on cv.store_id=stores.id WHERE cv.id='"+cash_voucher_id_inp.Text+"'";
                    query.Name = "Query";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                }
            }else if(by_date_check.Checked == false && by_store_check.Checked == true)
            {
                if(store_search_cmb.Text == "")
                {
                    XtraMessageBox.Show("Please select store !");
                    store_search_cmb.ShowPopup();
                    store_search_cmb.Focus();
                }
                else
                {
                    //store id
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT cv.date as 'Date',cv.id as 'Code',stores.id as 'Store.Code',stores.name as 'Store',stores.area_code as 'Area Code',cv.field_worker as 'Field Worker',cv.area_name as 'Area Name',cv.vehicle_number as 'Vehicle No',cv.voucher_balance as 'Voucher Balance' FROM cash_vouchers as cv left join stores on cv.store_id=stores.id WHERE cv.store_id='"+Convert.ToInt32(store_search_cmb.EditValue)+"'";
                    query.Name = "Query";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                }
            }else if(by_date_check.Checked == true && by_store_check.Checked == true)
            {
                if (store_search_cmb.Text == "")
                {
                    XtraMessageBox.Show("Please select store !");
                    store_search_cmb.ShowPopup();
                    store_search_cmb.Focus();
                }else
                {
                    if(from_date_picker.Text == "")
                    {
                        XtraMessageBox.Show("Select from date !");
                        from_date_picker.Focus();
                    }else if(to_date_picker.Text == "")
                    {
                        XtraMessageBox.Show("Select to date !");
                        to_date_picker.Focus();
                    }
                    else
                    {
                        sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                        CustomSqlQuery query = new CustomSqlQuery();
                        query.Sql = @"SELECT cv.date as 'Date',cv.id as 'Code',stores.id as 'Store.Code',stores.name as 'Store',stores.area_code as 'Area Code',cv.field_worker as 'Field Worker',cv.area_name as 'Area Name',cv.vehicle_number as 'Vehicle No',cv.voucher_balance as 'Voucher Balance' FROM cash_vouchers as cv left join stores on cv.store_id=stores.id WHERE cv.store_id='" + Convert.ToInt32(store_search_cmb.EditValue) + "' and CONVERT(DATETIME,cv.date,103) >= CONVERT(DATETIME,'"+from_date_picker.Text+"',103) and CONVERT(DATETIME,cv.date,103) <= CONVERT(DATETIME,'"+to_date_picker.Text+"',103)";
                        query.Name = "Query";
                        sqlDataSource1.Queries.Add(query);
                        sqlDataSource1.RebuildResultSchema();
                        sqlDataSource1.Fill();
                    }
                }
            }
            else
            {
                if(from_date_picker.Text == "")
                    {
                    XtraMessageBox.Show("Select from date !");
                    from_date_picker.Focus();
                }else if (to_date_picker.Text == "")
                {
                    XtraMessageBox.Show("Select to date !");
                    to_date_picker.Focus();
                }
                else
                {
                    //search by date

                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT cv.date as 'Date',cv.id as 'Code',stores.id as 'Store.Code',stores.name as 'Store',stores.area_code as 'Area Code',cv.field_worker as 'Field Worker',cv.area_name as 'Area Name',cv.vehicle_number as 'Vehicle No',cv.voucher_balance as 'Voucher Balance' FROM cash_vouchers as cv left join stores on cv.store_id=stores.id WHERE CONVERT(DATETIME,cv.date,103) >= CONVERT(DATETIME,'" + from_date_picker.Text + "',103) and CONVERT(DATETIME,cv.date,103) <= CONVERT(DATETIME,'" + to_date_picker.Text + "',103)";
                    query.Name = "Query";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                }
            }
        }

