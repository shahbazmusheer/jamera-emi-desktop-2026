        public void Save()
        {
            if(debit_account_id.Text == "")
            {
                XtraMessageBox.Show("Please select debit account !");
            }else if (credit_account_id.Text == "")
            {
                XtraMessageBox.Show("Please select credit account !");
            }
            else if (Convert.ToInt32(debit_account_id.EditValue) == Convert.ToInt32(credit_account_id.EditValue))
            {
                XtraMessageBox.Show("Same account can not be use for transaction.Please select different accounts for debit and credit.");
            }
            else if (amount_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter amount for transaction !");
                amount_inp.Focus();
            }
            else if (Convert.ToDouble(amount_inp.Text) <= 0)
            {
                XtraMessageBox.Show("Please enter amount grater then zero !");
                amount_inp.Focus();
            }
            else
            {
                Vouchers.Vouchers_Controller vouchers_controller = new Vouchers_Controller();
                String ref_no = "";
                if(ref_no_inp.Text != "")
                {
                    ref_no = ref_no_inp.Text;
                }
                int voucher_id = vouchers_controller.Store_Journal_Voucher(Convert.ToDateTime(date_picker.Text), Convert.ToInt32(debit_account_id.EditValue), debit_account_id.Text, debit_description_inp.Text, Convert.ToInt32(credit_account_id.EditValue), credit_account_id.Text, credit_description_inp.Text, Convert.ToDouble(amount_inp.Text),ref_no);
                if (voucher_id > 0)
                {
                    Reset_Fields();
                }
            }
    }

