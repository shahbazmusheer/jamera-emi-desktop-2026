        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_date_check.Checked)
            {
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
            }
            else
            {
                from_date_picker.Enabled = false;
                to_date_picker.Enabled = false;
                from_date_picker.Text = null;
                to_date_picker.Text = null;
            }
        }

        private void account_search_check_CheckedChanged(object sender, EventArgs e)
        {
            if (account_search_check.Checked)
            {
                account_search_cmb.Enabled = true;
            }
            else
            {
                account_search_cmb.Enabled = false;
                account_search_cmb.Text = "";
            }
        }

        private void refresh_btn_Click(object sender, EventArgs e)
        {
            refresh_btn.Enabled = false;
            account_search_check.CheckState = CheckState.Unchecked;
            by_date_check.CheckState = CheckState.Unchecked;
            voucher_type_cmb.SelectedIndex = 0;
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_1"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = @"select top 1000 vouchers.id  as 'Code',vouchers.ref_no as 'Ref.No',CONVERT(VARCHAR,vouchers.issue_date,106) as 'Issue Date',vouchers.voucher_type as 'TYPE',vouchers.debit_account_id as 'Debit Code',vouchers.debit_account_name as 'Debit Account',vouchers.credit_account_id as 'Credit Code',vouchers.credit_account_name as 'Credit Account',vouchers.debit_description as 'Debit Description',vouchers.credit_description as 'Credit Description',vouchers.amount as 'Amount'  from dbo.vouchers vouchers;";
            query.Name = "Query_1";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            refresh_btn.Enabled = true;
        }

