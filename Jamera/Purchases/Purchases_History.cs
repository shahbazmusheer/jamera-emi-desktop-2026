        private void gridView1_GroupLevelStyle(object sender, DevExpress.XtraGrid.Views.Grid.GroupLevelStyleEventArgs e)
        {
            switch (e.Level)
            {
                case 0:
                    e.LevelAppearance.Options.UseBackColor = true;
                    e.LevelAppearance.BackColor2 = Color.FromArgb(0, 153, 204);
                    e.LevelAppearance.ForeColor = Color.White;
                    e.LevelAppearance.BackColor = Color.FromArgb(0, 34, 204);
                    break;
                case 1:
                    e.LevelAppearance.Options.UseBackColor = true;
                    e.LevelAppearance.BackColor = Color.FromArgb(221, 0, 221);
                    e.LevelAppearance.ForeColor = Color.White;
                    e.LevelAppearance.BackColor2 = Color.FromArgb(255, 153, 102);
                    break;
                case 2:
                    e.LevelAppearance.Options.UseBackColor = true;
                    e.LevelAppearance.ForeColor = Color.White;
                    e.LevelAppearance.BackColor = Color.FromArgb(0, 102, 102);
                    e.LevelAppearance.BackColor2 = Color.FromArgb(0, 255, 255);
                    break;
                    //default:
                    //    //do nothing  
                    //break;

            }
        }

        private void gridView1_CustomDrawGroupRow(object sender, DevExpress.XtraGrid.Views.Base.RowObjectCustomDrawEventArgs e)
        {
            GridGroupRowInfo info = e.Info as GridGroupRowInfo;
            // DevExpress.XtraGrid.Views.Grid.ViewInfo.GridGroupRowInfo myinfo = e.Info as DevExpress.XtraGrid.Views.Grid.ViewInfo.GridGroupRowInfo;
            if (info == null) return;

            if(info.Level == 0)
            {
                // We use 'Max' summary because Paid/Total is the same for all items in one bill
                double total = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[0]));
                double paid = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[1]));
                double balance = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[2]));
                double items_qty = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[3]));

                string supplier = (info.EditValue).ToString();
                info.GroupText = $"Supplier: {supplier}  [Items Qty: {items_qty}]  [Total = {total:#,##0}]  [Paid: {paid:#,##0}]  [Balance: {balance:#,##0}]";
                
            }

            // Only apply to the Date level (Level 1)
            if (info.Level == 1)
            {
                // We use 'Max' summary because Paid/Total is the same for all items in one bill
                double total = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[0]));
                double paid = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[1]));
                double balance = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[2]));
                double items_qty = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[3]));

                string date = Convert.ToDateTime(info.EditValue).ToString("dd-MM-yyyy");

                info.GroupText = $"Date: {date}  [Items Qty: {items_qty}]  [Total = {total:#,##0}]  [Paid: {paid:#,##0}]  [Balance: {balance:#,##0}]";
            }

            if (info.Level == 2)
            {
                // We use 'Max' summary because Paid/Total is the same for all items in one bill
                double total = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[0]));
                double paid = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[1]));
                double balance = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[2]));
                double items_qty = Convert.ToDouble(gridView1.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView1.GroupSummary[3]));

                int childRowHandle = gridView1.GetChildRowHandle(e.RowHandle, 0);
                string mode = gridView1.GetRowCellValue(childRowHandle, "Mode").ToString();
                string invoice_no = gridView1.GetRowCellValue(childRowHandle, "Invoice No")?.ToString() ?? "";
                string remarks = "[Remarks: " + gridView1.GetRowCellValue(childRowHandle, "Remarks")?.ToString() + "]   " ?? "";

                info.GroupText = $"{remarks}[Invoice: {invoice_no}]  [Mode: {mode}] [Items Qty: {items_qty}]  [Total = {total:#,##0}]  [Paid: {paid:#,##0}]  [Balance: {balance:#,##0}]";
            }


            purch_no_of_rec_lbl.Text = gridView1.DataRowCount.ToString();
        }

