        private void ConfigureGridGrouping()
        {
            gridView1.BeginUpdate();
            gridView1.Columns["Supplier"].GroupIndex = 0;
            gridView1.Columns["Date"].GroupIndex = 1;

            // Clear and set hidden summaries used for the header calculation
            gridView1.GroupSummary.Clear();
            gridView1.GroupSummary.Add(DevExpress.Data.SummaryItemType.Max, "Total", null, "");
            gridView1.GroupSummary.Add(DevExpress.Data.SummaryItemType.Max, "Paid", null, "");
            gridView1.GroupSummary.Add(DevExpress.Data.SummaryItemType.Max, "Balance", null, "");
            gridView1.GroupSummary.Add(DevExpress.Data.SummaryItemType.Sum, "Qty", null, "");

            gridView1.OptionsView.GroupFooterShowMode = GroupFooterShowMode.Hidden;
            gridView1.EndUpdate();

            purch_no_of_rec_lbl.Text = gridView1.DataRowCount.ToString();
        }


