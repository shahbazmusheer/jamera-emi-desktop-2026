        public void Update_Purchases_List()
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Name = "Query";
            // Using the Raw SQL provided above
            query.Sql = @"SELECT suppliers.name AS 'Supplier', p.date AS 'Date', p.payment_method AS 'Mode', p.id AS 'Code', p.invoice_no AS 'Invoice No', p.total_amount AS 'Total', p.paid AS 'Paid', p.remaining AS 'Balance', p.remarks AS 'Remarks', itm.id AS 'Item Code', itm.name AS 'Item', models.name AS 'Model', p_i.quantity AS 'Qty', p_i.returned_quantity AS 'Returned', p_i.items_stock_out as 'Stock Out', p_i.purchase_rate AS 'Purch Rate', p_i.discount_percent as 'Discount(%)', p_i.discount_rs as 'Discount(R.S)', p_i.sale_rate AS 'Sale Rate', p_i.net_total AS 'Item Total', p.status AS 'Status'
                  FROM dbo.purchase_items p_i 
                  INNER JOIN dbo.purchases p ON p_i.purchase_id = p.id 
                  INNER JOIN dbo.accounts suppliers ON p.supplier_id = suppliers.id 
                  INNER JOIN dbo.items itm ON p_i.item_id = itm.id 
                  LEFT JOIN dbo.item_models models ON itm.model_id = models.id 
                  ORDER BY p.date DESC";

            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.Fill();
            ConfigureGridGrouping();
        }
