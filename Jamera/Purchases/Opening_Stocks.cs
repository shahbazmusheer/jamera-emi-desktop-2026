        private void packing_qty_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            int dot_counter = packing_qty_inp.Text.Count(f => f == '.');

            if ((packing_qty_inp.Text.Length <= 0 && ch == 46) || (dot_counter > 0 && ch == 46))
            {
                e.Handled = true;
            }

            if (ch == MoveToNextControl_KeyValue)
