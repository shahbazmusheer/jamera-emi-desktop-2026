        public bool If_Item_Exists_In_Cart(int item_id)
        {
            if (gridView1.DataRowCount > 0)
            {
                bool check_exists = false;

                for (int i = 0; i < gridView1.DataRowCount; i++)
                {
                    if (Convert.ToInt32(gridView1.GetRowCellValue(i, gridView1.Columns[0])) == item_id && Convert.ToString(gridView1.GetRowCellValue(i, gridView1.Columns["Mode"])) == payment_type_cmb.Text)
                    {
                        check_exists = true;
                        break;
                    }
                }
                return check_exists;
            }
            else
            {
                return false;
            }
        }
        public void Save()
        {
            if (search_item_cmb.EditValue.ToString() != "")
            {

                if (MessageBox.Show("You have not added one item to cart ! \n Do you want to remove that item from cart !", "Alert", MessageBoxButtons.YesNo) == DialogResult.Yes)
                {
                    Reset_Item_Entries();
                }
                else
                {
                    packing_qty_inp.Focus();
                }
            }
            else if (!(cart_items_table.Rows.Count > 0))
            {
                XtraMessageBox.Show("Please enter purchases data !");
                search_item_cmb.Focus();
            }
            else if (supplier_cmb.EditValue.ToString() == "")
            {
                XtraMessageBox.Show("Please select supplier !");
                supplier_cmb.Focus();
            }
            else
            {
                Purchases_Controller purchases_controller = new Purchases_Controller();
                int purchase_id = -1;
                Double whole_disc_percent = 0;
                Double whole_disc_rs = 0;
                purchase_id = purchases_controller.Store(Convert.ToDateTime(date_picker.Text), "Opening", "Opening", Convert.ToInt32(supplier_cmb.EditValue), cart_items_table, "Opening Entiries", (Convert.ToDouble(total_top_lbl.Text) + Convert.ToDouble(total_balance_inp.Text)), whole_disc_percent, whole_disc_rs, (Convert.ToDouble(total_top_lbl.Text) + Convert.ToDouble(total_balance_inp.Text)), null,0,true,Convert.ToDouble(total_balance_inp.Text));

                if (purchase_id > 0)
                    {
                        Reset_Fields();
                        search_item_cmb.ShowPopup();
                    }
                }
            }
        
        public void Add_Item_To_Cart()
        {
            DataRow dr = cart_items_table.NewRow();
            dr["Code"] = Convert.ToInt32(search_item_cmb.EditValue);
            dr["Item"] = search_item_cmb.Text;
            dr["Packing Qty"] = Convert.ToDouble(packing_qty_inp.Text);
            dr["Unit Qty"] = Convert.ToDouble(unit_qty_inp.Text);
            dr["Purchase Rate"] = Convert.ToDouble(purch_rate_inp.Text);
            dr["Unit Cost"] = Convert.ToDouble(unit_cost_inp.Text);
            dr["Sale Rate"] = Convert.ToDouble(sale_rate_inp.Text);
            dr["Balance"] = Convert.ToDouble(item_balance_inp.Text);
            dr["Mode"] = payment_type_cmb.Text;
            dr["Total"] = Convert.ToDouble(item_total_inp.Text);
            cart_items_table.Rows.Add(dr);
            Reset_Item_Entries();
            Set_Final_Values();
            search_item_cmb.ShowPopup();
        }
        public void Set_Final_Values()
        {

            GridSummaryItem summery_item = gridView1.Columns["Total"].SummaryItem;
            summery_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double sub_totals = Convert.ToDouble(summery_item.SummaryValue);
            total_top_lbl.Text = string.Format("{0:#,##0.00}", Double.Parse(sub_totals.ToString()));
            GridSummaryItem blc_summery_item = gridView1.Columns["Balance"].SummaryItem;
            blc_summery_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double total_balance = Convert.ToDouble(blc_summery_item.SummaryValue);
            total_balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(total_balance.ToString()));
        }
        public void Set_Item_To_Cart()
        {
            if (If_Item_Exists_In_Cart(Convert.ToInt32(search_item_cmb.EditValue)) == true)
            {
                XtraMessageBox.Show("Item already exists in cart !");
                Reset_Item_Entries();
                search_item_cmb.ShowPopup();
            }
            else
            {
                Add_Item_To_Cart();
            }
        }
