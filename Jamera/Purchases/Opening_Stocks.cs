        private void gridView1_KeyDown(object sender, KeyEventArgs e)
        {
            if (e.KeyCode == Keys.Delete)
            {
                gridView1.DeleteRow(gridView1.FocusedRowHandle);
                if (gridView1.DataRowCount > 0)
                {
                    Set_Final_Values();
                }
                else
                {
                    Reset_Fields();
                }
            }

            if (e.Control && e.KeyCode == Keys.E)
            {
                if (gridView1.DataRowCount > 0)
                {
                    Int32 curr_id = Convert.ToInt32(gridView1.GetFocusedRowCellValue("Code"));
                    search_item_cmb.EditValue = curr_id;
                    packing_qty_inp.Text = gridView1.GetFocusedRowCellValue("Packing Qty").ToString();
                    unit_qty_inp.Text = gridView1.GetFocusedRowCellValue("Unit Qty").ToString();
                    purch_rate_inp.Text = gridView1.GetFocusedRowCellValue("Purchase Rate").ToString();
                    sale_rate_inp.Text = Convert.ToString(gridView1.GetFocusedRowCellValue("Sale Rate"));
                    unit_cost_inp.Text = Convert.ToString(gridView1.GetFocusedRowCellValue("Unit Cost"));
                    payment_type_cmb.Text = Convert.ToString(gridView1.GetFocusedRowCellValue("Mode"));
                    item_balance_inp.Text = Convert.ToString(gridView1.GetFocusedRowCellValue("Balance"));
                    item_total_inp.Text = Convert.ToString(gridView1.GetFocusedRowCellValue("Total"));
                    int row_ind = gridView1.GetFocusedDataSourceRowIndex();
                    gridView1.DeleteRow(row_ind);
                    if (gridView1.DataRowCount > 0)
                    {
                        Set_Final_Values();
                    }
                    else
                    {
                        Set_Final_Values();
                    }

                    packing_qty_inp.Focus();
                }
            }

        }

