        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_date_check.Checked)
            {
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
            }
            else
            {
                from_date_picker.Enabled = false;
                to_date_picker.Enabled = false;
                from_date_picker.Text = null;
                to_date_picker.Text = null;
            }
        }

        private void by_supplier_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_supplier_check.Checked)
            {
                supplier_search_cmb.Enabled = true;
            }
            else
            {
                supplier_search_cmb.Enabled = false;
                supplier_search_cmb.Text = "";
            }
        }

        private void refresh_btn_Click(object sender, EventArgs e)
        {
            invoice_no_inp.Text = "";
            by_supplier_check.CheckState = CheckState.Unchecked;
            by_date_check.CheckState = CheckState.Unchecked;
            this.Update_Purchases_Return_List();
        }
        public void Update_Purchases_Return_List()
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = @"Select TOP 1000 purchases_return.id as 'Code',purchases_return.date as 'Date',accounts.name as 'Supplier',purchases_return.purchase_type as 'Purchase Type',purchases_return.payment_method as 'Mode',purchases_return.discount_percent as 'Disc(%)',purchases_return.discount_rs as 'Disc(R.S)',purchases_return.invoice_no as 'Invoice No',purchases_return.status as 'Status',purchases_return.total_amount as 'Net Total'  from (dbo.purchases_return purchases_return   left  join dbo.accounts accounts       on (accounts.id = purchases_return.supplier_id)) ORDER BY purchases_return.id DESC ";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
        }
        private void search_btn_Click(object sender, EventArgs e)
        {
            if (invoice_no_inp.Text == "" && by_supplier_check.CheckState != CheckState.Checked && by_date_check.CheckState != CheckState.Checked)
            {
                XtraMessageBox.Show("Please enter invoice number !");
                invoice_no_inp.Focus();
            }
            else if (invoice_no_inp.Text != "" && by_supplier_check.CheckState != CheckState.Checked && by_date_check.CheckState != CheckState.Checked)
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Sql = @"Select purchases.id as 'Code',purchases.date as 'Date',accounts.name as 'Supplier',purchases.purchase_type as 'Purchase Type',purchases.payment_method as 'Mode',purchases.discount_percent as 'Disc(%)',purchases.discount_rs as 'Disc(R.S)',purchases.invoice_no as 'Invoice No',purchases.status as 'Status',purchases.total_amount as 'Net Total'  from (dbo.purchases_return purchases   left  join dbo.accounts accounts       on (accounts.id = purchases.supplier_id)) WHERE purchases.invoice_no='" + invoice_no_inp.Text + "' ORDER BY purchases.id DESC ";
                query.Name = "Query";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
            }
            else if (supplier_search_cmb.Text == "" && by_supplier_check.CheckState == CheckState.Checked && by_date_check.CheckState != CheckState.Checked)
            {
                XtraMessageBox.Show("Please select supplier !");
                supplier_search_cmb.Focus();
            }
            else if (supplier_search_cmb.Text != "" && by_supplier_check.CheckState == CheckState.Checked && by_date_check.CheckState != CheckState.Checked)
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Sql = @"Select purchases.id as 'Code',purchases.date as 'Date',accounts.name as 'Supplier',purchases.purchase_type as 'Purchase Type',purchases.payment_method as 'Mode',purchases.discount_percent as 'Disc(%)',purchases.discount_rs as 'Disc(R.S)',purchases.invoice_no as 'Invoice No',purchases.status as 'Status',purchases.total_amount as 'Net Total'  from (dbo.purchases_return purchases   left  join dbo.accounts accounts       on (accounts.id = purchases.supplier_id)) WHERE purchases.supplier_id='" + supplier_search_cmb.EditValue.ToString() + "' ORDER BY purchases.id DESC ";
                query.Name = "Query";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
            }
            else if ((from_date_picker.Text == "" || to_date_picker.Text == "") && by_supplier_check.CheckState != CheckState.Checked && by_date_check.CheckState == CheckState.Checked)
            {
                XtraMessageBox.Show("Please select from date and to date !");
            }
            else if ((from_date_picker.Text != "" || to_date_picker.Text != "") && by_supplier_check.CheckState != CheckState.Checked && by_date_check.CheckState == CheckState.Checked)
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                String end_date = Convert.ToDateTime(to_date_picker.Text).AddDays(1).ToString("dd-MM-yyyy");
                query.Sql = @"Select purchases.id as 'Code',purchases.date as 'Date',accounts.name as 'Supplier',purchases.purchase_type as 'Purchase Type',purchases.payment_method as 'Mode',purchases.discount_percent as 'Disc(%)',purchases.discount_rs as 'Disc(R.S)',purchases.invoice_no as 'Invoice No',purchases.status as 'Status',purchases.total_amount as 'Net Total'  from (dbo.purchases_return purchases   left  join dbo.accounts accounts       on (accounts.id = purchases.supplier_id)) WHERE purchases.date >= CONVERT(DATETIME,'" + from_date_picker.Text + "',103) and purchases.date < CONVERT(DATETIME,'" + end_date + "',103) ORDER BY purchases.id DESC ";
                query.Name = "Query";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
            }
            else if ((from_date_picker.Text != "" || to_date_picker.Text != "") && by_supplier_check.CheckState == CheckState.Checked && by_date_check.CheckState == CheckState.Checked && supplier_search_cmb.Text != "")
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                String end_date = Convert.ToDateTime(to_date_picker.Text).AddDays(1).ToString("dd-MM-yyyy");
                query.Sql = @"Select purchases.id as 'Code',purchases.date as 'Date',accounts.name as 'Supplier',purchases.purchase_type as 'Purchase Type',purchases.payment_method as 'Mode',purchases.discount_percent as 'Disc(%)',purchases.discount_rs as 'Disc(R.S)',purchases.invoice_no as 'Invoice No',purchases.status as 'Status',purchases.total_amount as 'Net Total'  from (dbo.purchases_return purchases   left  join dbo.accounts accounts       on (accounts.id = purchases.supplier_id)) WHERE purchases.date >=CONVERT(DATETIME,'" + from_date_picker.Text + "',103) and purchases.date < CONVERT(DATETIME,'" + end_date + "',103) and supplier_id='" + supplier_search_cmb.EditValue.ToString() + "' ORDER BY purchases.id DESC ";
                query.Name = "Query";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
            }
        }

        private void gridView1_DoubleClick(object sender, EventArgs e)
        {
            if (gridView1.DataRowCount > 0)
            {
                Purchase purchase = new Purchase();
                purchase.Purchase_ID = Convert.ToInt32(gridView1.GetFocusedRowCellValue(gridView1.Columns["Code"]));
                purchase.Invoice_No = Convert.ToString(gridView1.GetFocusedRowCellValue(gridView1.Columns["Invoice No"]));
                purchase.Supplier_Name = Convert.ToString(gridView1.GetFocusedRowCellValue(gridView1.Columns["Supplier"]));
                purchase.Purchase_Type = Convert.ToString(gridView1.GetFocusedRowCellValue(gridView1.Columns["Purchase Type"]));
                purchase.Payment_Method = Convert.ToString(gridView1.GetFocusedRowCellValue(gridView1.Columns["Mode"]));
                purchase.Status = Convert.ToString(gridView1.GetFocusedRowCellValue(gridView1.Columns["Status"]));
                purchase.Purchase_Date = Convert.ToDateTime(gridView1.GetFocusedRowCellValue(gridView1.Columns["Date"])); ;
                purchase.Total_Discount_Percent = Convert.ToDouble(gridView1.GetFocusedRowCellValue(gridView1.Columns["Disc(%)"]));
                purchase.Total_Discount_RS = Convert.ToDouble(gridView1.GetFocusedRowCellValue(gridView1.Columns["Disc(R.S)"]));
                purchase.Net_Total = Convert.ToDouble(gridView1.GetFocusedRowCellValue(gridView1.Columns["Net Total"]));
                Purchase_Return_Details purchases_return_details = new Purchase_Return_Details(purchase);
                purchases_return_details.Show();
            }
        }

