        public void Controls_List(object sender, KeyEventArgs e)
        {
            if(e.KeyCode == Keys.Escape)
            {
                if (purchases_right_panel.CanFocus== true)
                {
                    purchases_right_panel.HideSliding();
                    gridView1.Focus();
                }
                else if (returns_right_panel.CanFocus == true)
                {
                    returns_right_panel.HideSliding();
                    gridView1.Focus();
                }
                else if(gridView1.DataRowCount > 0 || search_item_cmb.Text != "" || supplier_cmb.Text != "")
                {
                    if (XtraMessageBox.Show("Are you sure, You want to cancel the purchase !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                    {
                        Reset_Fields();
                    }
                }
            }
            else if(e.KeyCode == Keys.F1)
            {
                gridView1.Focus();
            }
            else if ((e.KeyCode == Keys.F5) || (e.Control && e.KeyCode == Keys.R))
            {
                this.Enabled = false;
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                supplier_cmb.Update();
                supplier_cmb.Refresh();
                search_item_cmb.Update();
                list.Update();
                gridControl1.Update();
                search_item_cmb.Refresh();
                this.Enabled = true;
                gridView1.Focus();
            }
            else if (e.KeyCode == Keys.F6 || (e.Control && e.KeyCode == Keys.N))
            {
                UC_Opener_Form form = new UC_Opener_Form("New Purchase", new Purchases.New_Purchase());
                form.Show(this);
            }
            else if (e.KeyCode == Keys.F7)
            {
                payment_cmb.Focus();
                payment_cmb.ShowPopup();
            }
            else if (e.KeyCode == Keys.F8)
            {
                purchase_type_cmb.Focus();
                purchase_type_cmb.ShowPopup();
            }
            else if (e.KeyCode == Keys.F9)
            {
                search_item_cmb.Focus();
                search_item_cmb.ShowPopup();
            }
            else if (e.KeyCode == Keys.F10)
            {
                supplier_cmb.Focus();
                supplier_cmb.ShowPopup();
            }
            else if (e.KeyCode == Keys.F11)
            {
                purchases_right_panel.Focus();
                purchases_right_panel.ShowSliding();
            }
            else if (e.KeyCode == Keys.F12)
            {
                returns_right_panel.Focus();
                returns_right_panel.ShowSliding();
            }
            else if (e.Control && e.Shift && e.KeyCode == Keys.I)
            {
                Items.New_Item new_item = new Items.New_Item();
                new_item.new_purchase = this;
                new_item.Update_Purchase_Items_List = true;
                UC_Opener_Form add_item_form = new UC_Opener_Form("Add Item", new_item);
                new_item.us_opener = add_item_form;
                add_item_form.Show();
            }
            else if (e.Control && e.Shift && e.KeyCode == Keys.S)
            {
                Accounts.New_Account new_account = new Accounts.New_Account();
                new_account.new_purchase = this;
                new_account.Update_Purchase_Accounts_List = true;
                new_account.group_cmb.ReadOnly = true;
                new_account.group_cmb.EditValue = 1001;
                UC_Opener_Form form = new UC_Opener_Form("Add Supplier", new_account);
                new_account.us_opener = form;
                form.Show();
            }
            else if(e.Control && e.KeyCode == Keys.I)
            {
                invoice_no_inp.Focus();
            }
            else if (e.Control && e.KeyCode == Keys.T)
            {
                whole_disc_perc_inp.Focus();
            }
            else if (e.Control && e.KeyCode == Keys.W)
            {
                remarks_inp.Focus();
            }
            else if (e.Control && e.KeyCode == Keys.P)
            {
                save_print = true;
                Save();
            }
            else if (e.Control && e.KeyCode == Keys.S)
            {
                Save();
            }

        }

