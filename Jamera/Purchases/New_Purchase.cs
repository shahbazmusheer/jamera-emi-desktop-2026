        public void setEvaluatedValues()
        {
            if (packing_qty_inp.Text != "" && purch_rate_inp.Text != "" && item_disc_rs_inp.Text != "" && item_disc_perc_inp.Text != "" )
            {
                var qty = Convert.ToDouble(packing_qty_inp.Text);
                var purchase_rate_val = Convert.ToDouble(purch_rate_inp.Text);
                single_changed_temp_total = (qty * purchase_rate_val);
                Double discount_value = Convert.ToDouble(item_disc_rs_inp.Text);
                unit_qty_inp.Text = (item_packing_size * qty).ToString();
                unit_cost_inp.Text = (Convert.ToDouble(purch_rate_inp.Text) / item_packing_size).ToString();

                if (discount_value >= 0)
                {
                    if (discount_value > 0)
                    {
                        item_disc_perc_inp.Text = Math.Round(((discount_value / single_changed_temp_total) * 100), 2).ToString();
                    }
                    single_changed_temp_total = single_changed_temp_total - discount_value;
                }

                item_total_inp.Text = single_changed_temp_total.ToString();
            }
        }
        public void Set_Final_Values()
        {
            
            GridSummaryItem summery_item= gridView1.Columns["Total"].SummaryItem;
            summery_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double sub_totals = Convert.ToDouble(summery_item.SummaryValue);
            sub_total_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(sub_totals.ToString()));

            GridSummaryItem summery_item_qty = gridView1.Columns["Unit Qty"].SummaryItem;
            summery_item_qty.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double total_qty = Convert.ToDouble(summery_item_qty.SummaryValue);
            total_qty_lbl.Text = string.Format("{0:#,##0.00}", Double.Parse(total_qty.ToString()));
            no_of_items_lbl.Text = cart_items_table.Rows.Count.ToString();

            Double total_discount_val = 0;
            Double paid_amount_val = 0;
            Double return_amount_val = 0;
            Double value_after_disc = 0;
            if (whole_disc_rs_inp.Text != "")
            {
                total_discount_val = Convert.ToDouble(whole_disc_rs_inp.Text);
                whole_disc_perc_inp.Text = Math.Round(((total_discount_val / sub_totals) * 100), 2).ToString();
            }

            if (paid_amount_inp.Text != "")
            {
                paid_amount_val = Convert.ToDouble(paid_amount_inp.Text);
            }
            value_after_disc = sub_totals - total_discount_val;
            Double value_after_expences = 0;
            if(fuel_expenses_inp.Text != "")
            {
                value_after_expences = Convert.ToDouble(fuel_expenses_inp.Text);
            }
            value_after_expences = value_after_disc + value_after_expences;
            total_top_lbl.Text=net_total_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(value_after_expences.ToString()));
            if (paid_amount_val > 0)
            {
                return_amount_val = value_after_expences - paid_amount_val;
                if (return_amount_val > 0)
                {
                    change_amount_inp.BackColor = Color.Green;
                }
                else if (return_amount_val < 0)
                {
                    change_amount_inp.BackColor = Color.Red;
                }
                else
                {
                    change_amount_inp.BackColor = SystemColors.Control;
                }
                change_amount_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(return_amount_val.ToString()));
            }
            else
            {
                change_amount_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(value_after_expences.ToString()));
            }

        }
