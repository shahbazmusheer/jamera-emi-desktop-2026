        public void Edit_Values()
        {
            Double basic_salary = 0;
            Double bonus = 0;
            Double commission = 0;

            Double advance_paid = 0;
            Double other_deductions = 0;
            Double net_salary = 0;
            if(basic_salary_inp.Text != "")
            {
                basic_salary = Convert.ToDouble(basic_salary_inp.Text);
            }
            if (bonus_inp.Text != "")
            {
                bonus = Convert.ToDouble(bonus_inp.Text);
            }
            if (commission_inp.Text != "")
            {
                commission = Convert.ToDouble(commission_inp.Text);
            }
            if (advance_payment_inp.Text != "")
            {
                advance_paid = Convert.ToDouble(advance_payment_inp.Text);
            }
            if (other_deductions_inp.Text != "")
            {
                other_deductions = Convert.ToDouble(other_deductions_inp.Text);
            }
            net_salary = (basic_salary + bonus + commission) - (advance_paid + other_deductions);
            net_salary_inp.Text = net_salary.ToString();
        }

