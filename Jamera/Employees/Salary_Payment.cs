        public void Send_Message_To_Numbers(int store_id, String Group_Name, String Message_Type, string Message_Text, String SMS_Gateway, String Phone_Option, int Employee_Code, String Employee_Name, String Home_Phone, String Office_Phone, Double Basic_Sallary, Double Bonus, Double Commission, Double Advance_PAid, Double Other_Desuctions, Double Net_Salary)
        {
            bool is_home_phone_selected = false;
            bool is_office_phone_selected = false;
            if (Phone_Option == "Both")
            {
                is_home_phone_selected = true;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Office Phone")
            {
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Home Phone")
            {
                is_home_phone_selected = true;
            }
            Messages.Message message = new Messages.Message();
            message.ACCOUNT_ID = Employee_Code;
            message.Store_Id = store_id;
            message.Message_Type = Message_Type;
            message.Group = Group_Name;
            message.SMS_Gateway = SMS_Gateway;
            string raw_msg = "Dear [Name],\nAap ki Basic Sallary Rs.[BASIC_SALLARY] hy.";
            var message_text_name_replace = raw_msg.Replace("[Name]", Employee_Name);
            var message_text_basic_sallary_replace = message_text_name_replace.Replace("[BASIC_SALLARY]", Convert.ToInt32(Basic_Sallary).ToString());

            // If bonus is given then
            if (Bonus > 0)
            {
                message_text_basic_sallary_replace = message_text_basic_sallary_replace + "Aap ko Rs.[BONUS] bonus dya gyaa hy.";
                message_text_basic_sallary_replace = message_text_basic_sallary_replace.Replace("[BONUS]", Convert.ToInt32(Bonus).ToString());
            }
            if (Commission > 0)
            {
                message_text_basic_sallary_replace = message_text_basic_sallary_replace + "Aap ko Rs.[COMMISSION] commission dya gyaa hy.";
                message_text_basic_sallary_replace = message_text_basic_sallary_replace.Replace("[COMMISSION]", Convert.ToInt32(Commission).ToString());
            }
            if (Advance_PAid > 0)
            {
                message_text_basic_sallary_replace = message_text_basic_sallary_replace + " Rs.[ADVANCE_PAID] advance ki mad main kaat liye gaye hyn.";
                message_text_basic_sallary_replace = message_text_basic_sallary_replace.Replace("[ADVANCE_PAID]", Convert.ToInt32(Advance_PAid).ToString());
            }
            if (Other_Desuctions > 0)
            {
                message_text_basic_sallary_replace = message_text_basic_sallary_replace + " Rs.[OTHER_DEDUCTIONS] Other Deductions ki mad main kaat liye gaye hyn.";
                message_text_basic_sallary_replace = message_text_basic_sallary_replace.Replace("[OTHER_DEDUCTIONS]", Convert.ToInt32(Other_Desuctions).ToString());
            }
            message_text_basic_sallary_replace = message_text_basic_sallary_replace + "Aap ki Net Sallary Rs.[NET_SALLARY] banti hy.Jo k aapko cash main adaa ki jaa chuki hy.";
            var final_replaced_message_text = message_text_basic_sallary_replace.Replace("[NET_SALLARY]", Convert.ToInt32(Net_Salary).ToString());
            if (is_office_phone_selected == true && Office_Phone != null && Office_Phone != "")
            {
                //Send Message to office phone
                Console.WriteLine("Send to numbers() =>  Office Phone" + Office_Phone);
                message.Message_Text = final_replaced_message_text;
                message.RECIEVER_NUMBER = Office_Phone;
                goto send_message_start;
            send_message_start:
                int is_sent = -1;
                is_sent = messages_controller.Send_Message(message);
                if (is_sent == 1)
                {
                    message.Status = "Sent";
                    Console.WriteLine("Message sent susscessfuly !");
                }
                else if (is_sent == -3)
                {
                    Thread.Sleep(2000);
                    goto send_message_start;
                }
                else
                {
                    message.Status = "Draft";
                    Console.WriteLine("Message Drafted !");
                }
                messages_controller.Store_Message(message);
                Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
            }
            if (is_home_phone_selected == true && Home_Phone != null && Home_Phone != "")
            {
                Console.WriteLine("Send to numbers() =>  Home Phone" + Home_Phone);
                message.Message_Text = final_replaced_message_text;
                message.RECIEVER_NUMBER = Home_Phone;
                goto send_message_start;
            send_message_start:
                int is_sent = -1;
                is_sent = messages_controller.Send_Message(message);
                if (is_sent == 1)
                {
                    message.Status = "Sent";
                    Console.WriteLine("Message sent susscessfuly !");
                }
                else if (is_sent == -3)
                {
                    Thread.Sleep(2000);
                    goto send_message_start;
                }
                else
                {
                    message.Status = "Draft";
                    Console.WriteLine("Message Drafted !");
                }
                messages_controller.Store_Message(message);
                Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
            }
            SMS_Thread.Abort();
        }
