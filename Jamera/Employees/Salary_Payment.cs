        public void Save()
        {
            if(employee_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select employee !");
                employee_cmb.ShowPopup();
            }else if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(net_salary_inp.Text == "")
            {
                XtraMessageBox.Show("Please calculate net salary !");
                bonus_inp.Focus();
            }else if(Convert.ToInt32(net_salary_inp.Text) <= 0)
            {
                XtraMessageBox.Show("Net salary is not enough for transaction !");
                bonus_inp.Focus();
            }
            else
            {
                Double basic_salary = 0;
                Double bonus = 0;
                Double commission = 0;
                Double advance_paid = 0;
                Double other_deductions = 0;
                Double net_salary = 0;
                if (basic_salary_inp.Text != "")
                {
                    basic_salary = Convert.ToDouble(basic_salary_inp.Text);
                }
                if (bonus_inp.Text != "")
                {
                    bonus = Convert.ToDouble(bonus_inp.Text);
                }
                if (commission_inp.Text != "")
                {
                    commission = Convert.ToDouble(commission_inp.Text);
                }
                if (advance_payment_inp.Text != "")
                {
                    advance_paid = Convert.ToDouble(advance_payment_inp.Text);
                }
                if (other_deductions_inp.Text != "")
                {
                    other_deductions = Convert.ToDouble(other_deductions_inp.Text);
                }
                net_salary = Convert.ToDouble(net_salary_inp.Text);
                Employees_Controller employees_controller = new Employees_Controller();
                int serial_no= employees_controller.Pay_Salary(Convert.ToInt32(employee_cmb.EditValue),employee_cmb.Text,Convert.ToDateTime(date_picker.Text),basic_salary,bonus,commission,advance_paid,other_deductions,net_salary,description_inp.Text);
                if(serial_no > 0)
                {
                    if (send_msg_chkbx.CheckState == CheckState.Checked)
                    {
                        int store_id = -1;
                        int account_id = -1;
                        Double Net_Sallary = Convert.ToDouble(net_salary_inp.Text);
                        String emp_name = employee_cmb.Text;
                        account_id = Convert.ToInt32(employee_cmb.EditValue);
                        String Group_Name = "Employees";
                        String Message_Type = null;
                        String Message_Text = null;
                        String SMS_Gateway = null;
                        String Phone_Options = "Both";
                        String Office_Phone = accounts_controller.Get_Office_Phone(account_id);
                        String Home_Phone = accounts_controller.Get_Home_Phone(account_id);
                        Console.WriteLine("Save() => Office Phone"+Office_Phone);
                        Console.WriteLine("Save() => Home Phone" + Home_Phone);
                        if (sms_gateway_cmb.Text != "")
                        {
                            SMS_Gateway = sms_gateway_cmb.Text;
                        }
                        Message_Text = message_inp.Text;
                        Message_Type = messages_type_cmb.Text;
                        SMS_Thread = new Thread(() => Send_Message_To_Numbers(store_id, Group_Name, Message_Type, Message_Text, SMS_Gateway, Phone_Options, account_id, emp_name, Home_Phone, Office_Phone, basic_salary,bonus,commission,advance_paid,other_deductions,net_salary));
                        SMS_Thread.Start();
                    }
                    Reset_Fields();
                }

            }
        }
