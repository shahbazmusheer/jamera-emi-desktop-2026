        public void Send_Message_To_Numbers(int store_id, String Group_Name, String Message_Type, string Message_Text, String SMS_Gateway, String Phone_Option,int Employee_Code,String Employee_Name,String Home_Phone,String Office_Phone,Double Paid_Amount)
        {
            bool is_home_phone_selected = false;
            bool is_office_phone_selected = false;
            if (Phone_Option == "Both")
            {
                is_home_phone_selected = true;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Office Phone")
            {
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Home Phone")
            {
                is_home_phone_selected = true;
            }
            if (is_office_phone_selected == true && Office_Phone != null && Office_Phone != "")
            {
                //Send Message to office phone
                Messages.Message message = new Messages.Message();
                message.ACCOUNT_ID = Employee_Code;
                message.Store_Id = store_id;
                string raw_msg= Message_Text;
                var message_text_name_replace = raw_msg.Replace("[Name]",Employee_Name);
                var message_text_paid_amount_replace = message_text_name_replace.Replace("[PAID_AMOUNT]",Convert.ToInt32(Paid_Amount).ToString());
                message.Message_Text = message_text_paid_amount_replace;
                message.Message_Type = Message_Type;
                message.Group = Group_Name;
                message.SMS_Gateway = SMS_Gateway;
                message.RECIEVER_NUMBER = Office_Phone;
                goto send_message_start;
            send_message_start:
                int is_sent = -1;
                is_sent = messages_controller.Send_Message(message);
                if (is_sent == 1)
                {
                    message.Status = "Sent";
                    Console.WriteLine("Message sent susscessfuly !");
                }
                else if (is_sent == -3)
                {
                    Thread.Sleep(2000);
                    goto send_message_start;
                }
                else
                {
                    message.Status = "Draft";
                    Console.WriteLine("Message Drafted !");
                }
                messages_controller.Store_Message(message);
                Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
            }
            if (is_home_phone_selected == true && Home_Phone != null && Home_Phone != "")
            {
                //Send Message to home phone
                Messages.Message message = new Messages.Message();
                message.ACCOUNT_ID = Employee_Code;
                message.Store_Id = store_id;
                message.Message_Text = Message_Text;
                message.Message_Type = Message_Type;
                message.Group = Group_Name;
                message.SMS_Gateway = SMS_Gateway;
                message.RECIEVER_NUMBER = Home_Phone;
                goto send_message_start;
            send_message_start:
                int is_sent = -1;
                is_sent = messages_controller.Send_Message(message);
                if (is_sent == 1)
                {
                    message.Status = "Sent";
                    Console.WriteLine("Message sent susscessfuly !");
                }
                else if (is_sent == -3)
                {
                    Thread.Sleep(2000);
                    goto send_message_start;
                }
                else
                {
                    message.Status = "Draft";
                    Console.WriteLine("Message Drafted !");
                }
                messages_controller.Store_Message(message);
                Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
            }
            SMS_Thread.Abort();
        }
        public void Reset_Fields()
        {
            employee_cmb.Text = null;
            amount_inp.Text = null;
            description_inp.Text = null;
        }
        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(employee_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select employee !");
                employee_cmb.ShowPopup();
            }else if(amount_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter amount !");
                amount_inp.Focus();
            }
            else
            {
                Double amount = Convert.ToDouble(amount_inp.Text);
                if(amount > 0)
                {

                    Double advance_limit = -1;
                    Double advance_paid = 0;
                    if(employee_cmb.Properties.View.GetFocusedRowCellValue("Advance Limit") != DBNull.Value)
                    {
                        advance_limit = Convert.ToDouble(employee_cmb.Properties.View.GetFocusedRowCellValue("Advance Limit"));
                    }
                    if (employee_cmb.Properties.View.GetFocusedRowCellValue("Advance Paid") != DBNull.Value)
                    {
                        advance_paid = Convert.ToDouble(employee_cmb.Properties.View.GetFocusedRowCellValue("Advance Paid"));
                    }
                    if(advance_limit < (advance_paid + amount) && advance_limit != -1)
                    {
                        XtraMessageBox.Show("You can not pay more then advance limit !");
                        amount_inp.Focus();
                    }
                    else
                    {
                        Accounts.Accounts_Controller accounts_controller = new Accounts.Accounts_Controller();
                        Accounts.Account cash_account= new Accounts.Account();
                        cash_account = accounts_controller.Get_Account(2001);
                        Accounts.Account employee_account = new Accounts.Account();
                        employee_account = accounts_controller.Get_Account(Convert.ToInt32(employee_cmb.EditValue));
                        Double Advance_Amount = 0;
                        Advance_Amount = Convert.ToDouble(amount_inp.Text);
                        //credit cash account
                        accounts_controller.Insert_Account_Transaction(cash_account.Account_Id,cash_account.Account_Name,cash_account.Account_Type,cash_account.Account_Nature,"Advance Payment",description_inp.Text,0,0,0,Advance_Amount,(cash_account.Balance - Advance_Amount),Convert.ToDateTime(date_picker.EditValue));

                        //Debit Employee Account
                        accounts_controller.Insert_Account_Transaction(employee_account.Account_Id,employee_account.Account_Name,employee_account.Account_Type,employee_account.Account_Nature,"Advance Payment",description_inp.Text,0,0,Advance_Amount,0,(employee_account.Balance + Advance_Amount),Convert.ToDateTime(date_picker.EditValue));
                        if (send_msg_chkbx.CheckState == CheckState.Checked)
                        {
                            int store_id = -1;
                            int account_id = -1;
                            Double paid_amt = Convert.ToDouble(amount_inp.Text);
                            String emp_name = employee_cmb.Text;
                            account_id=Convert.ToInt32(employee_cmb.EditValue);
                            String Group_Name = "Employees";
                            String Message_Type = null;
                            String Message_Text = null;
                            String SMS_Gateway = null;
                            String Phone_Options = "Both";
                            String Office_Phone = accounts_controller.Get_Office_Phone(account_id);
                            String Home_Phone = accounts_controller.Get_Home_Phone(account_id);
                            if (sms_gateway_cmb.Text != "")
                            {
                                SMS_Gateway = sms_gateway_cmb.Text;
                            }
                            Message_Text = message_inp.Text;
                            Message_Type = messages_type_cmb.Text;
                            SMS_Thread = new Thread(() => Send_Message_To_Numbers(store_id, Group_Name, Message_Type, Message_Text, SMS_Gateway, Phone_Options,account_id,emp_name,Home_Phone,Office_Phone, paid_amt));
                            SMS_Thread.Start();
                        }
                        Reset_Fields();
                    }
                }
                else
                {
                    XtraMessageBox.Show("Please enter amount greater then zero !");
                    amount_inp.Focus();
                }
            }
        }
