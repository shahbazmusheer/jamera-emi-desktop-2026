using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Drawing;
using System.Data;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;
using DevExpress.DataAccess.Sql;

namespace Jamera.Employees
{
    public partial class Payment_History : DevExpress.XtraEditors.XtraUserControl
    {
        //String Message_Title = "Error Alert";
        public Payment_History()
        {
            InitializeComponent();
            employee_search_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if(by_date_check.Checked == false)
            {
                from_date_picker.Text = null;
                to_date_picker.Text = null;
                from_date_picker.Enabled = false;
                to_date_picker.Enabled = false;
            }
            else
            {
                from_date_picker.Text = null;
                to_date_picker.Text = null;
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
                employee_check.Checked = false;
                employee_search_cmb.Enabled = false;
                employee_search_cmb.Text = null;
            }
        }

        private void employee_check_CheckedChanged(object sender, EventArgs e)
        {
            if (employee_check.Checked)
            {
                employee_search_cmb.Enabled = true;
                employee_search_cmb.Text = "";
                by_date_check.Checked = false;
            }
            else
            {
                employee_search_cmb.Text = "";
                employee_search_cmb.Enabled = false;
            }
        }

        private void refresh_btn_Click(object sender, EventArgs e)
        {
            by_date_check.CheckState = CheckState.Unchecked;
            employee_check.CheckState = CheckState.Unchecked;
            employee_search_cmb.Text = null;
            from_date_picker.Text = null;
            to_date_picker.Text = null;
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = @"SELECT TOP 1000 e_s.pay_date as 'Paid Date',ac.id as 'Emp.Code',ac.name as 'Emp.Name',e_s.basic_salary'Basic Salary',e_s.bonus as 'Bonus',e_s.commission as 'Commission',e_s.advance_payment as 'Advance Payment',e_s.other_deductions as 'Other Duductons',e_s.net_salary as 'Net Salary',e_s.remarks as 'Remarks' FROM employees_salaries e_s left join accounts as ac on e_s.account_id=ac.id";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            if(by_date_check.Checked == true)
            {
                if(from_date_picker.Text == "" || to_date_picker.Text == "")
                {
                    XtraMessageBox.Show("Please select from date and to date properly !");
                }
                else
                {
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT e_s.pay_date as 'Paid Date',ac.id as 'Emp.Code',ac.name as 'Emp.Name',e_s.basic_salary'Basic Salary',e_s.bonus as 'Bonus',e_s.commission as 'Commission',e_s.advance_payment as 'Advance Payment',e_s.other_deductions as 'Other Duductons',e_s.net_salary as 'Net Salary',e_s.remarks as 'Remarks' FROM employees_salaries e_s left join accounts as ac on e_s.account_id=ac.id WHERE CONVERT(DATETIME,e_s.pay_date,103) >= CONVERT(DATETIME,'"+from_date_picker.Text+"',103) AND CONVERT(DATETIME,e_s.pay_date,103) <= CONVERT(DATETIME,'"+to_date_picker.Text+"',103)";
                    query.Name = "Query";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                }
            }
            
            if(employee_check.Checked == true)
            {
                if(employee_search_cmb.Text == "")
                {
                    XtraMessageBox.Show("Please select employee !");
                    employee_search_cmb.ShowPopup();
                    employee_search_cmb.Focus();
                }
                else
                {
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT e_s.pay_date as 'Paid Date',ac.id as 'Emp.Code',ac.name as 'Emp.Name',e_s.basic_salary'Basic Salary',e_s.bonus as 'Bonus',e_s.commission as 'Commission',e_s.advance_payment as 'Advance Payment',e_s.other_deductions as 'Other Duductons',e_s.net_salary as 'Net Salary',e_s.remarks as 'Remarks' FROM employees_salaries e_s left join accounts as ac on e_s.account_id=ac.id WHERE ac.id='"+Convert.ToInt32(employee_search_cmb.EditValue)+"'";
                    query.Name = "Query";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                }
            }
        }

        private void Payment_History_SizeChanged(object sender, EventArgs e)
        {

            employee_search_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
        }
    }
}
