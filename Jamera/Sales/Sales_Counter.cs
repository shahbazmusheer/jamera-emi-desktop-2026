        private void gridView1_KeyDown(object sender, KeyEventArgs e)
        {
            if(e.Control && e.KeyCode == Keys.D)
            {
                gridView1.CloseEditor();
                gridView1.UpdateCurrentRow();
                date_picker.Focus();
            }

            if (e.KeyCode == Keys.Enter)
            {
                // 1. Force the grid to save the value currently being typed
                gridView1.CloseEditor();
                gridView1.UpdateCurrentRow();

                if(end_date_picker.Text == "" || date_picker.Text == "")
                {
                    XtraMessageBox.Show("Select sale dates first.");
                    return;
                }

                // 2. Get the Qty from the focused row
                object qtyObj = gridView1.GetFocusedRowCellValue("Qty");

                if (qtyObj != null && qtyObj != DBNull.Value)
                {
                    int addedQty = Convert.ToInt32(qtyObj);

                    // Only proceed if quantity is valid
                    //if (addedQty <= 0) return;

                    int rowIndex = gridView1.FocusedRowHandle;
                    object itemCode = gridView1.GetFocusedRowCellValue("Code");
                    string itemName = gridView1.GetFocusedRowCellValue("Name").ToString();
                    string selectedDate = date_picker.DateTime.ToShortDateString();

                    // 3. SEARCH: Check if this item already exists in the target table for this date
                    // We search by Code and Date
                    DataRow[] existingRows = dateWiseSalesCountTable.Select($"Code = {itemCode} AND Date = '{selectedDate}'");

                    if (existingRows.Length > 0)
                    {
                        // PRODUCT EXISTS: Update existing quantity
                        int currentQty = Convert.ToInt32(existingRows[0]["Qty"]);
                        int updatedQty = currentQty + addedQty;
                        if (updatedQty > 0)
                        {
                            existingRows[0]["Qty"] = updatedQty;
                        }
                        else
                        {
                            existingRows[0].Delete();
                        }
                    }
                    else
                    {
                        // NEW PRODUCT: Add a new row to the cart
                        DataRow row = dateWiseSalesCountTable.NewRow();
                        row["Code"] = itemCode;
                        row["Date"] = selectedDate;
                        row["Name"] = itemName;
                        row["Qty"] = addedQty;
                        dateWiseSalesCountTable.Rows.Add(row);
                    }


                    // 3. SEARCH: Check if this item already exists in the target table for this date
                    // We search by Code and Date

                    selectedDate = end_date_picker.DateTime.ToShortDateString();
                    DataRow[] existingRowsinMonthly = monthlySalesCountTable.Select($"Code = {itemCode} AND Date = '{selectedDate}'");

                    if (existingRowsinMonthly.Length > 0)
                    {
                        // PRODUCT EXISTS: Update existing quantity
                        int currentQty = Convert.ToInt32(existingRowsinMonthly[0]["Qty"]);
                        int updatedQty = currentQty + addedQty;
                        if (updatedQty > 0)
                        {
                            existingRowsinMonthly[0]["Qty"] = updatedQty;
                        }
                        else
                        {
                            existingRowsinMonthly[0].Delete();
                        }
                    }
                    else
                    {
                        // NEW PRODUCT: Add a new row to the cart
                        DataRow row = monthlySalesCountTable.NewRow();
                        row["Code"] = itemCode;
                        row["Date"] = selectedDate;
                        row["Name"] = itemName;
                        row["Qty"] = addedQty;
                        monthlySalesCountTable.Rows.Add(row);
                    }

                    entry_status_label.Text = "Status: Inserted Sale Count ("+addedQty+" - "+ itemName +"  -  "+date_picker.DateTime.ToShortDateString()+")";


                    // 4. Reset the Main Grid Qty back to 1 (as per your requirement)
                    gridView1.SetRowCellValue(rowIndex, "Qty", 1);

                    // 5. Optional: Mark event as handled so focus doesn't jump to the next row immediately
                    e.Handled = true;
                }
            }
        }

