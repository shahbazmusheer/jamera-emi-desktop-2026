                if (XtraMessageBox.Show("Do you want to update the date for all items in the monthly list?", "Confirm Update", MessageBoxButtons.YesNo, MessageBoxIcon.Question) == DialogResult.Yes)
                {
                    // Get the new date string
                    string newDate = end_date_picker.DateTime.ToShortDateString();

                    // Correct C# foreach syntax for DataTable Rows
                    foreach (DataRow row in monthlySalesCountTable.Rows)
                    {
                        // Ensure the column name "Date" matches your DataTable definition (case-sensitive)
                        row["Date"] = newDate;
                    }

