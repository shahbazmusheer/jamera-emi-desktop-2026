        private void Print_Report()
        {
            // 1. Validation
            if (store_cmb.EditValue == null || store_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select a store first!", "Error", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            // 2. Decide which table to print
            DataTable tableToPrint;
            string reportTitle;

            if (filter_cmb.SelectedIndex == 0)
            {
                tableToPrint = monthlySalesCountTable;
                reportTitle = "Monthly Sales Count";
            }
            else
            {
                tableToPrint = dateWiseSalesCountTable;
                reportTitle = "Date Wise Sales Count";
            }

            if (tableToPrint.Rows.Count == 0)
            {
                XtraMessageBox.Show("No data available to print!", "Empty", MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            // 3. Initialize and Show Report
            try
            {
                Sales_Count_Report report = new Sales_Count_Report(tableToPrint, store_cmb.Text, reportTitle);
                ReportPrintTool printTool = new ReportPrintTool(report);
                printTool.ShowPreviewDialog();
            }
            catch (Exception ex)
            {
                XtraMessageBox.Show("Error generating report: " + ex.Message);
            }
        }

