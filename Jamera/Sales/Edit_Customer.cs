        private void id_card_1_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8))
            {
                e.Handled = true;
            }

            int digits_counter = id_card_1_inp.Text.Length;
            if (digits_counter == 5 && ch != 8)
            {
                e.Handled = true;
            }
            if (digits_counter == 4 && ch != 8)
            {
                id_card_2_inp.Focus();
            }
        }

