        public void Load_Data()
        {
            Accounts.Account customer= accounts_controller.Get_Customer(customer_id);
            name_inp.Text = customer.Account_Name;
            father_name_inp.Text = customer.Father_Name;
            if(customer.Age != -1)
            {
                age_inp.Text = customer.Age.ToString();
            }
            store_cmb.EditValue= Convert.ToDecimal(customer.Store_Id);
            cost_inp.Text = customer.Cast;
            profession_inp.Text = customer.Profession;
            var id_card_no = customer.Id_Card_No;
            if(id_card_no != "")
            {
                string id_card_01 = id_card_no.Split('-')[0];
                string id_card_02 = id_card_no.Split('-')[1];
                string id_card_03 = id_card_no.Split('-')[2];
                id_card_1_inp.Text = id_card_01;
                id_card_2_inp.Text = id_card_02;
                id_card_3_inp.Text = id_card_03;
            }
            business_address_inp.Text = customer.Office_Address;
            home_address_inp.Text = customer.Home_Address;
            permanent_address_inp.Text = customer.Permanent_Address;
            office_phone_inp.Text = customer.Office_Phone;
            home_phone_inp.Text = customer.Home_Phone;
            description_inp.Text = customer.Account_Remarks;
            current_balance_inp.Text = customer.Balance.ToString();
        }
        public void Update()
        {
            if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter customer name !");
                name_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_1_inp.Text.Length != 5))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_1_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_2_inp.Text.Length != 7))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_2_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_3_inp.Text.Length != 1))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_3_inp.Focus();
            }
            else
            {
                Accounts.Accounts_Controller accounts_controller = new Accounts.Accounts_Controller();
                int age = -1;
                if (age_inp.Text != "")
                {
                    age = Convert.ToInt32(age_inp.Text);
                }
                String id_card_no_val = id_card_1_inp.Text + "-" + id_card_2_inp.Text + "-" + id_card_3_inp.Text;
                int store_id = -1;
                if(store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }
                if (accounts_controller.Id_Card_Exists(this.customer_id,id_card_no_val, 1002, store_id) != true)
                {
                    bool inserted_record_id = accounts_controller.Update(customer_id,name_inp.Text, null, 1002, "Customers ( Debitors )","DR",office_phone_inp.Text,permanent_address_inp.Text, description_inp.Text,Convert.ToInt32(store_cmb.EditValue), father_name_inp.Text, age, cost_inp.Text, profession_inp.Text, id_card_no_val, business_address_inp.Text, home_address_inp.Text, home_phone_inp.Text);
                    if(inserted_record_id == true)
                    {
                        if (this.Do_Selection == true)
                        {
                            
                            new_aggreement.Save_Customer_Callback(Convert.ToInt32(inserted_record_id));
                            this.uc_opener.Close();
                        }
                    }
                }
                  else
                {
                    XtraMessageBox.Show("Another customer already exists with same ID Card No. !");
                }
            }
        }
        private void update_btn_Click(object sender, EventArgs e)
