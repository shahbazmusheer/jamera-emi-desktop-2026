        private void id_card_3_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8))
            {
                e.Handled = true;
            }
            int digits_counter = id_card_3_inp.Text.Length;
            if(id_card_3_inp.Text.Length == 0 && ch == 8)
            {
                id_card_2_inp.Focus();
            }
            if(digits_counter == 1 && ch != 8)
            {
                e.Handled = true;
            }
            if (digits_counter == 1 && ch != 8)
            {
                String id_card_no_val = id_card_1_inp.Text + "-" + id_card_2_inp.Text + "-" + id_card_3_inp.Text;
                int store_id = -1;
                if (store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }
                int existing_customer_id = accounts_controller.Get_Existing_Account_Id_By_IDCard(id_card_no_val, 1002, store_id);
                int existing_guarrantor_id = accounts_controller.Get_Existing_Account_Id_By_IDCard(id_card_no_val, 1010, store_id);
                if (existing_customer_id > -1)
                {
                    if(XtraMessageBox.Show("Customer already exists with this ID Card No. Do you want to select it!", "Duplicate Entry!", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) == DialogResult.Yes)
                    {
                        new_aggreement.Save_Customer_Callback(existing_customer_id);
                        this.us_opener.Close();
                    }
                }
                else if (existing_guarrantor_id > -1)
                {
                    // Customer Exists
                    if (XtraMessageBox.Show("A Guarrantor already exists with this ID Card No. Do you want to load its details!", "CNIC Already Exists!", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) == DialogResult.Yes)
                    {
                        Account customer = accounts_controller.Get_Full_Account_Details(existing_guarrantor_id);
                        setDetails(customer, "CNIC_Existing");
                    }
                }
                name_inp.Focus();
                
            }
        }

        private void office_phone_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            TextEdit phone_inp = office_phone_inp;
            phone_inp.Properties.MaxLength = 13;
            Char ch = e.KeyChar;

            if (!char.IsDigit(ch) && ch != 13 && ch != 8 && ch != 127 && ch != 45 && ch != 43)
            {
                e.Handled = true;
            }
            if (phone_inp.Text.StartsWith("+92", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                Regex r = new Regex(@"\d{6}\-\d{7}");
                phone_inp.Properties.MaxLength = 14;
            }
            else if (phone_inp.Text.StartsWith("+92", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 13;
            }
            else if (phone_inp.Text.StartsWith("03", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                Regex r = new Regex(@"\d{4}\-\d{7}");
                phone_inp.Properties.MaxLength = 12;
            }
            else if (phone_inp.Text.StartsWith("03", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 11;
            }
            else if (phone_inp.Text.StartsWith("92", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                phone_inp.Properties.MaxLength = 13;
            }
            else if (phone_inp.Text.StartsWith("92", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 12;
            }

        }

