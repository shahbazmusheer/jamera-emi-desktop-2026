                    id_card_3_inp.Text = id_card_03;
                }
                business_address_inp.Text = guardian.Office_Address;
                home_address_inp.Text = guardian.Home_Address;
                permanent_address_inp.Text = guardian.Permanent_Address;
                office_phone_inp.Text = guardian.Office_Phone;
                home_phone_inp.Text = guardian.Home_Phone;
            }
            else
            {
                if (Settings.Default.load_prev_acc_name) name_inp.Text = guardian.Account_Name;
                if (Settings.Default.load_prev_acc_father_name) father_name_inp.Text = guardian.Father_Name;
                if (guardian.Age != -1 && Settings.Default.load_prev_acc_age)
                {
                    age_inp.Text = guardian.Age.ToString();
                }
                //store_cmb.EditValue = Convert.ToDecimal(guardian.Store_Id);
                if (Settings.Default.load_prev_acc_cast) cost_inp.Text = guardian.Cast;
                if (Settings.Default.load_prev_acc_profession) profession_inp.Text = guardian.Profession;
                var id_card_no = guardian.Id_Card_No;
                if (id_card_no != "" && Settings.Default.load_prev_acc_cnic)
                {
                    string id_card_01 = id_card_no.Split('-')[0];
                    string id_card_02 = id_card_no.Split('-')[1];
                    string id_card_03 = id_card_no.Split('-')[2];
                    id_card_1_inp.Text = id_card_01;
                    id_card_2_inp.Text = id_card_02;
                    id_card_3_inp.Text = id_card_03;
                }
                if (Settings.Default.load_prev_acc_business_address) business_address_inp.Text = guardian.Office_Address;
