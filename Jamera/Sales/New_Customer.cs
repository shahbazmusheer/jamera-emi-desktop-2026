        public void Save()
        {
            if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter customer name !");
                name_inp.Focus();
            }
            else if ((id_card_1_inp.Text !="" &&id_card_2_inp.Text != ""&&id_card_3_inp.Text != "") && (id_card_1_inp.Text.Length != 5))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_1_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_2_inp.Text.Length != 7))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_2_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_3_inp.Text.Length != 1))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_3_inp.Focus();
            }else if(store_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select a specific store!");
                store_cmb.Focus();
                store_cmb.ShowPopup();
            }
            else
            {
                
                int age = -1;
                if (age_inp.Text != "")
                {
                    age = Convert.ToInt32(age_inp.Text);
                }
                String customer_name = name_inp.Text;
                int store_id = -1;
                if (store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }
                String id_card_no_val = id_card_1_inp.Text + "-" + id_card_2_inp.Text + "-" + id_card_3_inp.Text;
                
                if (accounts_controller.Id_Card_Exists(id_card_no_val, 1002, store_id) != true)
                {
                    String ac_type = "DR";
                    int Group_Id = 1002;
                    String Group_Name = "Customers ( Debitors )";

                    int inserted_record_id = accounts_controller.Store(customer_name, null, Group_Id, Group_Name, ac_type, office_phone_inp.Text, permanent_address_inp.Text, description_inp.Text, 0, store_id, father_name_inp.Text, age, cost_inp.Text, profession_inp.Text, id_card_no_val, business_address_inp.Text, home_address_inp.Text, home_phone_inp.Text);
                    if (inserted_record_id > 0)
                    {
                        if (this.Do_Selection == true)
                        {
                            new_aggreement.Save_Customer_Callback(inserted_record_id);
                            this.us_opener.Close();
                        }
                        if (this.opening_sales == true)
                        {
                            Opening_Sales.sqlDataSource1.RebuildResultSchema();
                            Opening_Sales.sqlDataSource1.Fill();
                            Opening_Sales.customer_cmb.Refresh();
                            Opening_Sales.customer_cmb.EditValue = inserted_record_id;
                            this.us_opener.Close();
                        }
                        if (this.update_creditors_entry_list == true)
                        {
                            Creditors_Entry.sqlDataSource1.RebuildResultSchema();
                            Creditors_Entry.sqlDataSource1.Fill();
                            Creditors_Entry.customer_cmb.Refresh();
                            Creditors_Entry.customer_cmb.EditValue = inserted_record_id;
                            this.us_opener.Close();
                        }
                        Reset_Fields();
                    }
                    else
                    {
                        XtraMessageBox.Show("Something went wrong !");
                    }
                }
                else
                {
                    XtraMessageBox.Show("Customer already exists with same CNIC !");
                }
            }
        }

        public void Controls_List(object sender, KeyEventArgs e)
        {

            if (e.KeyCode == Keys.Escape && (name_inp.Text != ""))
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
            else if (e.KeyCode == Keys.F6 || (e.Control && e.KeyCode == Keys.N))
            {
                UC_Opener_Form form = new UC_Opener_Form("New Customer", new New_Customer(Convert.ToInt32(store_cmb.EditValue)));
                form.Show(this);
            }
            else if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
            else if (e.Control && e.Alt && e.KeyCode == Keys.G)
            {
                Account guarrantor = accounts_controller.Get_Last_Saved_Account(1010, Convert.ToInt32(store_cmb.EditValue));
                setDetails(guarrantor);
            }
            else if (e.Control && e.Alt && e.KeyCode == Keys.C)
            {
                Account customer = accounts_controller.Get_Last_Saved_Account(1002, Convert.ToInt32(store_cmb.EditValue));
                setDetails(customer);
            }
        }

