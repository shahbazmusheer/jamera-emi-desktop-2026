        private void mesg_pause_play_btn_Click(object sender, EventArgs e)
        {
            if(SMS_Thread.ThreadState == ThreadState.Unstarted || SMS_Thread.ThreadState == ThreadState.Aborted || SMS_Thread.ThreadState == ThreadState.Stopped)
            {
                contacts_table.Clear();
                Get_Dueable_Contacts();
                if(contacts_table.Rows.Count > 0)
                {
                    mesg_pause_play_btn.Image = Jamera.Properties.Resources.pause_16x16;
                    tasks_cmb.Enabled = false;
                    String Group_Name = null;
                    String Message_Type = null;
                    String Message_Text = null;
                    String SMS_Gateway = null;
                    String Phone_Options = "Both";

                    Group_Name = "Customers ( Debitors )";

                    if (sms_gateway_cmb.Text != "")
                    {
                        SMS_Gateway = sms_gateway_cmb.Text;
                    }
                    if (phones_options_cmb.Text != "")
                    {
                        Phone_Options = phones_options_cmb.Text;
                    }
                    Message_Text = message_inp.Text;
                    Message_Type = messages_type_cmb.Text;
                    SMS_Thread = new Thread(() => Send_Messages(Group_Name, Message_Type, Message_Text, SMS_Gateway, Phone_Options, contacts_table));
                    SMS_Thread.Start();
                }
                else
                {
                    XtraMessageBox.Show("There is no record for due date !");
                }
            }
            else if(SMS_Thread.ThreadState == ThreadState.Running)
            {
                mesg_pause_play_btn.Image = Jamera.Properties.Resources.play_16x16;
                tasks_cmb.Enabled = true;
                SMS_Thread.Abort();
            }else if (SMS_Thread.ThreadState == ThreadState.Aborted)
            {
                contacts_table.Clear();
                Get_Dueable_Contacts();
                if (contacts_table.Rows.Count > 0)
                {
                    mesg_pause_play_btn.Image = Jamera.Properties.Resources.pause_16x16;
                    tasks_cmb.Enabled = false;
                    String Group_Name = null;
                    String Message_Type = null;
                    String Message_Text = null;
                    String SMS_Gateway = null;
                    String Phone_Options = "Both";
                    
                    Group_Name = "Customers ( Debitors )";

                    if (sms_gateway_cmb.Text != "")
                    {
                        SMS_Gateway = sms_gateway_cmb.Text;
                    }
                    if (phones_options_cmb.Text != "")
                    {
                        Phone_Options = phones_options_cmb.Text;
                    }                    
                    Message_Text = message_inp.Text;
                    Message_Type = messages_type_cmb.Text;
                    SMS_Thread = new Thread(()=>Send_Messages(Group_Name,Message_Type,Message_Text,SMS_Gateway,Phone_Options,contacts_table));
                    SMS_Thread.Start();
                }
                else
                {
                    XtraMessageBox.Show("There is no record for due date !");
                }
                
            }
        }

