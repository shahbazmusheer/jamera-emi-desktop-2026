        public void Send_Messages(String Group_Name, String Message_Type, string Message_Text, String SMS_Gateway, String Phone_Option, DataTable temp_contacts_Table)
        {
            var office_phones_count = temp_contacts_Table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Office Phone") != "")
            .Count();
            var home_phones_count = temp_contacts_Table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Home Phone") != "")
            .Count();
            Double total_phone_numbers_count = 0;
            bool is_home_phone_selected = false;
            bool is_office_phone_selected = false;
            Double message_sent_counter = 0;
            if (Phone_Option == "Both")
            {
                total_phone_numbers_count = office_phones_count + home_phones_count;
                is_home_phone_selected = true;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Office Phone")
            {
                total_phone_numbers_count = office_phones_count;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Home Phone")
            {
                total_phone_numbers_count = home_phones_count;
                is_home_phone_selected = true;
            }
            int interval_after_each_message_sent_in_sec = Settings.Default.sms_loop_delay_time_in_sec;
            Aggrements.Aggrements_Controller aggrements_controller = new Aggrements.Aggrements_Controller();
            int no_of_records= temp_contacts_Table.Rows.Count;
            Messages.Messages_Controller messages_controller = new Messages.Messages_Controller();
            for (int i=0;i < no_of_records; i++)
            {
                Messages.Message message = new Messages.Message();
                message.ACCOUNT_ID =Convert.ToInt32(temp_contacts_Table.Rows[i]["customer_code"]);
                message.RECIEVER_NAME= temp_contacts_Table.Rows[i]["Name"].ToString();
                int dues_id =Convert.ToInt32(temp_contacts_Table.Rows[i]["Dues Id"]);
                int store_id = Convert.ToInt32(temp_contacts_Table.Rows[i]["Store.Id"]);
                message.SMS_Gateway = SMS_Gateway;
                string raw_message = Message_Text;
                var replace_reciever_name = raw_message.Replace("[CUSTOMER_NAME]", temp_contacts_Table.Rows[i]["Name"].ToString());
                var replace_ref_no = replace_reciever_name.Replace("[REF_NO]", temp_contacts_Table.Rows[i]["Ref.No"].ToString());
                var replace_due_date = replace_ref_no.Replace("[DUE_DATE]", temp_contacts_Table.Rows[i]["Due Date"].ToString());
                var replace_due_amount = replace_due_date.Replace("[DUE_AMOUNT]", Convert.ToInt32(temp_contacts_Table.Rows[i]["Due Amount"]).ToString());
                var replace_paid_amount = replace_due_amount.Replace("[PAID_AMOUNT]", Convert.ToInt32(temp_contacts_Table.Rows[i]["Paid Amount"]).ToString());
                var replace_agreement_balance = replace_paid_amount.Replace("[Current_balance]", Convert.ToInt32(temp_contacts_Table.Rows[i]["Balance"]).ToString());
                // Here is message for today cash vouchers
                message.Message_Text = replace_agreement_balance;
                if (is_office_phone_selected == true && temp_contacts_Table.Rows[i]["Office Phone"] != DBNull.Value && temp_contacts_Table.Rows[i]["Office Phone"] != null && temp_contacts_Table.Rows[i]["Office Phone"].ToString() != "")
                {
                    message.RECIEVER_NUMBER = temp_contacts_Table.Rows[i]["Office Phone"].ToString();
                    goto send_message_start;
                send_message_start:
                    int is_sent = -1;
                    is_sent = messages_controller.Send_Message(message);
                    if (is_sent == 1)
                    {
                        //Progress Update
                           
                        message_sent_counter = message_sent_counter + 1;
                        Double result = ((message_sent_counter / total_phone_numbers_count) * 100);
                        int res = Convert.ToInt32(result);
                        SetValueCallback d = new SetValueCallback(SetProcessBarValue);
                        progressBarControl1.BeginInvoke(d, res);
                            
                        message.Status = "Sent";
                        Console.WriteLine("Message Sending...");
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Black);
                    }
                    else if (is_sent == -2)
                    {
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "Connecting ...");

                        goto send_message_start;
                    }
                    else if (is_sent == -3)
                    {
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "Wating ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    else if (is_sent == -1)
                    {
                        //No Service ...
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "No Service ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    messages_controller.Store_Message(message);
                    Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
                    Console.WriteLine("Messages Delay for "+ Settings.Default.sms_loop_delay_time_in_sec + " sec started");
                }

               if (is_home_phone_selected == true && temp_contacts_Table.Rows[i]["Home Phone"] != DBNull.Value && temp_contacts_Table.Rows[i]["Home Phone"] != null && temp_contacts_Table.Rows[i]["Home Phone"].ToString() != "")
                {
                    message.RECIEVER_NUMBER = temp_contacts_Table.Rows[i]["Home Phone"].ToString();
                    goto send_message_start;
                send_message_start:
                    int is_sent = -1;
                    is_sent = messages_controller.Send_Message(message);
                    if (is_sent == 1)
                    {
                        message_sent_counter = message_sent_counter + 1;
                        Double result = (message_sent_counter / total_phone_numbers_count) * 100;
                        int res = Convert.ToInt32(result);
                        SetValueCallback d = new SetValueCallback(SetProcessBarValue);
                        progressBarControl1.BeginInvoke(d, res);

                        message.Status = "Sent";
                        Console.WriteLine("Message Sending...");
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Black);
                    }
                    else if (is_sent == -2)
                    {
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "Connecting ...");

                        goto send_message_start;
                    }
                    else if (is_sent == -3)
                    {
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "Wating ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    else if (is_sent == -1)
                    {
                        //No Service ...
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progressBarControl1.BeginInvoke(progress_status_color_updater, Color.Red);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        progressBarControl1.BeginInvoke(progress_status_updater, "No Service ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    messages_controller.Store_Message(message);
                    Thread.Sleep(Settings.Default.sms_loop_delay_time_in_sec);
                    Console.WriteLine("Messages Delay for " + Settings.Default.sms_loop_delay_time_in_sec + " sec started");               
                }
            }
            After_Send_All_Messages after_all_messages_sent = new After_Send_All_Messages(after_sent_messages);
            mesg_pause_play_btn.BeginInvoke(after_all_messages_sent, Jamera.Properties.Resources.play_16x16);
