        public void Update()
        {
            if (messages_groups_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select group first !");
                messages_groups_cmb.ShowPopup();
                messages_groups_cmb.Focus();
            }
            else if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter name of contact person !");
                name_inp.Focus();
            }
            else
            {
                int group_id = Convert.ToInt32(messages_groups_cmb.EditValue);
                if (contacts_controller.Exists(id, group_id,name_inp.Text) != true)
                {
                    int store_id = -1;
                    if (store_cmb.Text != null)
                    {
                        store_id = Convert.ToInt32(store_cmb.EditValue);
                    }
                    contacts_controller.Update(group_id,id, name_inp.Text, office_phone_inp.Text, home_phone_inp.Text, address_inp.Text, remarks_inp.Text,store_id);
                    this.Close();
                }
                else
                {
                    XtraMessageBox.Show("contact already exists with same name !");
                }

            }
        }
        private void update_btn_Click(object sender, EventArgs e)
        {
            Update();
        }

        private void delete_btn_Click(object sender, EventArgs e)
        {
            contacts_controller.Delete_Contact(id);
            this.Close();
        }

        private void home_phone_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            TextEdit phone_inp = home_phone_inp;
            phone_inp.Properties.MaxLength = 13;
            Char ch = e.KeyChar;

            if (!char.IsDigit(ch) && ch != 13 && ch != 8 && ch != 127 && ch != 45 && ch != 43)
            {
                e.Handled = true;
            }
            if (phone_inp.Text.StartsWith("+92", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                Regex r = new Regex(@"\d{6}\-\d{7}");
                phone_inp.Properties.MaxLength = 14;
            }
            else if (phone_inp.Text.StartsWith("+92", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 13;
            }
            else if (phone_inp.Text.StartsWith("03", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                Regex r = new Regex(@"\d{4}\-\d{7}");
                phone_inp.Properties.MaxLength = 12;
            }
            else if (phone_inp.Text.StartsWith("03", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 11;
            }
            else if (phone_inp.Text.StartsWith("92", StringComparison.CurrentCulture) && phone_inp.Text.Contains("-"))
            {
                phone_inp.Properties.MaxLength = 13;
            }
            else if (phone_inp.Text.StartsWith("92", StringComparison.CurrentCulture))
            {
                phone_inp.Properties.MaxLength = 12;
            }
        }

