        private void Add_Contact_KeyDown(object sender, KeyEventArgs e)
        {
            if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
            else if (e.Control && e.KeyCode == Keys.N || e.KeyCode == Keys.F6)
            {
                Add_Contact form = new Add_Contact();
                form.Show(this);
            }
            if (e.KeyCode == Keys.Escape && (name_inp.Text != "" ))
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
        }

