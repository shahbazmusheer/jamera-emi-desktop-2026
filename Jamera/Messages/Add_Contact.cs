        }
        public void Save()
        {
           if(messages_groups_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select group first !");
                messages_groups_cmb.ShowPopup();
                messages_groups_cmb.Focus();
            }
            else if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter name of contact person !");
                name_inp.Focus();
            }
            else
            {
                int group_id = Convert.ToInt32(messages_groups_cmb.EditValue);
                if (contacts_controller.Exists(group_id,name_inp.Text) != true)
                {
                    int store_id = -1;
                    if(store_cmb.Text != "")
                    {
                        store_id = Convert.ToInt32(store_cmb.EditValue);
                    }
                    contacts_controller.Store(group_id,name_inp.Text, office_phone_inp.Text, home_phone_inp.Text, address_inp.Text,remarks_inp.Text,store_id);
                }
                else
                {
                    XtraMessageBox.Show("contact already exists with same name !");
                }
                Reset_Fields();

            }
        }
        private void save_btn_Click(object sender, EventArgs e)
        {
