                    int is_sent = -1;
                    is_sent = messages_controller.Send_Message(message);
                    if (is_sent == 1)
                    {
                        message.Status = "Sent";

                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Black);
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "Messages Sending ...");
                    }
                    else if (is_sent == -2)
                    {
                        //Update_Progress_Status_Label_Color
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "Connecting ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    else if (is_sent == -3)
                    {
                        //Update_Progress_Status_Label_Color
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
