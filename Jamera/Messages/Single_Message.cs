        public void Send_Message()
        {
            if (phone_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter phone number !");
                phone_inp.Focus();
            }
            else if (message_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter message text !");
                message_inp.Focus();
            }
            else
            {
                send_btn.Enabled = false;
                message_inp.ReadOnly = true;
                var phone_inp_str = phone_inp.Text;
                var phone_str_split = phone_inp_str.Split(',');
                Console.WriteLine("Total Phone Numbers:"+phone_str_split.Length);


                progress_status_lable.Text = "Messages Sending ... ";
                if (SMS_Thread.ThreadState == ThreadState.Unstarted || SMS_Thread.ThreadState == ThreadState.Aborted || SMS_Thread.ThreadState == ThreadState.Stopped)
                {
                    int temp_store_id = -1;
                    if(this.store_id != -1)
                    {
                        temp_store_id = this.store_id;
                    }
                    Console.WriteLine("This.Store_Id:"+this.store_id);
                    String Group_Name = this.Group_Name;
                    String Message_Type = messages_type_cmb.Text;
                    String Message_Text = message_inp.Text;
                    String SMS_Gateway = sms_gateway_cmb.Text;
                    String Phone_Options = null;
                    Contacts_Table.Clear();
                    DataRow dr=Contacts_Table.NewRow();
                    dr["Code"] = this.account_id;
                    dr["Name"] = this.Name;
                    if((this.Home_Phone != null && this.Home_Phone != "") || (this.Office_Phone != null && this.Office_Phone != ""))
                    {
                        dr["Home Phone"] = this.Home_Phone;
                        dr["Office Phone"] = this.Office_Phone;
                    }
                    else
                    {
                        dr["Office Phone"] = phone_inp.Text;
                    }
                    Contacts_Table.Rows.Add(dr);
                    if (phone_str_split.Length == 2)
                    {
                        Phone_Options = "Both";
                    }
                    else if (phone_str_split.Length == 1 && phone_inp.Text == this.Office_Phone)
                    {
                        Phone_Options = "Office Phone";
                    }
                    else if (phone_str_split.Length == 1 && phone_inp.Text == this.Home_Phone)
                    {
                        Phone_Options = "Home Phone";
                    }
                    else
                    {
                        Phone_Options = "Office Phone";
                    }
                    
                    progress_panel.Visible = true;     
                    Message_Text = message_inp.Text;
                    Message_Type = messages_type_cmb.Text;
                    SMS_Thread = new Thread(() => Send_Message_To_Numbers(temp_store_id, Group_Name, Message_Type, Message_Text, SMS_Gateway, Phone_Options, Contacts_Table));
                    SMS_Thread.Start();
                    
                }

            }
        }

        public void Send_Message_To_Numbers(int str_id, String Group_Name, String Message_Type, string Message_Text, String SMS_Gateway, String Phone_Option, DataTable temp_contacts_Table)
        {
            Console.WriteLine("str_id:" + str_id);
            int interval_after_each_message_sent_in_sec = Settings.Default.sms_loop_delay_time_in_sec;
            var office_phones_count = temp_contacts_Table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Office Phone") != "")
            .Count();
            var home_phones_count = temp_contacts_Table.Rows.Cast<DataRow>()
            .Where(r => r.Field<String>("Home Phone") != "")
            .Count();
            int total_phone_numbers_count = 0;
            bool is_home_phone_selected = false;
            bool is_office_phone_selected = false;
            if (Phone_Option == "Both")
            {
                total_phone_numbers_count = office_phones_count + home_phones_count;
                is_home_phone_selected = true;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Office Phone")
            {
                total_phone_numbers_count = office_phones_count;
                is_office_phone_selected = true;
            }
            else if (Phone_Option == "Home Phone")
            {
                total_phone_numbers_count = home_phones_count;
                is_home_phone_selected = true;
            }
            Console.WriteLine("Total Phone number :" + total_phone_numbers_count);
            Console.WriteLine("Table Data rows Count :" + temp_contacts_Table.Rows.Count);
            int sent_messages_count = 0;
            Update_Sent_Message_Counter sent_msg_counter_updater = new Update_Sent_Message_Counter(update_sent_message_counter);
            sent_message_count_lbl.BeginInvoke(sent_msg_counter_updater, sent_messages_count + "/" + total_phone_numbers_count);
            for (int i = 0; i < temp_contacts_Table.Rows.Count; i++)
            {


                if (is_office_phone_selected == true && temp_contacts_Table.Rows[i]["Office Phone"] != DBNull.Value && temp_contacts_Table.Rows[i]["Office Phone"] != null && temp_contacts_Table.Rows[i]["Office Phone"].ToString() != "")
                {
                    //Send Message to office phone
                    Message message = new Message();
                    message.ACCOUNT_ID = Convert.ToInt32(temp_contacts_Table.Rows[i]["Code"]);
                    message.Store_Id = str_id;
                    message.Message_Text = Message_Text;
                    message.Message_Type = Message_Type;
                    message.Group = Group_Name;
                    message.SMS_Gateway = SMS_Gateway;
                    Console.WriteLine("Office Phone :" + temp_contacts_Table.Rows[i]["Office Phone"].ToString());
                    message.RECIEVER_NUMBER = temp_contacts_Table.Rows[i]["Office Phone"].ToString();
                    goto send_message_start;
                send_message_start:
                    int is_sent = -2;
                    //Server Result Codes Description -----
                    //[-2]=Client not connected 
                    //[-1]= No Service
                    //[0] = Null PDU
                    //[1] = Sent
                    //[2] = AirPlane Mode / Radio Off
                    //[3] = Short Codes Never Allowed
                    //[4] = Unknown Error
                    is_sent = messages_controller.Send_Message(message);
                    if (is_sent == 1)
                    {
                        message.Status = "Sent";

                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Black);
