                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "Messages Sending ...");
                    }
                    else if (is_sent == -2)
                    {
                        //Update_Progress_Status_Label_Color
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "Connecting ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    else if (is_sent == -3)
                    {
                        //Update_Progress_Status_Label_Color
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "Wating ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    else if (is_sent == -1)
                    {
                        //Update_Progress_Status_Label_Color
                        Update_Progress_Status_Label_Color progress_status_color_updater = new Update_Progress_Status_Label_Color(update_progress_status_label_color);
                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "No Service ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    messages_controller.Store_Message(message);
                    sent_messages_count = sent_messages_count + 1;
                    Console.WriteLine("Sent Messages Counter=" + sent_messages_count);
                    sent_msg_counter_updater = new Update_Sent_Message_Counter(update_sent_message_counter);
                    sent_message_count_lbl.BeginInvoke(sent_msg_counter_updater, sent_messages_count + "/" + total_phone_numbers_count);
                    if (SMS_Gateway == "Android Wifi")
                    {
                        Thread.Sleep(interval_after_each_message_sent_in_sec);
                    }
                    else if (SMS_Gateway == "API")
                    {
                        Thread.Sleep(2000);
                    }
                }
                if (is_home_phone_selected == true && temp_contacts_Table.Rows[i]["Home Phone"] != DBNull.Value && temp_contacts_Table.Rows[i]["Home Phone"] != null && temp_contacts_Table.Rows[i]["Home Phone"].ToString() != "")
                {
                    //Send Message to home phone
                    Message message = new Message();
                    message.ACCOUNT_ID = Convert.ToInt32(temp_contacts_Table.Rows[i]["Code"]);
                    message.Store_Id = str_id;
                    message.Message_Text = Message_Text;
                    message.Message_Type = Message_Type;
                    message.Group = Group_Name;
                    message.SMS_Gateway = SMS_Gateway;
