                        progress_status_lable.BeginInvoke(progress_status_color_updater, Color.Red);
                        //
                        Update_Progress_Status_Text progress_status_updater = new Update_Progress_Status_Text(update_progress_status_text);
                        sent_message_count_lbl.BeginInvoke(progress_status_updater, "No Service ...");
                        Thread.Sleep(2000);
                        goto send_message_start;
                    }
                    messages_controller.Store_Message(message);
                    sent_messages_count = sent_messages_count + 1;
                    Console.WriteLine("Sent Messages Counter=" + sent_messages_count);
                    sent_msg_counter_updater = new Update_Sent_Message_Counter(update_sent_message_counter);
                    sent_message_count_lbl.BeginInvoke(sent_msg_counter_updater, sent_messages_count + "/" + total_phone_numbers_count);
                    Console.WriteLine("Loop Iteration=" + i);
                    Console.WriteLine(interval_after_each_message_sent_in_sec + " sec Delay start now !");
                    Thread.Sleep(interval_after_each_message_sent_in_sec);
                    Console.WriteLine(interval_after_each_message_sent_in_sec + " sec Delay end now !");
                    if (SMS_Gateway == "Android Wifi")
                    {
                        Thread.Sleep(interval_after_each_message_sent_in_sec);
                    }
                    else if (SMS_Gateway == "API")
                    {
                        Thread.Sleep(2000);
                    }
                }
            }
            Hide_Panel after_all_messages_sent = new Hide_Panel(after_sent_messages);
            progress_panel.BeginInvoke(after_all_messages_sent, false);
            Send_Btn_Enabled send_btn_enbl = new Send_Btn_Enabled(send_btn_enabled);
            send_btn.BeginInvoke(send_btn_enbl, true);
            //Group_Cmb_Enabled group_cmb_enbl = new Group_Cmb_Enabled(group_cmb_enabled);
            //messages_groups_cmb.BeginInvoke(group_cmb_enbl, true);
            //Grid_Cntl_Enabled grd_enabled = new Grid_Cntl_Enabled(grid_ctrl_enabled);
