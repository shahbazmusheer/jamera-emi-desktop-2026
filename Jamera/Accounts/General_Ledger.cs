        public void Set_Sum()
        {
            DevExpress.XtraGrid.GridSummaryItem debit_item = gridView1.Columns["Debit"].SummaryItem;
            debit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double debit_total = Convert.ToDouble(debit_item.SummaryValue);
            total_debit.Text = string.Format("{0:#,##0.00}", Double.Parse(debit_total.ToString()));

            DevExpress.XtraGrid.GridSummaryItem credit_item = gridView1.Columns["Credit"].SummaryItem;
            credit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double credit_total = Convert.ToDouble(credit_item.SummaryValue);
            total_credit.Text = string.Format("{0:#,##0.00}", Double.Parse(credit_total.ToString()));
        }

        private void refresh_btn_Click(object sender, EventArgs e)
        {
            this.Enabled = false;
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();
            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;

            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = "SELECT account_id as 'Code',account_name as 'Account',SUBSTRING(CONVERT(VARCHAR(8),entry_date,1),0,7) as 'Date',invoice_no as 'Invoice No',account_nature as 'Nature',description as 'Description',item_name as 'Item Name', item_quantity as 'Item quantity',debit as 'Debit',credit as 'Credit',closing_balance as 'Closing Balance' FROM journal_transactions WHERE DATEADD(dd,0,DATEDIFF(dd,0,entry_date)) >= DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0) and DATEADD(dd,0,DATEDIFF(dd,0,entry_date)) <= DATEADD(dd,0,DATEDIFF(dd,0,GETDATE())) and (debit > 0 or credit > 0 )";
            query.Name = "Query";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            Set_Sum();
            this.Enabled = true;
            from_date_picker.Focus();
        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = "SELECT account_id as 'Code',account_name as 'Account',SUBSTRING(CONVERT(VARCHAR(8),entry_date,1),0,7) as 'Date',invoice_no as 'Invoice No',account_nature as 'Nature',description as 'Description',item_name as 'Item Name', item_quantity as 'Item quantity',debit as 'Debit',credit as 'Credit',closing_balance as 'Closing Balance' FROM journal_transactions WHERE entry_date >= Convert(DATETIME,'"+from_date_picker.Text+"',103) and entry_date <= Convert(DATETIME,'"+to_date_picker.Text+"',103) and (debit > 0 or credit > 0 )";
            query.Name = "Query";
