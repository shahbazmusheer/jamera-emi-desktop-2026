        public void Load_Popup_Settings()
        {
            int width = this.Width;
            int height = 280;
            exp_account_cmb.Properties.PopupFormSize = new Size(width, height);
            store_cmb.Properties.PopupFormSize = new Size(width, height);
        }

        private void new_btn_Click(object sender, EventArgs e)
        {
            date_picker.Focus();
            UC_Opener_Form form = new UC_Opener_Form("Expense Manager",new Expense_Manager());
            form.Show(this);
        }

        private void cancel_btn_Click(object sender, EventArgs e)
        {
            this.Reset_Fields();
        }

        public void Reset_Fields()
        {
            exp_account_cmb.Text = "";
            payment_method_cmb.SelectedIndex = 0;
            amount_inp.Text = "0";
            description_inp.Text = "";
            store_cmb.Text = null;
            exp_account_cmb.Focus();
        }
        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(exp_account_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select and expense account !");
                exp_account_cmb.ShowPopup();
            }else if(amount_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter expense amount !");
                amount_inp.Focus();
            }
            else
            {
                Double Amount = Convert.ToDouble(amount_inp.Text);
                if(Amount > 0)
                {
                    int store_id = -1;
                    int credit_account_id = -1;
                    if(store_cmb.Text != "")
                    {
                        store_id = Convert.ToInt32(store_cmb.EditValue);
                    }
                    if(payment_method_cmb.Text == "Cash")
                    {
                        credit_account_id = 2001;
                    }
                    else
                    {
                        credit_account_id = 2002;
                    }

                    Account credit_account = accounts_controller.Get_Account(credit_account_id);
                    if(credit_account.Balance > Amount)
                    {
                        Account expense_account = accounts_controller.Get_Account(Convert.ToInt32(exp_account_cmb.EditValue));
                        //transactions
                        accounts_controller.Insert_Account_Transaction(credit_account.Account_Id,credit_account.Account_Name,credit_account.Account_Type,credit_account.Account_Nature,"General Expense",description_inp.Text,0,0,0,Amount,(credit_account.Balance - Amount),Convert.ToDateTime(date_picker.Text),null,null,0,-1,store_id);

                        accounts_controller.Insert_Account_Transaction(expense_account.Account_Id,expense_account.Account_Name,expense_account.Account_Type,expense_account.Account_Nature,"Genral Expense",description_inp.Text,0,0,Amount,0,(expense_account.Balance + Amount),Convert.ToDateTime(date_picker.Text), null, null, 0, -1, store_id);

                        Reset_Fields();
                    }
                    else
                    {
                        XtraMessageBox.Show("Not enough balance in "+ credit_account.Account_Name+".Please recharge it first !");
                    }
                }
                else
                {
                    XtraMessageBox.Show("Please enter expense amount greater then zero !");
                    amount_inp.Focus();
                }
            }
        }
        private void save_btn_Click(object sender, EventArgs e)
        {
            Save();
        }

