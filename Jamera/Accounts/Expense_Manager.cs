        }

        private void description_inp_KeyDown(object sender, KeyEventArgs e)
        {
            Controls_List(sender, e);
        }

        private void amount_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }
        }

        private void exp_account_cmb_Properties_ButtonClick(object sender, DevExpress.XtraEditors.Controls.ButtonPressedEventArgs e)
        {
            int i = e.Button.Index;

            if (i == 1)
            {
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                exp_account_cmb.Refresh();
            }
        }

        private void store_cmb_Properties_ButtonClick(object sender, DevExpress.XtraEditors.Controls.ButtonPressedEventArgs e)
        {
            int i = e.Button.Index;

            if (i == 1)
            {
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                store_cmb.Refresh();
            }
        }

        public void Controls_List(object sender, KeyEventArgs e)
        {

            if (e.KeyCode == Keys.Escape && (exp_account_cmb.Text != "" || amount_inp.Text != "" || store_cmb.Text == ""))
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
            else if (e.KeyCode == Keys.F5 || (e.Control && e.KeyCode == Keys.R))
            {
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                exp_account_cmb.Refresh();
                store_cmb.Refresh();
            }
            else if (e.KeyCode == Keys.F6 || (e.Control && e.KeyCode == Keys.N))
            {
                UC_Opener_Form form = new UC_Opener_Form("Expense Manager", new Expense_Manager());
                form.Show(this);
            }
            else if (e.KeyCode == Keys.F7)
            {
                payment_method_cmb.Focus();
                payment_method_cmb.ShowPopup();
            }
            else if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
        }

