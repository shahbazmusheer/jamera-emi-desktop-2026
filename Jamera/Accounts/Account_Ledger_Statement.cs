        private void refresh_btn_Click(object sender, EventArgs e)
        {
            this.Enabled = false;
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_1"]);
            account_cmb.EditValue = 2001;
            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = "SELECT account_id as 'Code',account_name as 'Account',SUBSTRING(CONVERT(VARCHAR(8),entry_date,1),0,7) as 'Date',invoice_no as 'Invoice No',source as 'Source',description as 'Description',item_name as 'Item Name', item_quantity as 'Item quantity',debit as 'Debit',credit as 'Credit',closing_balance as 'Closing Balance' FROM journal_transactions WHERE DATEADD(dd,0,DATEDIFF(dd,0,entry_date)) >= DATEADD(mm,DATEDIFF(mm,0,GETDATE()),0) and DATEADD(dd,0,DATEDIFF(dd,0,entry_date)) <= DATEADD(dd,0,DATEDIFF(dd,0,GETDATE())) and account_name='Cash';";
            query.Name = "Query_1";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            Set_Sum();
            DateTime today_date = DateTime.Now;
            String month = today_date.Month.ToString();
            String year = today_date.Year.ToString();
            from_date_picker.EditValue = Convert.ToDateTime("01-" + month + "-" + year);
            to_date_picker.EditValue = DateTime.Now;
            this.Enabled = true;
            from_date_picker.Focus();
        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_1"]);

            CustomSqlQuery query = new CustomSqlQuery();
            query.Sql = "SELECT account_id as 'Code',account_name as 'Account',SUBSTRING(CONVERT(VARCHAR(8),entry_date,1),0,7) as 'Date',invoice_no as 'Invoice No',source as 'Source',description as 'Description',item_name as 'Item Name', item_quantity as 'Item quantity',debit as 'Debit',credit as 'Credit',closing_balance as 'Closing Balance' FROM journal_transactions WHERE entry_date >= Convert(DATETIME,'" + from_date_picker.Text + "',103) and entry_date <= Convert(DATETIME,'" + to_date_picker.Text + "',103) and account_name='"+account_cmb.Text+"'";
            query.Name = "Query_1";
            sqlDataSource1.Queries.Add(query);
            sqlDataSource1.RebuildResultSchema();
            sqlDataSource1.Fill();
            Set_Sum();
            gridView1.Focus();
        }
        public void Set_Sum()
        {
            DevExpress.XtraGrid.GridSummaryItem debit_item = gridView1.Columns["Debit"].SummaryItem;
            debit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double debit_total = Convert.ToDouble(debit_item.SummaryValue);
            total_debit.Text = string.Format("{0:#,##0.00}", Double.Parse(debit_total.ToString()));

            DevExpress.XtraGrid.GridSummaryItem credit_item = gridView1.Columns["Credit"].SummaryItem;
            credit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double credit_total = Convert.ToDouble(credit_item.SummaryValue);
            total_credit.Text = string.Format("{0:#,##0.00}", Double.Parse(credit_total.ToString()));

            Accounts_Controller accounts_controller = new Accounts_Controller();
            if( accounts_controller.Get_Account_Type(Convert.ToInt32(account_cmb.EditValue)) == "DR")
            {
                //debit account
                Double net_activity = debit_total - credit_total;
                net_activity_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(net_activity.ToString()));
            }
            else
            {
                //credit account
                Double net_activity =  credit_total - debit_total;
                net_activity_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(net_activity.ToString()));
            }

        }

        private void gridView1_RowCountChanged(object sender, EventArgs e)
        {
            Set_Sum();
        }

