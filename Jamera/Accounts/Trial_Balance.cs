        public void Set_Sum()
        {
            DevExpress.XtraGrid.GridSummaryItem debit_item = gridView1.Columns["Total Debit"].SummaryItem;
            debit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double debit_total = Convert.ToDouble(debit_item.SummaryValue);
            total_debit.Text = string.Format("{0:#,##0.00}", Double.Parse(debit_total.ToString()));

            DevExpress.XtraGrid.GridSummaryItem credit_item = gridView1.Columns["Total Credit"].SummaryItem;
            credit_item.SummaryType = DevExpress.Data.SummaryItemType.Sum;
            Double credit_total = Convert.ToDouble(credit_item.SummaryValue);
            total_credit.Text = string.Format("{0:#,##0.00}", Double.Parse(credit_total.ToString()));
        }
        private void gridView1_RowCountChanged(object sender, EventArgs e)
        {
            Set_Sum();
        }

        private void search_btn_Click(object sender, EventArgs e)
        {
            if(from_date_picker.Text != "" && to_date_picker.Text != "")
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Sql = "SELECT ac.id as 'Code',ac.name as 'Account',SUM(debit) as 'Total Debit',SUM(credit) as 'Total Credit' ,(CASE WHEN ac.account_type='DR' THEN (SUM(jt.debit) - SUM(jt.credit)) ELSE (SUM(jt.credit)- SUM(jt.debit)) END) as 'Closing Balance' FROM accounts as ac right join journal_transactions as jt on ac.id=jt.account_id WHERE DATEADD(dd,0,DATEDIFF(dd,0,jt.entry_date)) >= DATEADD(dd,0,DATEDIFF(dd,0,CONVERT(DATETIME,'"+from_date_picker.Text+ "',103))) and DATEADD(dd,0,DATEDIFF(dd,0,jt.entry_date)) <= DATEADD(dd,0,DATEDIFF(dd,0,CONVERT(DATETIME,'" + to_date_picker.Text + "',103))) and (jt.debit > 0 or jt.credit > 0 )  group by jt.debit,jt.credit,ac.id,ac.name,ac.account_type;";
                query.Name = "Query";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                Set_Sum();
                gridView1.Focus();
            }
            else
            {
                XtraMessageBox.Show("Please select from date and to date properly !");
            }
        }

