        public void Save()
        {
            if(name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter account name !");
                name_inp.Focus();
            }
            else if(group_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select account group !");
                group_cmb.Focus();
            }
            else
            {
                Double amount = 0;
                amount = Convert.ToDouble(amount_inp.Text);
                if (amount > 0 && openings_cmb.Text == "")
                {
                    XtraMessageBox.Show("Please select debit/credit !");
                }
                else
                {
                    Accounts_Controller accounts_controller = new Accounts_Controller();
                    if (accounts_controller.Exists(name_inp.Text) != true)
                    {
                        String ac_type = null;
                        int Group_Id;
                        String Group_Name = null;
                        Group_Id = Convert.ToInt32(group_cmb.EditValue);
                        Group_Name = group_cmb.Text;
                        ac_type = Convert.ToString(group_cmb.Properties.View.GetFocusedRowCellValue("A/C Type"));
                        String nature = Convert.ToString(group_cmb.Properties.View.GetFocusedRowCellValue("Nature"));
                        int inserted_record_id = accounts_controller.Store(name_inp.Text, null, Group_Id, Group_Name, ac_type, phone_inp.Text, address_inp.Text, description_inp.Text,0);
                        if (inserted_record_id > 0)
                        {

                            if(amount > 0)
                            {
                                if(openings_cmb.SelectedIndex == 1)
                                {
                                    //Debit Selection
                                    accounts_controller.Insert_Account_Transaction(inserted_record_id,name_inp.Text,ac_type,nature,"Opening Balance",description_inp.Text,amount,0,0,0,amount,DateTime.Now);

                                }
                                else
                                {
                                    //Credit Selection
                                    accounts_controller.Insert_Account_Transaction(inserted_record_id, name_inp.Text, ac_type, nature, "Opening Balance", description_inp.Text, 0, amount,0, 0, amount, DateTime.Now);
                                }
                            }
                            
                            if(Update_Purchase_Accounts_List == true)
                            {
                                this.new_purchase.Update_Suppliers_List();
                                this.new_purchase.supplier_cmb.EditValue = inserted_record_id;
                                this.new_purchase.balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(amount_inp.Text));
                                this.us_opener.Close();
                            }
                            if (Update_Cash_Voucher_Exp_List == true)
                            {
                                this.CASH_VOUCHER.Update_Expense_Accounts_List();
                                this.CASH_VOUCHER.search_exp_acoounts_inp.EditValue = inserted_record_id;
                                this.us_opener.Close();
                            }
                            if (Update_Purchase_Paid_By_Accounts_List == true)
                            {
                                this.new_purchase.Update_Paid_By_List();
                                this.new_purchase.fuel_expenses_paid_account_cmb.EditValue = inserted_record_id;
                                //this.new_purchase.balance_inp.Text = string.Format("{0:#,##0.00}", Double.Parse(amount_inp.Text));
                                this.us_opener.Close();
                            }
                            if (Update_Item_Accounts_List == true)
                            {
                                this.new_item.Update_Suppliers_List();
                                this.new_item.supplier_cmb.EditValue = inserted_record_id;
                                this.us_opener.Close();
                            }
                            if(Update_Opening_Stock_Accounts_List == true)
                            {
                                this.opening_stocks.Update_Suppliers_List();
                                this.opening_stocks.supplier_cmb.EditValue = inserted_record_id;
                                this.us_opener.Close();
                            }
                            Reset_Fields();
                        }
                        else
                        {
                            XtraMessageBox.Show("Something went wrong !");
                        }
                    }
                    else
                    {
                        XtraMessageBox.Show("Account already exists with same name !");
                    }
                }
            }
            
        }

