        private void credit_balance_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            int dot_counter = item_balance_inp.Text.Count(f => f == '.');

            if ((item_balance_inp.Text.Length <= 0 && ch == 46) || (dot_counter > 0 && ch == 46))
            {
                e.Handled = true;
            }
        }

        private void item_balance_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            int dot_counter = item_balance_inp.Text.Count(f => f == '.');

            if ((item_balance_inp.Text.Length <= 0 && ch == 46) || (dot_counter > 0 && ch == 46))
            {
                e.Handled = true;
            }

            if (ch == 13)
            {
                Add_Item_To_Cart();
            }
        }

