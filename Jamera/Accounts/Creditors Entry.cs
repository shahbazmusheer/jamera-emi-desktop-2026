        public bool If_Item_Exists_In_Cart()
        {
            if (gridView1.DataRowCount > 0)
            {
                bool check_exists = false;

                for (int i = 0; i < gridView1.DataRowCount; i++)
                {
                    if (Convert.ToInt32(gridView1.GetRowCellValue(i, gridView1.Columns["Customer.Code"])) == Convert.ToInt32(customer_cmb.EditValue) && Convert.ToInt32(gridView1.GetRowCellValue(i, gridView1.Columns["Code"])) == Convert.ToInt32(search_item_cmb.EditValue) && Convert.ToString(gridView1.GetRowCellValue(i, gridView1.Columns["Ref.No"])) == ref_no_inp.Text)
                    {
                        check_exists = true;
                        break;
                    }
                }
                return check_exists;
            }
            else
            {
                return false;
            }
        }
        public void Save()
        {
            if (carts_table.Rows.Count <= 0)
            {
                XtraMessageBox.Show("Please enter opening sales entries !");
                customer_cmb.Focus();
                customer_cmb.ShowPopup();
            }
            else if (date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.Focus();
                date_picker.ShowPopup();
            }
            else if (store_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select store !");
                store_cmb.Focus();
                store_cmb.ShowPopup();
            }
            else if (accounts_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select account !");
                accounts_cmb.Focus();
                accounts_cmb.ShowPopup();
            }
            else if (debit_balance_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter credit balance!");
                debit_balance_inp.Focus();
            }
            else if (Convert.ToDouble(debit_balance_inp.Text) != Convert.ToDouble(total_balance_inp.Text))
            {
                XtraMessageBox.Show("Debit amount must meet the total credit amount !");
                debit_balance_inp.Focus();
            }
            else
            {
                //save
                for (int i = 0; i < carts_table.Rows.Count; i++)
                {
                    //jv vouchers entery
                    Vouchers.Vouchers_Controller vouchers_controller = new Vouchers.Vouchers_Controller();
                    int voucher_id = vouchers_controller.Store_Journal_Voucher(Convert.ToDateTime(date_picker.Text), Convert.ToInt32(accounts_cmb.EditValue), accounts_cmb.Text, "Reciepts Entry", Convert.ToInt32(carts_table.Rows[i]["Creditor.Code"]), Convert.ToString(carts_table.Rows[i]["Creditor"]), "Reciepts Entry", Convert.ToDouble(carts_table.Rows[i]["Balance"]), Convert.ToString(carts_table.Rows[i]["Ref.No"]));
                }
                Reset_Fields();
            }
        }
        public void Add_Item_To_Cart()
        {
            if (If_Item_Exists_In_Cart() == true)
            {
                XtraMessageBox.Show("Item already exists in cart !");
                item_balance_inp.Focus();
            }
            else
            {
                DataRow dr = carts_table.NewRow();
                GridView view = search_item_cmb.Properties.View;
                string fieldName = "Code"; // or other field name  
                int item_code = Convert.ToInt32(view.GetRowCellValue(search_item_cmb.Properties.GetIndexByKeyValue(search_item_cmb.EditValue), fieldName));
                dr["Code"] = item_code;
                dr["Item"] = search_item_cmb.Text;
                dr["Model"] = model_cmb.Text;
                dr["Balance"] = item_balance_inp.Text;
                dr["Creditor.Code"] = customer_cmb.EditValue;
                dr["Creditor"] = customer_cmb.Text;
                dr["Ref.No"] = ref_no_inp.Text;
                carts_table.Rows.Add(dr);
                Reset_Item_Entries();
                Set_Calculated_fields();
                customer_cmb.ShowPopup();
            }

        }
