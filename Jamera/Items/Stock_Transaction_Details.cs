            if (icon_path != "")
            {
                FileInfo image = new FileInfo(icon_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(icon_path);
                }
            }
            else
            {
                string img_path = Environment.CurrentDirectory + @"\Icons\" + img_name + @".ico";
                FileInfo image = new FileInfo(img_path);
                if (image.Exists == true)
                {
                    this.Icon = new Icon(img_path);
                }
            }
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }

        public void Load_Date()
        {
            Stock_Transaction stock_transaction = stocks_controller.Get_Stock_Transaction(Stock_Transaction_Id);
            code_lbl.Text = stock_transaction.Stock_Transaction_Id.ToString();
            date_picker_lbl.Text = stock_transaction.Date;
            name_lbl.Text= stock_transaction.Name;
            from_store_lbl.Text = stock_transaction.From_Store_Name;
            gatepass_lbl.Text = stock_transaction.GatePassNo;
            to_store_lbl.Text = stock_transaction.To_Store_Name;
            Items_list_Container.DataSource = stock_transaction.Stock_Transaction_Items_Table;
            no_of_items_lbl.Text = stock_transaction.Stock_Transaction_Items_Table.Rows.Count.ToString();
            Double Total_Quantity =Convert.ToDouble(stock_transaction.Stock_Transaction_Items_Table.AsEnumerable().Sum(row => row.Field<Decimal>("Quantity")));
            total_quantity_lbl.Text = Total_Quantity.ToString();
            remarks_label.Text = stock_transaction.Remarks;
            Items_list_Container.Focus();
        }

