        private void gridView1_CellValueChanged(object sender, DevExpress.XtraGrid.Views.Base.CellValueChangedEventArgs e)
        {
            if(e.Column.FieldName == "Quantity")
            {
                GridView view = sender as GridView;
                Double total_qty = 0;
                if(view != null)
                {
                    for(int i=0;i < view.DataRowCount; i++)
                    {
                        if(view.GetRowCellValue(i, gridView1.Columns["Quantity"]) != DBNull.Value)
                        {
                            total_qty = total_qty + Convert.ToDouble(view.GetRowCellValue(i, gridView1.Columns["Quantity"]));
                        }
                    }
                    total_quantity_lbl.Text = total_qty.ToString();
                }

            }
        }

