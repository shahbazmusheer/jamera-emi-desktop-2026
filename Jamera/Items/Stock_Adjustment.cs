        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
            }else if(search_item_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select item !");
                search_item_cmb.ShowPopup();
                search_item_cmb.Focus();
            }
            else
            {
                if(task_cmb.Text == "Add Item")
                {
                    Double item_total = Convert.ToDouble(item_total_inp.Text);
                    DataTable cart_items_table = new DataTable();
                    cart_items_table.Columns.Add("Code", typeof(Int32));
                    cart_items_table.Columns.Add("Item", typeof(String));
                    cart_items_table.Columns.Add("Packing Qty", typeof(Double));
                    cart_items_table.Columns.Add("Unit Qty", typeof(Double));
                    cart_items_table.Columns.Add("Purchase Rate", typeof(Double));
                    cart_items_table.Columns.Add("Unit Cost", typeof(Double));
                    cart_items_table.Columns.Add("Sale Rate", typeof(Double));
                    cart_items_table.Columns.Add("Disc(%)", typeof(Double));
                    cart_items_table.Columns.Add("Disc(R.S)", typeof(Double));
                    cart_items_table.Columns.Add("Total", typeof(Double));

                    DataRow dr = cart_items_table.NewRow();
                    dr["Code"] = Convert.ToInt32(search_item_cmb.EditValue);
                    dr["Item"] = search_item_cmb.Text;
                    dr["Packing Qty"] = (Convert.ToDouble(packing_qty_inp.Text));
                    dr["Unit Qty"] = Convert.ToDouble(unit_qty_inp.Text);
                    Double item_packing_size = Convert.ToDouble(search_item_cmb.Properties.View.GetFocusedRowCellValue("Packing"));
                    dr["Purchase Rate"] = (Convert.ToDouble(unit_cost_inp.Text) * item_packing_size);
                    dr["Unit Cost"] = Convert.ToDouble(unit_cost_inp.Text);
                    dr["Sale Rate"] = Convert.ToDouble(sale_rate_inp.Text);
                    dr["Disc(%)"] = 0;
                    dr["Disc(R.S)"] = 0;
                    dr["Total"] = item_total;
                    cart_items_table.Rows.Add(dr);

                    Purchases.Purchases_Controller purchases_controller = new Purchases.Purchases_Controller();
                    purchases_controller.Store(Convert.ToDateTime(date_picker.Text), "New Purchase", "Paid", 2006, cart_items_table, "Opening Stock", item_total, 0, 0, item_total, null,0);
                    Reset_Fields();
                }
                else
                {
                    //Remove Item
                    Purchases.Purchases_Controller purchases_controller = new Purchases.Purchases_Controller();
                    Double qty = Convert.ToDouble(unit_qty_inp.Text);
                    Double packing_size = Convert.ToDouble(search_item_cmb.Properties.View.GetFocusedRowCellValue("Packing"));
                    Double Purchase_Rate = (packing_size * Convert.ToDouble(unit_cost_inp.Text));
                    if (purchases_controller.Get_Available_Stock(Convert.ToInt32(search_item_cmb.EditValue),Purchase_Rate,Convert.ToDouble(sale_rate_inp.Text)) > qty)
                    {
                        purchases_controller.Update_Purchase_Damaged_Stock(Convert.ToInt32(search_item_cmb.EditValue), Purchase_Rate, Convert.ToInt32(sale_rate_inp.Text), packing_size, qty);
                        Reset_Fields();
                    }
                    else
                    {
                        XtraMessageBox.Show("Stock was not enough available !");
                        unit_qty_inp.Focus();
                    }
                }
            } 
        }
        private void save_btn_Click(object sender, EventArgs e)
        {
            Save();
        }
        public void Reset_Fields()
        {
            task_cmb.SelectedIndex = 0;
            search_item_cmb.Text = null;
            model_cmb.Text = null;
            unit_qty_inp.Text = null;
            packing_qty_inp.Text = null;
            sale_rate_inp.Text = null;
            unit_cost_inp.Text = null;
            item_total_inp.Text = null;
            search_item_cmb.Focus();
        }

        private void cancel_btn_Click(object sender, EventArgs e)
        {
            this.Reset_Fields();
        }

        private void new_btn_Click(object sender, EventArgs e)
        {
            Stock_Adjustment form = new Stock_Adjustment();
            form.Show();
        }
        public void Reset_Item_Entries()
        {
            search_item_cmb.Text = "";
            packing_qty_inp.Text = "";
            sale_rate_inp.Text = "";
            unit_qty_inp.Text = null;
            unit_cost_inp.Text = null;
            item_total_inp.Text = "";
            search_item_cmb.Focus();
        }
        public void setEvaluatedValues()
        {
            if (packing_qty_inp.Text != "")
            {
                var qty = Convert.ToDouble(packing_qty_inp.Text);
                var purchase_rate_val = Convert.ToDouble(unit_cost_inp.Text);
                single_changed_temp_total = (qty * purchase_rate_val);
                Double item_packing_size = 0;
                item_packing_size = Convert.ToDouble(search_item_cmb.Properties.View.GetFocusedRowCellValue("Packing"));
                unit_qty_inp.Text = (item_packing_size * qty).ToString();
                item_total_inp.Text = (Convert.ToDouble(unit_qty_inp.Text) * Convert.ToDouble(unit_cost_inp.Text)).ToString();
            }
        }
        private void search_item_cmb_EditValueChanged(object sender, EventArgs e)
        {
            if (search_item_cmb.ContainsFocus == true)
            {
                if (search_item_cmb.EditValue != null)
                {
                    Purchases.Purchases_Controller purchases_controller = new Purchases.Purchases_Controller();
                    Item item = new Item();
                    item = purchases_controller.Get_Item(Convert.ToInt32(search_item_cmb.Properties.View.GetFocusedRowCellValue("Code")));
                    packing_qty_inp.Text = "1";
                    unit_qty_inp.Text = item.Packing.ToString();
                    sale_rate_inp.Text = item.Sale_Rate.ToString();
                    unit_cost_inp.Text = item.Unit_Cost.ToString();
                    item_total_inp.Text = item.Purchase_Rate.ToString();
                    packing_qty_inp.Focus();
                }
                else
                {
                    Reset_Item_Entries();
                }
            }
        }

        private void packing_qty_inp_EditValueChanged(object sender, EventArgs e)
        {
            if (packing_qty_inp.ContainsFocus == true)
            {
                if (packing_qty_inp.Text != "")
                {
                    Double item_qty = Convert.ToDouble(packing_qty_inp.Text);
                    if (item_qty > 0)
                    {
                        setEvaluatedValues();
                    }
                }
            }
        }

        private void unit_qty_inp_EditValueChanged(object sender, EventArgs e)
        {
            if (unit_qty_inp.ContainsFocus == true)
            {
                if (unit_qty_inp.Text != "")
                {
                    Double unit_qty = Convert.ToDouble(unit_qty_inp.Text);
                    if (unit_qty > 0)
                    {
                        Double packing_size = Convert.ToDouble(search_item_cmb.Properties.View.GetFocusedRowCellValue("Packing"));
                        packing_qty_inp.Text = (unit_qty / packing_size).ToString();
                        setEvaluatedValues();
                    }
                }
            }
        }

        private void unit_cost_inp_EditValueChanged(object sender, EventArgs e)
        {
            if (unit_cost_inp.ContainsFocus == true)
            {
                if (unit_cost_inp.Text != "" && unit_cost_inp.Text != ".")
                {
                    Double uc = Convert.ToDouble(unit_cost_inp.Text);
                    if (uc >= 0)
                    {
                        setEvaluatedValues();
                    }
                }
            }
        }

        private void Stock_Adjustment_KeyDown(object sender, KeyEventArgs e)
        {
            if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
            if (e.KeyCode == Keys.Escape && search_item_cmb.Text != "")
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
        }

