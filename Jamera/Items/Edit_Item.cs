        public void Update()
        {
            if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter name of item !");
                name_inp.Focus();
            }
            else if (packing_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter packing size !");
                packing_inp.Focus();
            }
            else if (purch_rate_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter purchase rate !");
                purch_rate_inp.Focus();
            }
            else if (unit_cost_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter unit cost !");
                unit_cost_inp.Focus();
            }
            else if (sale_rate_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter sale rate of packing !");
                sale_rate_inp.Focus();
            }
            else
            {
                int Unit_Id = -1;
                int Model_Id = -1;
                int Category_Id = -1;
                int Group_Id = -1;
                int Manufacturer_Id = -1;
                Double Sale_Discount = 0;
                Double Reorder_Level = 0;
                bool Is_Active = false;
                int Location = -1;
                int Rack_Id = -1;
                int Barcode_Id = -1;
                Byte Picture = Byte.MinValue;
                if (unit_cmb.Text != "")
                {
                    Unit_Id = Convert.ToInt32(unit_cmb.EditValue);
                }
                if(model_cmb.Text != "")
                {
                    Model_Id = Convert.ToInt32(model_cmb.EditValue);
                }
                if (category_cmb.Text != "")
                {
                    Category_Id = Convert.ToInt32(category_cmb.EditValue);
                }
                if (group_cmb.Text != "")
                {
                    Group_Id = Convert.ToInt32(group_cmb.EditValue);
                }

                if (manufac_cmb.Text != "")
                {
                    Manufacturer_Id = Convert.ToInt32(manufac_cmb.EditValue);
                }
                if (sale_disc_inp.Text != "")
                {
                    Sale_Discount = Convert.ToDouble(sale_disc_inp.Text);
                }
                if (reorder_level_inp.Text != "")
                {
                    Reorder_Level = Convert.ToDouble(reorder_level_inp.Text);
                }
                if (is_active_chbx.Checked == true)
                {
                    Is_Active = true;
                }
                Items_Controller items_controller = new Items_Controller();
                if (items_controller.Exists(this.id,name_inp.Text,Model_Id) != true)
                {
                    bool inserted_rec_id = items_controller.Update(this.id,name_inp.Text,unicode_inp.Text, Convert.ToDouble(purch_rate_inp.Text), Convert.ToDouble(sale_rate_inp.Text), Convert.ToDouble(unit_cost_inp.Text), Convert.ToDouble(packing_inp.Text), Barcode_Id, Picture, Unit_Id, Group_Id, Category_Id, Manufacturer_Id, -1, 0, Sale_Discount, Reorder_Level, 0, false, false, Is_Active, false, Rack_Id, Location,Model_Id, Convert.ToInt32(no_of_installments_inp.Text), Convert.ToDouble(advance_rate_inp.Text), Convert.ToDouble(monthly_emi_rate_inp.Text), Convert.ToDouble(cash_rate_inp.Text));
                    if (inserted_rec_id == true)
                    {
                        this.Close();
                    }
                    else
                    {
                        XtraMessageBox.Show("Something went wrong !");
                    }
                }
                else
                {
                    XtraMessageBox.Show("Item already exists !");
                }

            }
        }
