        private void gridView7_CustomDrawGroupRow(object sender, DevExpress.XtraGrid.Views.Base.RowObjectCustomDrawEventArgs e)
        {
            GridGroupRowInfo info = e.Info as GridGroupRowInfo;
            // DevExpress.XtraGrid.Views.Grid.ViewInfo.GridGroupRowInfo myinfo = e.Info as DevExpress.XtraGrid.Views.Grid.ViewInfo.GridGroupRowInfo;
            if (info == null) return;

            if (info.Level == 0)
            {
                info.GroupText = "Date: " + Convert.ToDateTime(info.EditValue).ToString("dd-MM-yyyy");
            }

            // Only apply to the Date level (Level 1)
            if (info.Level == 1)
            {
                // We use 'Max' summary because Paid/Total is the same for all items in one bill
                double items_qty = Convert.ToDouble(gridView7.GetGroupSummaryValue(e.RowHandle, (GridGroupSummaryItem)gridView7.GroupSummary[0]));

                int childRowHandle = gridView7.GetChildRowHandle(e.RowHandle, 0);
                string Code = "[Code: " + gridView7.GetRowCellValue(childRowHandle, "Code")?.ToString() + "]" ?? "";
                string gatepass = gridView7.GetRowCellValue(childRowHandle, "Gatepass.No").ToString() != "" ? "         [Gatepass.No: " + gridView7.GetRowCellValue(childRowHandle, "Gatepass.No")?.ToString() + "]" : "";
                string name = gridView7.GetRowCellValue(childRowHandle, "Name").ToString() != "" ? "          [Name: " + gridView7.GetRowCellValue(childRowHandle, "Name")?.ToString() + "]" : "";
                string remarks = gridView7.GetRowCellValue(childRowHandle, "Remarks").ToString() != "" ? ("          [Remarks: " + gridView7.GetRowCellValue(childRowHandle, "Remarks")?.ToString() + "]") : "";

                info.GroupText = $"Code: {Code}{gatepass}{name}         [Total Quantity: {items_qty}]{remarks}";
            }
        }

