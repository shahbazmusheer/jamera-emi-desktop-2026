        public void ExecuteResponsiveStockSearch()
        {
            // 1. Define SQL constant parts (using your new query)
            string selectPart = @"
        SELECT 
            FORMAT(CONVERT(DATETIME, st.date, 103), 'dd-MM-yyyy') as 'Date',
            st.id as 'Code',
            st.name as 'Name',    
            COALESCE(from_stores.name,  'Purchases ('+suppliers.name+')') as 'From.Store',
            from_stores.name as 'From.Store',
            from_stores.area_code as 'From.Area.Code',
            COALESCE(to_stores.name,  'Purchases ('+suppliers.name+')') as 'To.Store',
            to_stores.area_code as 'To.Area.Code',
            st.fuel_expenses_amount as 'Fuel Exp',
            st.remarks as 'Remarks',
            st.gate_pass_no as 'Gatepass.No',
            ac.name as 'Paid By',
            items.id as 'Item.Code',
            items.name as 'Item',
            models.name as 'Model',
            sti.sale_rate as 'Sale.Rate',
            SUM(sti.stock_in) as 'Qty',
            sti.returned as 'Returned',
            sti.remarks as 'Item.Remarks' ";

            string joinPart = @"
        FROM stock_transactions as st 
        LEFT JOIN stores as from_stores ON st.from_store = from_stores.id 
        LEFT JOIN stores as to_stores ON st.to_store = to_stores.id 
        LEFT JOIN accounts as ac ON st.paid_by_ac_id = ac.id
        INNER JOIN stock_transaction_items as sti ON st.id = sti.stock_transaction_id
        LEFT JOIN purchases as p ON sti.purchase_id = p.id
        LEFT JOIN accounts as suppliers ON p.supplier_id = suppliers.id
        LEFT JOIN items ON sti.item_id = items.id
        LEFT JOIN item_models as models ON items.model_id = models.id ";

            string groupByPart = @"
        GROUP BY 
            st.date, st.id, st.name, st.remarks, st.gate_pass_no,
            from_stores.name, from_stores.area_code, 
            to_stores.name, to_stores.area_code, 
            st.fuel_expenses_amount, ac.name,
            suppliers.name,
            items.id, items.name, models.name, 
            sti.sale_rate, sti.returned, sti.remarks";

            // 2. Build dynamic filters
            List<string> filters = new List<string>();

            // A. Item Filter
            if (search_items_history_cmb.EditValue != null && search_items_history_cmb.Text != "")
            {
                filters.Add($"items.id = {Convert.ToInt32(search_items_history_cmb.EditValue)}");
            }

            // B. Responsive Store Logic
            var fStore = item_from_store_cmb.EditValue;
            var tStore = item_to_store_cmb.EditValue;

            if(item_store_chkbx.CheckState == CheckState.Checked)
            {
                if (fStore != null && (tStore == null || tStore.ToString() == ""))
                {
                    if (Convert.ToInt32(fStore) == -1) 
                    {
                        fStore = "is null";
                    }
                    else
                    {
                        fStore = "=" + fStore;
                    }
                    // Only From Store selected: check if it exists in either column
                    filters.Add($"(st.from_store {fStore} OR st.to_store {fStore})");
                }
                else if (fStore != null && tStore != null)
                {
                    if (Convert.ToInt32(fStore) != -1)
                    {
                        fStore = "="+fStore;
                    }
                    else
                    {
                        fStore = "is null";
                    }
                    if (Convert.ToInt32(tStore) != -1)
                    {
                        tStore = "="+tStore;
                    }
                    else
                    {
                        tStore = "is null";
                    }

                        filters.Add($"(st.from_store {fStore} AND st.to_store {tStore})");
                    // Both selected: Specific From -> To match
                }
                else if (tStore != null) 
                {
                    if (Convert.ToInt32(tStore) == -1) tStore = "is null";
                    else { tStore =  "="+tStore; }
                        // Only To Store selected
                        filters.Add($"st.to_store {tStore}");
                }
            }

            // C. Date Range Filter
            if (item_date_chkbx.CheckState == CheckState.Checked) 
            {
                if (!string.IsNullOrEmpty(item_from_date_picker.Text) && !string.IsNullOrEmpty(item_to_date_picker.Text))
                {
                    filters.Add($"(CONVERT(DATETIME, st.date, 103) >= CONVERT(DATETIME, '{item_from_date_picker.Text}', 103) " +
                                $"AND CONVERT(DATETIME, st.date, 103) <= CONVERT(DATETIME, '{item_to_date_picker.Text}', 103))");
                }
            }

            // D. Gate Pass Filter (Partial search)
            if (!string.IsNullOrEmpty(gate_pass_no_inp.Text))
            {
                filters.Add($"st.gate_pass_no LIKE '%{gate_pass_no_inp.Text}%'");
            }

            // 3. Assemble and Execute
            string whereClause = (filters.Count > 0) ? " WHERE " + string.Join(" AND ", filters) : "";
            string finalSql = selectPart + joinPart + whereClause + groupByPart + " ORDER BY CONVERT(DATETIME, st.date, 103) DESC, st.id DESC;";

            try
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Name = "Query";
                query.Sql = finalSql;
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
            }
            catch (Exception ex)
            {
                XtraMessageBox.Show("Stock Transaction Search Failed: " + ex.Message);
            }
        }

