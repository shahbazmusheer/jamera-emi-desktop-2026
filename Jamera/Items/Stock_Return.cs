        private void store_cmb_EditValueChanged(object sender, EventArgs e)
        {
            if (store_cmb.ContainsFocus == true)
            {
                if (store_cmb.Text != "")
                {
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_1"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT rank() over(order by sti.item_id,items.name,models.name,sti.sale_rate) as 'Sr.No',sti.item_id as 'Code',items.name as 'Item',models.name as 'Model',sti.sale_rate as 'Sale Rate',i_u.name as 'Unit',items.packing as 'Packing',SUM(sti.stock_in - (sti.sold_out + sti.returned + sti.transfered)) as 'Stock' FROM stock_transaction_items as sti left join items on sti.item_id=items.id left join item_units as i_u on items.unit_id=i_u.id left join item_models as models on items.model_id=models.id WHERE ((sti.stock_in - (sti.sold_out + sti.returned + sti.transfered) ) > 0) and sti.store_id='" + Convert.ToInt32(store_cmb.EditValue) + "' GROUP BY sti.item_id,items.name,sti.sale_rate,i_u.name,items.packing,models.name";
                    query.Name = "Query_1";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                    search_item_cmb.Refresh();
                }
                else
                {
                    sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query_1"]);
                    CustomSqlQuery query = new CustomSqlQuery();
                    query.Sql = @"SELECT rank() over(order by sti.item_id,items.name,models.name,sti.sale_rate) as 'Sr.No',sti.item_id as 'Code',items.name as 'Item',models.name as 'Model',sti.sale_rate as 'Sale Rate',i_u.name as 'Unit',items.packing as 'Packing',SUM(sti.stock_in - (sti.sold_out + sti.returned + sti.transfered)) as 'Stock' FROM stock_transaction_items as sti left join items on sti.item_id=items.id left join item_units as i_u on items.unit_id=i_u.id left join item_models as models on items.model_id=models.id WHERE ((sti.stock_in - (sti.sold_out + sti.returned + sti.transfered) ) > 0) GROUP BY sti.item_id,items.name,sti.sale_rate,i_u.name,items.packing,models.name";
                    query.Name = "Query_1";
                    sqlDataSource1.Queries.Add(query);
                    sqlDataSource1.RebuildResultSchema();
                    sqlDataSource1.Fill();
                    search_item_cmb.Refresh();
                }
            }
        }

