        private void opening_quantity_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;
            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            int dot_counter = opening_quantity_inp.Text.Count(f => f == '.');

            if ((opening_quantity_inp.Text.Length <= 0 && ch == 46) || (dot_counter > 0 && ch == 46))
            {
                e.Handled = true;
            }
            if (ch == MoveToNextControl_KeyValue)
            {
                opening_rate_inp.Focus();
            }
        }

