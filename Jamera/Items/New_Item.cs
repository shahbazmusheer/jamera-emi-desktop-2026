        private void calculateNoOfInstallments()
        {
            try
            {
                // Use double.TryParse to prevent crashes on empty strings or non-numeric input
                double totalEmiPrice = 0;
                double advanceAmount = 0;
                double monthlyInstallment = 0;

                double.TryParse(sale_rate_inp.Text, out totalEmiPrice);
                double.TryParse(advance_price_inp.Text, out advanceAmount);

                // This is the "Monthly EMI" the customer will pay
                // Depending on your UI, this might be a different control name
                double.TryParse(emi_price_inp.Text, out monthlyInstallment);

                if (monthlyInstallment > 0)
                {
                    double remainingBalance = totalEmiPrice - advanceAmount;

                    // Example: 10,000 balance / 3,000 per month = 3.33 -> 4 Installments
                    double count = remainingBalance / monthlyInstallment;

                    // Math.Ceiling rounds UP to the nearest whole number
                    no_of_installments_inp.Text = Math.Ceiling(count).ToString();
                }
                else
                {
                    no_of_installments_inp.Text = "0";
                }
            }
            catch (Exception)
            {
                no_of_installments_inp.Text = "0";
            }
        }

