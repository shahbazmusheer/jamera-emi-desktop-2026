        private void purch_rate_inp_EditValueChanged(object sender, EventArgs e)
        {
            if (purch_rate_inp.Text != "" && packing_inp.Text != "." && packing_inp.Text != "")
            {
                Double purchase_rate_inp = Convert.ToDouble(purch_rate_inp.Text);
                Double packing_qty = Convert.ToDouble(packing_inp.Text);
                if (purchase_rate_inp > 0 && packing_qty > 0)
                {
                    Double res = purchase_rate_inp / packing_qty;
                    unit_cost_inp.Text = string.Format("{0:0,0.00}", Double.Parse(res.ToString()));
                }
            }
        }

