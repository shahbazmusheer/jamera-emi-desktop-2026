using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Drawing;
using System.Data;
using System.Text;
using System.Linq;
using System.Threading.Tasks;
using System.Windows.Forms;
using DevExpress.XtraEditors;

namespace Jamera.Complaints
{
    public partial class New_Complaint : DevExpress.XtraEditors.XtraUserControl
    {
        Aggrements.Aggrements_Controller aggrements_controller = new Aggrements.Aggrements_Controller();
        public New_Complaint()
        {
            InitializeComponent();
            electrition_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
            date_picker.EditValue = DateTime.Now;
            status_cmb.SelectedIndex = 0;
            // This line of code is generated by Data Source Configuration Wizard
            // Fill a SqlDataSource
            sqlDataSource1.Fill();
        }
        public void Save()
        {
            if(date_picker.Text == "")
            {
                XtraMessageBox.Show("Please select date !");
                date_picker.ShowPopup();
                date_picker.Focus();
            }else if(electrition_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select electrition !");
                electrition_cmb.ShowPopup();
                electrition_cmb.Focus();
            }else
            {
                Aggrements.Aggrement aggrement = aggrements_controller.Get_Aggrement_By_Ref_No(aggrement_id_inp.Text);
                if (aggrement.Aggrement_Id <= 0)
                {
                    XtraMessageBox.Show("Ref.No is not relating any agreement! Please enter valid Ref.No !");
                    aggrement_id_inp.Focus();
                }
                else
                {
                    Complaints_Controller complaints_controller = new Complaints_Controller();
                    int complaint_id = complaints_controller.Store(Convert.ToInt32(aggrement_id_inp.Text), Convert.ToInt32(electrition_cmb.EditValue), Convert.ToDateTime(date_picker.Text), status_cmb.Text, description_inp.Text);
                    if (complaint_id > -1)
                    {
                        Reset_Fields();
                    }
                }
            }
        }
        public void Reset_Fields()
        {
            electrition_cmb.Text = null;
            status_cmb.SelectedIndex = 0;
            description_inp.Text = null;
            aggrement_id_inp.Text = null;
        }
        private void save_btn_Click(object sender, EventArgs e)
        {
            Save();
        }

        private void New_Complaint_SizeChanged(object sender, EventArgs e)
        {
            electrition_cmb.Properties.PopupFormSize = new Size(this.Width, 280);
        }
    }
}
