        public void Send_Msg()
        {
            send_btn.Enabled = false;
            gridView3.OptionsBehavior.Editable = false;
            message_inp.ReadOnly = true;
            DataTable tmp_table = Contacts_Table.Copy();
            int deleted_entries_counter = 0;
            for (int i = 0; i < Contacts_Table.Rows.Count; i++)
            {
                if (!(gridView3.IsRowSelected(i) == true))
                {
                    int INDEX_TO_DEL = i - deleted_entries_counter;
                    tmp_table.Rows.RemoveAt(INDEX_TO_DEL);
                    deleted_entries_counter = deleted_entries_counter + 1;
                }
            }

            progress_status_lable.Text = "Messages Sending ... ";
            if (SMS_Thread.ThreadState == ThreadState.Unstarted || SMS_Thread.ThreadState == ThreadState.Aborted || SMS_Thread.ThreadState == ThreadState.Stopped)
            {
                int store_id = -1;
                String Group_Name = null;
                String Message_Type = null;
                String Message_Text = null;
                String SMS_Gateway = null;
                String Phone_Options = null;
                if (store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }

                Group_Name ="Customers ( Debitors )";

                if (sms_gateway_cmb.Text != "")
                {
                    SMS_Gateway = sms_gateway_cmb.Text;
                }
                if (phones_options_cmb.Text != "")
                {
                    Phone_Options = phones_options_cmb.Text;
                }
                Message_Text = message_inp.Text;
                Message_Type = messages_type_cmb.Text;
                progress_panel.Visible = true;
                SMS_Thread = new Thread(() => Send_Message_To_Numbers(store_id, Group_Name, Message_Type, Message_Text, SMS_Gateway, Phone_Options, tmp_table));
                SMS_Thread.Start();
            }
            //Send Messages List TO Thread
        }
