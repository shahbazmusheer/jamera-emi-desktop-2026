        public void Controls_List(object sender, KeyEventArgs e)
        {

            if (e.KeyCode == Keys.Escape && (name_inp.Text != ""))
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
            else if (e.KeyCode == Keys.F6 || (e.Control && e.KeyCode == Keys.N))
            {
                UC_Opener_Form form = new UC_Opener_Form("New Guarrantor", new New_Guardian(Convert.ToInt32(store_cmb.EditValue)));
                form.Show(this);
            }
            else if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
            else if (e.Control && e.Alt && e.KeyCode == Keys.G)
            {
                Account guarrantor = accounts_controller.Get_Last_Saved_Account(1010, Convert.ToInt32(store_cmb.EditValue));
                setDetails(guarrantor);
            }
            else if (e.Control && e.Alt && e.KeyCode == Keys.C)
            {
                Account customer = accounts_controller.Get_Last_Saved_Account(1002, Convert.ToInt32(store_cmb.EditValue));
                setDetails(customer);
            }
        }

        private void setDetails(Account guardian, string source = null)
        {
            Reset_Loadable_Fields();
            if (source != null) {
                name_inp.Text = guardian.Account_Name;
                father_name_inp.Text = guardian.Father_Name;
                if (guardian.Age != -1)
                {
                    age_inp.Text = guardian.Age.ToString();
                }
                //store_cmb.EditValue = Convert.ToDecimal(guardian.Store_Id);
                cost_inp.Text = guardian.Cast;
                profession_inp.Text = guardian.Profession;
                var id_card_no = guardian.Id_Card_No;
                if (id_card_no != "")
                {
                    string id_card_01 = id_card_no.Split('-')[0];
                    string id_card_02 = id_card_no.Split('-')[1];
                    string id_card_03 = id_card_no.Split('-')[2];
                    id_card_1_inp.Text = id_card_01;
                    id_card_2_inp.Text = id_card_02;
                    id_card_3_inp.Text = id_card_03;
                }
                business_address_inp.Text = guardian.Office_Address;
                home_address_inp.Text = guardian.Home_Address;
                permanent_address_inp.Text = guardian.Permanent_Address;
                office_phone_inp.Text = guardian.Office_Phone;
                home_phone_inp.Text = guardian.Home_Phone;
            } else
            {
                if (Settings.Default.load_prev_acc_name) name_inp.Text = guardian.Account_Name;
                if (Settings.Default.load_prev_acc_father_name) father_name_inp.Text = guardian.Father_Name;
                if (guardian.Age != -1 && Settings.Default.load_prev_acc_age)
                {
                    age_inp.Text = guardian.Age.ToString();
                }
                //store_cmb.EditValue = Convert.ToDecimal(guardian.Store_Id);
                if (Settings.Default.load_prev_acc_cast) cost_inp.Text = guardian.Cast;
                if (Settings.Default.load_prev_acc_profession) profession_inp.Text = guardian.Profession;
                var id_card_no = guardian.Id_Card_No;
                if (id_card_no != "" && Settings.Default.load_prev_acc_cnic)
                {
                    string id_card_01 = id_card_no.Split('-')[0];
                    string id_card_02 = id_card_no.Split('-')[1];
                    string id_card_03 = id_card_no.Split('-')[2];
                    id_card_1_inp.Text = id_card_01;
                    id_card_2_inp.Text = id_card_02;
                    id_card_3_inp.Text = id_card_03;
                }
                if (Settings.Default.load_prev_acc_business_address) business_address_inp.Text = guardian.Office_Address;
                if (Settings.Default.load_prev_acc_home_address) home_address_inp.Text = guardian.Home_Address;
                if (Settings.Default.load_prev_acc_permanent_address) permanent_address_inp.Text = guardian.Permanent_Address;
                if (Settings.Default.load_prev_acc_office_phone) office_phone_inp.Text = guardian.Office_Phone;
                if (Settings.Default.load_prev_acc_home_phone) home_phone_inp.Text = guardian.Home_Phone;
            }
        }
