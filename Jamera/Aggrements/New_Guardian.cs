        public void Save()
        {
            if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter guarrantor name !");
                name_inp.Focus();
            }
            else if (father_name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter guarrantor's father name !");
                father_name_inp.Focus();
            }
            else if (father_name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter guarrantor's father name !");
                father_name_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_1_inp.Text.Length != 5))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_1_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_2_inp.Text.Length != 7))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_2_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_3_inp.Text.Length != 1))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_3_inp.Focus();
            }
            else if (store_cmb.Text == "")
            {
                XtraMessageBox.Show("Please select a specific store!");
                store_cmb.Focus();
                store_cmb.ShowPopup();
            }
            else
            {
                
                int store_id = -1;
                int age = -1;
                if(store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }

                if(age_inp.Text != "")
                {
                    age = Convert.ToInt32(age_inp.Text);
                }
                String id_card_no_val = id_card_1_inp.Text + "-" + id_card_2_inp.Text + "-" + id_card_3_inp.Text;
                if (accounts_controller.Id_Card_Exists(id_card_no_val, 1010, store_id) != true)
                {
                    int inserted_record_id = accounts_controller.Store(name_inp.Text, null,1010, "Guardians ( Debitors )","DR",office_phone_inp.Text,permanent_address_inp.Text,description_inp.Text,0,store_id,father_name_inp.Text,age,cost_inp.Text,profession_inp.Text,id_card_no_val,business_address_inp.Text,home_address_inp.Text,home_phone_inp.Text);
                    if (inserted_record_id > 0)
                    {
                        if(Do_Selection == true)
                        {
                            new_aggreement.Save_Guardian_Callback(inserted_record_id);
                            this.us_opener.Close();
                        }
                        if (edit_aggrement_refresh == true)
                        {
                            edit_aggreement.sqlDataSource1.RebuildResultSchema();
                            edit_aggreement.sqlDataSource1.Fill();
                            edit_aggreement.guardian_cmb.Refresh();
                            edit_aggreement.guardian_cmb.EditValue = inserted_record_id;
                            this.us_opener.Close();
                        }
                        Reset_Fields();
                    }
                    else
                    {
                        XtraMessageBox.Show("Something went wrong !");
                    }
                }
                else
                {
                    XtraMessageBox.Show("Another Guarrantor already exists with same ID Card!");
                }
            }
        }
