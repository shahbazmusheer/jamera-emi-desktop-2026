        public void ApplyGridStyles()
        {
            // 1. Create a new Style Format Condition
            StyleFormatCondition cn = new StyleFormatCondition();

            // 2. Specify the column to check
            cn.Column = emi_dues_container.Columns["Received Amount"];

            // 3. Define the condition (Paid Amount > 0)
            cn.Condition = FormatConditionEnum.Greater;
            cn.Value1 = 0;

            // 4. Set the appearance
            cn.Appearance.BackColor = Color.LightGreen;
            cn.Appearance.ForeColor = Color.DarkGreen;
            cn.Appearance.Font = new Font(emi_dues_container.Appearance.Row.Font, FontStyle.Italic);
            cn.Appearance.Options.UseBackColor = true;
            cn.Appearance.Options.UseForeColor = true;
            cn.Appearance.Options.UseFont = true;

            // 5. Apply to the whole row (set to false if you only want the specific cell colored)
            cn.ApplyToRow = true;

            // 6. Add it to the grid
            emi_dues_container.FormatConditions.Add(cn);

            // Inside your grid setup code
            StyleFormatCondition retFix = new StyleFormatCondition();
            retFix.Column = emi_dues_container.Columns["Is Return Fixed"];
            retFix.Condition = FormatConditionEnum.Equal;
            retFix.Value1 = "1";
            retFix.Appearance.BackColor = Color.DeepSkyBlue;
            retFix.Appearance.ForeColor = Color.White;
            retFix.Appearance.Options.UseBackColor = true;
            retFix.Appearance.Options.UseForeColor = true;
            retFix.Appearance.Options.UseFont = true;
            retFix.Appearance.Font = new Font(emi_dues_container.Appearance.Row.Font, FontStyle.Italic);
            retFix.ApplyToRow = true;
            emi_dues_container.FormatConditions.Add(retFix);
        }
        public void Refresh_Return_Summary_Calculations()
        {
            // 1. Sum up Items in the return grid
            int totalReturnItemsQty = 0;
            double totalReturnItemValue = 0;
            double totalPaidAmount = 0;
            double totalRemainingBalance = 0;
            for (int i = 0; i < gridView4.RowCount; i++)
            {
                totalReturnItemsQty += Convert.ToInt32(gridView4.GetRowCellValue(i, "Quantity"));
                totalReturnItemValue += Convert.ToDouble(gridView4.GetRowCellValue(i, "Total"));
                totalPaidAmount += Convert.ToDouble(gridView4.GetRowCellValue(i, "Paid"));
                totalRemainingBalance += Convert.ToDouble(gridView4.GetRowCellValue(i, "Remaining"));
            }
            total_ret_items_qty_inp.Text = totalReturnItemsQty.ToString("0");
            total_returning_amt_inp.Text = totalReturnItemValue.ToString("0.00");
            total_paid_amt_inp.Text = totalPaidAmount.ToString("0.00");
            total_remaining_amt_inp.Text = totalRemainingBalance.ToString("0.00");

        }

        private void update_btn_Click(object sender, EventArgs e)
        {
            bool result = true;
            if(ref_no_inp.Text != "")
            {
                String ref_no = null;
                if(aggrement.Ref_No != "")
                {
                    ref_no = aggrement.Ref_No;
                }
                if(ref_no_inp.Text != ref_no)
                {
                    if (aggrements_controller.Aggrement_Ref_No_Exists(aggrement.Aggrement_Id, ref_no_inp.Text) == false)
                    {
                        aggrements_controller.Update_Aggrement_Ref_No(aggrement_id, ref_no_inp.Text);
                    }
                    else
                    {
                        result = false;
                        XtraMessageBox.Show("This Ref.No is related with another agreement !Please select different Ref.No.");
                    }
                }
            }
            else
            {
                aggrements_controller.Update_Aggrement_Ref_No(aggrement_id, "");
            }
            if(guardian_cmb.Text != "")
            {
                if (Convert.ToInt32(guardian_cmb.EditValue) != aggrement.Guardian_Id)
                {
                    aggrements_controller.Update_Aggrement_Guardian_Id(aggrement_id,Convert.ToInt32(guardian_cmb.EditValue));
                }
            }
            else
            {
                if (Convert.ToInt32(guardian_cmb.EditValue) != aggrement.Guardian_Id)
                {
                    aggrements_controller.Update_Aggrement_Guardian_Id(aggrement_id, -1);
                }
            }
            if (voucher_id_inp.Text != "")
            {
                String emi_no = null;
                if (aggrement.Ref_No != "")
                {
                    ref_no_inp.Text = aggrement.Ref_No;
                }
                if (voucher_id_inp.Text != emi_no)
                {
                    Vouchers.Vouchers_Controller vouchers_controller = new Vouchers.Vouchers_Controller();
                    int emi_voucher_id = vouchers_controller.Get_Valid_Emi_Store_Serial(Convert.ToInt32(store_cmb.EditValue), Convert.ToInt32(voucher_id_inp.Text), date_picker.DateTime);
                    if (emi_voucher_id > 0)
                    {
                       aggrements_controller.Update_Aggrement_EMI_No(aggrement_id, Convert.ToInt32(voucher_id_inp.Text), date_picker.DateTime, Convert.ToInt32(store_cmb.EditValue));
                    }
                    else
                    {
                        result = false;
                        XtraMessageBox.Show("The EMI serial number were not issue for this store. May be wrong serial number !");
                        voucher_id_inp.Focus();
                    }                    
                }
            }
            else
            {
                aggrements_controller.Update_Aggrement_EMI_No(aggrement_id, -1,  date_picker.DateTime, Convert.ToInt32(store_cmb.EditValue));
            }
            if (aggrement.Status != status_cmb.Text)
            {
                if (aggrements_controller.Update_Status(this.aggrement_id, status_cmb.Text) == true)
                {
                    update_btn.Enabled = false;
                    status_cmb.ReadOnly = true;
                }
            }
            if(aggrement.Remarks != remarks_inp.Text)
            {
                aggrements_controller.Update_Aggrement_Remarks(aggrement_id,remarks_inp.Text);
            }
            if(result == true)
            {
                XtraMessageBox.Show("Aggrement is updated !");
            }
        }

        private void delete_btn_Click(object sender, EventArgs e)
        {
            if (XtraMessageBox.Show("Are you sure, you want to delete this agreement?", "Warning", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes) return;
            if(ref_no_inp.Text != "")
            {
                if (aggrements_controller.Is_Aggrement_Deletable(ref_no_inp.Text) == true)
                {
                    if(aggrements_controller.Delete(aggrement_id) == true)
                    {
                        uc_opener.Close();
                    }
                }
                else
                {
                    if(XtraMessageBox.Show("Some transactions are relating to cash vouchers. Are you sure to delete this agreement!", "Warning Alert", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) == DialogResult.Yes)
                    {
                        if (aggrements_controller.Delete(aggrement_id) == true)
                        {
                            uc_opener.Close();
                        }
                    }
                }
            }
            else
            {
                if (aggrements_controller.Delete(aggrement_id) == true)
                {
                    uc_opener.Close();
                }
            }
        }

        private void total_amount_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8 || ch == 46))
            {
                e.Handled = true;
            }

            int dot_counter = total_amount_inp.Text.Count(f => f == '.');

            if ((total_amount_inp.Text.Length <= 0 && ch == 46) || (dot_counter > 0 && ch == 46))
            {
                e.Handled = true;
            }
        }

