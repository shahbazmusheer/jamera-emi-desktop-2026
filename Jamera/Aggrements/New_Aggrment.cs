        public void Calculate_EMI_Dues()
        {
            if (balance_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter above fields !");

            } else if (first_emi_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter first emi amount !");
                first_emi_inp.Focus();
            }
            else if (start_datepicker.Text == "")
            {
                XtraMessageBox.Show("Please select start date !");
                start_datepicker.Focus();
            }
            else if (frequency_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter frequency input !");
                frequency_inp.Focus();
            }
            else
            {
                int frequency = 0;
                String start_date;
                Double balance = 0;
                Double repeat_balance = 0;
                Double first_emi = 0;
                Double rest_emi = 0;
                emi_amounts_table.Clear();
                start_date = start_datepicker.Text;
                frequency = Convert.ToInt32(frequency_inp.Text);
                balance = Convert.ToDouble(balance_inp.Text);
                repeat_balance = balance;
                rest_emi = first_emi = Convert.ToDouble(first_emi_inp.Text);
                int i = 0;
                while (repeat_balance > 0)
                {
                    DataRow dr = emi_amounts_table.NewRow();
                    dr["EMI No"] = (i+1);
                    if (i == 0)
                    {
                        dr["Due Date"] = start_date;
                    }
                    else
                    {
                        DateTime emi_date = Convert.ToDateTime(start_date).AddMonths(i);
                        dr["Due Date"] = emi_date.ToString("dd-MM-yyyy");
                    }

                    if (repeat_balance > first_emi)
                    {
                        dr["Due Amount"] = first_emi;
                        repeat_balance = repeat_balance - first_emi;
                        dr["Balance"] = repeat_balance;
                    }
                    else
                    {
                        dr["Due Amount"] = repeat_balance;
                        repeat_balance = 0;
                        dr["Balance"] = repeat_balance;
                    }

                    emi_amounts_table.Rows.Add(dr);

                    i++;
                }
            }
        }

