        public void Controls_List(object sender, KeyEventArgs e)
        {

            if (e.KeyCode == Keys.Escape && (customer_cmb.Text != "" || store_cmb.Text != ""))
            {
                if (XtraMessageBox.Show("Are you sure, you want to cancel !", "Warning Alert", MessageBoxButtons.YesNo) != DialogResult.No)
                {
                    this.Reset_Fields();
                }
            }
            else if (e.KeyCode == Keys.F6 || (e.Control && e.Shift && e.KeyCode == Keys.C))
            {
                Add_New_Customer();
            }
            else if (e.KeyCode == Keys.F7 || (e.Control && e.Shift && e.KeyCode == Keys.G))
            {
                guardian_cmb.Focus();
                int temp_store_id = -1;
                if (store_cmb.Text != "")
                {
                    temp_store_id = Convert.ToInt32(store_cmb.EditValue);
                }
                New_Guardian new_guardian = new New_Guardian(temp_store_id);
                new_guardian.Do_Selection = true;
                new_guardian.new_aggreement = this;
                UC_Opener_Form form = new UC_Opener_Form("New Guarantor [Ref: "+ref_no_inp.Text+"]", new_guardian);
                new_guardian.us_opener = form;
                form.Show();
            }
            else if (e.Control && e.KeyCode == Keys.S)
            {
                this.Save();
            }
        }

