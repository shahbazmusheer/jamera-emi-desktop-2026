        public void Set_Final_Values_New()
        {
            try
            {
                // 1. Ensure Columns exist to prevent NullReferenceException
                if (gridView7.Columns["Total"] == null ||
                    gridView7.Columns["Advance"] == null ||
                    gridView7.Columns["Monthy EMI"] == null)
                    return;

                // 2. Initialize Summary Items
                GridSummaryItem summaryTotal = gridView7.Columns["Total"].SummaryItem;
                GridSummaryItem summaryAdv = gridView7.Columns["Advance"].SummaryItem;
                GridSummaryItem summaryEmi = gridView7.Columns["Monthy EMI"].SummaryItem;

                summaryTotal.SummaryType = DevExpress.Data.SummaryItemType.Sum;
                summaryAdv.SummaryType = DevExpress.Data.SummaryItemType.Sum;
                summaryEmi.SummaryType = DevExpress.Data.SummaryItemType.Sum;

                // 3. Declare variables and safely parse summary values
                double subTotals = 0;
                double advance = 0;
                double monthlyEmi = 0;

                // TryParse handles cases where the grid is empty (SummaryValue is null)
                double.TryParse(summaryTotal.SummaryValue?.ToString(), out subTotals);
                double.TryParse(summaryAdv.SummaryValue?.ToString(), out advance);
                double.TryParse(summaryEmi.SummaryValue?.ToString(), out monthlyEmi);

                // 4. Update UI Inputs with consistent formatting
                total_amount_inp.Text = subTotals.ToString("#,##0.00");
                advance_payment_inp.Text = advance.ToString("#,##0.00");
                first_emi_inp.Text = monthlyEmi.ToString("#,##0.00");

                // 5. Calculate and set Balance
                double balance = subTotals - advance;
                balance_inp.Text = balance.ToString("0.00");
            }
            catch (Exception ex)
            {
                // Log the error or handle it as per system requirements
                // System.Diagnostics.Debug.WriteLine("Error in Set_Final_Values: " + ex.Message);
            }
            finally
            {
                // Logic here always runs (e.g. updating a status bar or triggering a UI refresh)
            }
        }
