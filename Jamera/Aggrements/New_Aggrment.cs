        public void setEvaluatedValues()
        {
            try
            {
                double qty = 0;
                double saleRateVal = 0;
                double discountValueRs = 0;
                double subTotal = 0;
                double finalTotal = 0;

                // 1. Safe Parsing
                double.TryParse(item_qty_inp.Text, out qty);
                double.TryParse(sale_rate_inp.Text, out saleRateVal);
                double.TryParse(disc_rs_inp.Text, out discountValueRs);

                // 2. Calculate Sub-Total (Rate * Qty)
                subTotal = qty * saleRateVal;

                // 3. Discount Logic
                if (subTotal > 0)
                {
                    double discPercent = Math.Round(((discountValueRs / subTotal) * 100), 2);
                    if (!disc_percent_inp.ContainsFocus)
                    {
                        disc_percent_inp.Text = discPercent.ToString("0.00");
                    }
                    finalTotal = subTotal - discountValueRs;
                }
                else
                {
                    finalTotal = 0;
                    if (!disc_percent_inp.ContainsFocus) disc_percent_inp.Text = "0.00";
                }

                // 4. Update the scaled Advance and Monthly EMI based on Quantity
                // itemAdv and itemMonthlyEMI are the base rates set in item_cmb_EditValueChanged
                item_adv_inp.Text = (this.itemAdv * qty).ToString("#,##0.00");
                item_monthly_emi.Text = (this.itemMonthlyEMI * qty).ToString("#,##0.00");

                // 5. Update Final Item Total
                item_total.Text = finalTotal.ToString("#,##0.00");
            }
            catch (Exception ex)
            {
                // Fail silently or log error
            }
        }

