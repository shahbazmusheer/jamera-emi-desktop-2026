        private void id_card_1_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8))
            {
                e.Handled = true;
            }

            int digits_counter = id_card_1_inp.Text.Length;
            if (digits_counter == 5 && ch != 8)
            {
                e.Handled = true;
            }
            if (digits_counter == 4 && ch != 8)
            {
                id_card_2_inp.Focus();
            }
        }

        private void id_card_2_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8))
            {
                e.Handled = true;
            }

            int digits_counter = id_card_2_inp.Text.Length;
            if (id_card_2_inp.Text.Length == 0 && ch == 8)
            {
                id_card_1_inp.Focus();
            }
            if (digits_counter == 7 && ch != 8)
            {
                e.Handled = true;
            }
            if (digits_counter == 6 && ch != 8)
            {
                id_card_3_inp.Focus();
            }
        }

        private void id_card_3_inp_KeyPress(object sender, KeyPressEventArgs e)
        {
            Char ch = e.KeyChar;

            if (!(Char.IsDigit(ch) || ch == 13 || ch == 8))
            {
