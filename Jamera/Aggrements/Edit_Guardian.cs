        public void Load_Data()
        {
            //because having same features customers=guardians
            Accounts.Account guardian = accounts_controller.Get_Customer(guardian_id);
            name_inp.Text = guardian.Account_Name;
            father_name_inp.Text = guardian.Father_Name;
            if (guardian.Age != -1)
            {
                age_inp.Text = guardian.Age.ToString();
            }
            store_cmb.EditValue = Convert.ToDecimal(guardian.Store_Id);
            cost_inp.Text = guardian.Cast;
            profession_inp.Text = guardian.Profession;
            var id_card_no = guardian.Id_Card_No;
            if (id_card_no != "")
            {
                string id_card_01 = id_card_no.Split('-')[0];
                string id_card_02 = id_card_no.Split('-')[1];
                string id_card_03 = id_card_no.Split('-')[2];
                id_card_1_inp.Text = id_card_01;
                id_card_2_inp.Text = id_card_02;
                id_card_3_inp.Text = id_card_03;
            }
            business_address_inp.Text = guardian.Office_Address;
            home_address_inp.Text = guardian.Home_Address;
            permanent_address_inp.Text = guardian.Permanent_Address;
            office_phone_inp.Text = guardian.Office_Phone;
            home_phone_inp.Text = guardian.Home_Phone;
            description_inp.Text = guardian.Account_Remarks;
            current_balance_inp.Text = guardian.Balance.ToString();
        }
        public void Update()
        {
            if (name_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter customer name !");
                name_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_1_inp.Text.Length != 5))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_1_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_2_inp.Text.Length != 7))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_2_inp.Focus();
            }
            else if ((id_card_1_inp.Text != "" && id_card_2_inp.Text != "" && id_card_3_inp.Text != "") && (id_card_3_inp.Text.Length != 1))
            {
                XtraMessageBox.Show("Please enter valid id CNIC !");
                id_card_3_inp.Focus();
            }
            else
            {
                Accounts.Accounts_Controller accounts_controller = new Accounts.Accounts_Controller();
                int store_id = -1;
                int age = -1;
                if (age_inp.Text != "")
                {
                    age = Convert.ToInt32(age_inp.Text);
                }
                if(store_cmb.Text != "")
                {
                    store_id = Convert.ToInt32(store_cmb.EditValue);
                }
                String id_card_no_val = id_card_1_inp.Text + "-" + id_card_2_inp.Text + "-" + id_card_3_inp.Text;

                if (accounts_controller.Id_Card_Exists(guardian_id,id_card_no_val, 1010, store_id) != true)
                {
                    bool inserted_record_id = accounts_controller.Update(guardian_id, name_inp.Text, null, 1010, "Guardians ( Debitors )", "DR", office_phone_inp.Text, permanent_address_inp.Text, description_inp.Text, store_id, father_name_inp.Text, age, cost_inp.Text, profession_inp.Text, id_card_no_val, business_address_inp.Text, home_address_inp.Text, home_phone_inp.Text);
                    if (inserted_record_id == true)
                    {
                        this.uc_opener.Close();
                    }
                }
                else
                {
                    XtraMessageBox.Show("Another Guarrantor already exists with same ID Card!!");
                }
            }
        }
        private void update_btn_Click(object sender, EventArgs e)
