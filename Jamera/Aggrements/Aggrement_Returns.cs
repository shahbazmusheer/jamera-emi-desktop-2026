        public string AuditRefNumberSequencesAsString()
        {
            // Key: "AREA-YEAR", Value: List of Serial Numbers
            var sequences = new Dictionary<string, List<int>>();

            // processedAggCodes ensures we only count each Agreement once
            var processedAggCodes = new HashSet<string>();

            int absoluteMin = int.MaxValue;
            int absoluteMax = int.MinValue;
            string minRefStr = "---";
            string maxRefStr = "---";

            // 1. Loop through Grid Rows
            for (int i = 0; i < gridView1.DataRowCount; i++)
            {
                // Use the internal DB ID 'Code' to identify the unique agreement
                object aggCodeVal = gridView1.GetRowCellValue(i, "Code");
                if (aggCodeVal == null) continue;

                string aggCode = aggCodeVal.ToString();

                // UNIQUE CHECK: If we have already seen this agreement ID, skip to next row
                if (processedAggCodes.Contains(aggCode)) continue;
                processedAggCodes.Add(aggCode);

                // --- Logic below only runs ONCE per Agreement ---

                object refVal = gridView1.GetRowCellValue(i, "Ref.No");
                if (refVal == null || string.IsNullOrEmpty(refVal.ToString())) continue;

                string refNo = refVal.ToString();
                string[] parts = refNo.Split('-');

                if (parts.Length == 3)
                {
                    try
                    {
                        string areaPart = parts[0].Trim().ToUpper();
                        string yearPart = parts[1].Trim();
                        string areaYearKey = areaPart + "-" + yearPart;

                        int serialNum = int.Parse(parts[2].Trim());

                        if (!sequences.ContainsKey(areaYearKey))
                            sequences[areaYearKey] = new List<int>();

                        sequences[areaYearKey].Add(serialNum);

                        // Track Absolute Min/Max
                        if (serialNum < absoluteMin) { absoluteMin = serialNum; minRefStr = refNo; }
                        if (serialNum > absoluteMax) { absoluteMax = serialNum; maxRefStr = refNo; }
                    }
                    catch { }
                }
            }

            // 2. UPDATE UI LABELS
            // The Count of the HashSet is your unique agreement count
            total_aggrements_lbl.Text = processedAggCodes.Count.ToString();


            StringBuilder finalAlert = new StringBuilder();

            // 3. Analyze sequences for Gaps and Duplicates
            foreach (var entry in sequences)
            {
                string areaYear = entry.Key;
                List<int> serials = entry.Value;

                // Duplicate Check
                var duplicates = serials.GroupBy(x => x).Where(g => g.Count() > 1).Select(g => g.Key).ToList();

                // Missing Check (Between Min and Max found in this search)
                int currentGroupMin = serials.Min();
                int currentGroupMax = serials.Max();
                var missing = new List<int>();
                for (int check = currentGroupMin; check <= currentGroupMax; check++)
                {
                    if (!serials.Contains(check)) missing.Add(check);
                }

                if (duplicates.Count > 0 || missing.Count > 0)
                {
                    string areaMsg = $"\n[{areaYear}] -> ";
                    if (duplicates.Count > 0) areaMsg += "\n\tDUPLICATES (" + duplicates.Select(d => d.ToString("D2")).Count() + ") :" + string.Join(",", duplicates.Select(d => d.ToString("D2")));
                    if (missing.Count > 0) areaMsg += "\n\tMISSING (" + missing.Select(m => m.ToString("D2")).Count() + ") :" + string.Join(",", missing.Select(m => m.ToString("D2")));
                    finalAlert.AppendLine(areaMsg);
                }
            }

            // 4. Update Status Label
            if (finalAlert.Length > 0)
            {
                return "Sequence Error: \n" + finalAlert.ToString();

            }
            else
            {
                return "";
            }
        }


