        public void ExecuteResponsiveSearch()
        {
            // 1. Define the Base Query (Select + Joins)
            string baseQuery = @"
        SELECT 
            st.area_code as 'Area Code', 
            ar.return_date as 'Date', 
            ar.id as 'Code', 
            ar.ref_no as 'Ref.No', 
            cust.id as 'Cust.Code', 
            cust.name as 'Customer', 
            gr.id as 'Guarantor.Code', 
            gr.name as 'Guarantor', 
            ar.new_balance as 'Balance',
            itm.id as 'Item.Code', 
            itm.name as 'Item', 
            ari.sale_rate as 'Rate', 
            ari.quantity as 'Qty', 
            ari.sub_total as 'Total',
            ar.aggrement_total_amount as 'Agg. Total',
            ar.prev_balance as 'Prev. Balance'
        FROM agreement_returns ar
        INNER JOIN agreement_return_items ari ON ar.id = ari.aggrement_return_id
        LEFT JOIN items itm ON ari.item_id = itm.id
        LEFT JOIN accounts cust ON ar.customer_id = cust.id
        LEFT JOIN accounts gr ON ar.guardian_id = gr.id
        INNER JOIN stores st ON ar.store_id = st.id";

            // 2. Build the List of Filters based on UI state
            List<string> filters = new List<string>();

            // A. Filter by Agreement Reference Number (Manual Input)
            if (!string.IsNullOrEmpty(aggrement_id_inp.Text))
            {
                filters.Add($"ar.ref_no LIKE '%{aggrement_id_inp.Text.Trim()}%'");
            }

            // B. Filter by Customer
            if (by_customer_check.Checked && customer_search_cmb.EditValue != null && customer_search_cmb.Text != "")
            {
                filters.Add($"ar.customer_id = {Convert.ToInt32(customer_search_cmb.EditValue)}");
            }

            // C. Filter by Store
            if (stores_check.Checked && stores_cmb.EditValue != null && stores_cmb.Text != "")
            {
                filters.Add($"ar.store_id = {Convert.ToInt32(stores_cmb.EditValue)}");
            }

            // D. Filter by Item
            if (item_chkbx.Checked && items_cmb.EditValue != null && items_cmb.Text != "")
            {
                filters.Add($"ari.item_id = {Convert.ToInt32(items_cmb.EditValue)}");
            }

            // E. Filter by Date Range (return_date)
            if (by_date_check.Checked && !string.IsNullOrEmpty(from_date_picker.Text) && !string.IsNullOrEmpty(to_date_picker.Text))
            {
                filters.Add($"(CONVERT(DATETIME, ar.return_date, 103) >= CONVERT(DATETIME, '{from_date_picker.Text}', 103) " +
                            $"AND CONVERT(DATETIME, ar.return_date, 103) <= CONVERT(DATETIME, '{to_date_picker.Text}', 103))");
            }

            // 3. Assemble Final SQL
            string whereClause = filters.Count > 0 ? " WHERE " + string.Join(" AND ", filters) : "";
            string finalSql = baseQuery + whereClause + " ORDER BY ar.id DESC";

            // 4. Update the Data Source
            try
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Name = "Query";
                query.Sql = finalSql;

                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();

                Set_Sum(); // Recalculate footers for current results
            }
            catch (Exception ex)
            {
                XtraMessageBox.Show("Search failed: " + ex.Message, "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

