        public void Calculate_EMI_Dues()
        {
            if (balance_inp.Text == "")
            {
                XtraMessageBox.Show("Please enter above fields !");

            } else if (first_emi_inp.Text == "" && Convert.ToInt32(balance_inp.Text) > 0)
            {
                XtraMessageBox.Show("Please enter first emi amount !");
                first_emi_inp.Focus();
            }
            else if (start_datepicker.Text == "" && Convert.ToInt32(balance_inp.Text) > 0)
            {
                XtraMessageBox.Show("Please select start date !");
                start_datepicker.Focus();
            }
            else if (frequency_inp.Text == "" && Convert.ToInt32(balance_inp.Text) > 0)
            {
                XtraMessageBox.Show("Please enter frequency input !");
                frequency_inp.Focus();
            }
            else
            {
                int frequency = 0;
                String start_date;
                Double balance = 0;
                Double repeat_balance = 0;
                Double first_emi = 0;
                Double rest_emi = 0;
                emi_amounts_table.Clear();
                rem_emi_amounts_table.Clear();
                // Previously Paid Dues
                emi_amounts_table = aggrements_controller.Get_Aggrement_Paid_Dues_Table(aggrement);

                // Sale Return Adjustment Row
                DataRow ndr = rem_emi_amounts_table.NewRow();
                ndr["EMI No"] = (ret_emi_no_inp.Text != "") ? ret_emi_no_inp.Text : "-1";

                ndr["Sr.No"] = emi_amounts_table.Rows.Count + 1;
                ndr["Due Amount"] = repeat_balance;
                ndr["Due Date"] = return_date_picker.Text;
                ndr["Status"] = "Item Returned";
                ndr["Is Return Fixed"] = "1";
                ndr["Receipt Date"] = return_date_picker.Text;
                ndr["Balance"] = Convert.ToDouble(balance_inp.Text);
                ndr["Remarks"] = "Sale Return Adjustment";
                rem_emi_amounts_table.Rows.Add(ndr);

                repeat_balance = 0;

                // Remaining Dues
                start_date = start_datepicker.Text;
                frequency = Convert.ToInt32(frequency_inp.Text);
                balance = Convert.ToDouble(balance_inp.Text);
                repeat_balance = balance;
                rest_emi = first_emi = Convert.ToDouble(first_emi_inp.Text);
                int rows_count = emi_amounts_table.Rows.Count+2; 
                int i = 0;

                while (repeat_balance > 0)
                {
                    DataRow dr = rem_emi_amounts_table.NewRow();
                    dr["EMI No"] = DBNull.Value;
                    dr["Is Return Fixed"] = "-1";
                    dr["Sr.No"] = rows_count;
                    if (i == 0)
                    {
                        dr["Due Date"] = start_date;
                    }
                    else
                    {
                        DateTime emi_date = Convert.ToDateTime(start_date).AddMonths(i);
                        dr["Due Date"] = emi_date.ToString("dd-MM-yyyy");
                    }

                    if (repeat_balance > first_emi)
                    {
                        dr["Due Amount"] = first_emi;
                        repeat_balance = repeat_balance - first_emi;
                    }
                    else
                    {
                        dr["Due Amount"] = repeat_balance;
                        repeat_balance = 0;
                    }

                    rem_emi_amounts_table.Rows.Add(dr);

                    i++;
                    rows_count++;
                }

                foreach (DataRow row in rem_emi_amounts_table.Rows)
                {
                    emi_amounts_table.ImportRow(row);
                }

                emi_dues_container.DataSource = emi_amounts_table;
            }
        }

