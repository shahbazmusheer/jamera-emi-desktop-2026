        public void Refresh_Summary_Calculations()
        {
            // 1. Sum up Items in the return grid
            double totalReturnItemValue = 0;
            double totalPaidAmount = 0;
            double totalRemainingBalance = 0;
            for (int i = 0; i < gridView7.RowCount; i++)
            {
                totalReturnItemValue += Convert.ToDouble(gridView7.GetRowCellValue(i, "Total"));
                totalPaidAmount += Convert.ToDouble(gridView7.GetRowCellValue(i, "Paid"));
                totalRemainingBalance += Convert.ToDouble(gridView7.GetRowCellValue(i, "Remaining"));
            }
            total_amount_inp.Text = totalReturnItemValue.ToString("0.00");
            advance_payment_inp.Text = totalPaidAmount.ToString("0.00");
            total_rem_inp.Text = totalRemainingBalance.ToString("0.00");

            // 2. Get Header Info
            double currentDebt = 0;
            double.TryParse(remaining_bal_inp.Text, out currentDebt);

            double moneyAlreadyPaidForReturningItem = 0;
            double.TryParse(advance_payment_inp.Text, out moneyAlreadyPaidForReturningItem);

            // 3. New Balance Calculation
            // We give customer credit for the UNPAID part of the item: (Total - Paid)
            double creditAmount = totalReturnItemValue - moneyAlreadyPaidForReturningItem;
            double proposedNewBalance = currentDebt - creditAmount;

            // Set bottom balance for EMI generation
            balance_inp.Text = proposedNewBalance.ToString("0.00");
        }
        public void Add_Item_To_Cart()
        {
            if(item_cmb.Text != "")
            {
                if (If_Item_Exists_In_Cart(Convert.ToInt32(item_cmb.EditValue)) == true)
                {
                    XtraMessageBox.Show("Item already exists in cart !");
                    Reset_Item_Entries();
                    item_cmb.ShowPopup();
                }
                else
                {
                    if (Convert.ToDouble(item_qty_inp.Text) <= Max_Item_Qty)
                    {
                        DataRow dr = agreement_items_table.NewRow();
                        GridView view = item_cmb.Properties.View;
                        string fieldName = "Code"; // or other field name  
                        int item_code = Convert.ToInt32(view.GetRowCellValue(item_cmb.Properties.GetIndexByKeyValue(item_cmb.EditValue), fieldName));
                        dr["Code"] = item_code;
                        dr["Item"] = item_cmb.Text;
                        dr["Model"] = model_cmb.Text;
                        dr["Quantity"] = Convert.ToDouble(item_qty_inp.Text);
                        dr["Sale Rate"] = Convert.ToDouble(sale_rate_inp.Text);
                        dr["Total"] = Convert.ToDouble(item_total.Text);
                        dr["Paid"] = (item_total_paid_inp.Text == "") ? 0 : Convert.ToDouble(item_total_paid_inp.Text);
                        dr["Remaining"] = (item_rem_inp.Text == "") ? 0 : Convert.ToDouble(item_rem_inp.Text);
                        dr["Original Sale Rate"] = this.orignal_sale_rate;
                        agreement_items_table.Rows.Add(dr);
                        Reset_Item_Entries();
                        this.orignal_sale_rate = 0;
                        Refresh_Summary_Calculations();
                        ret_emi_no_inp.Focus();
                    }
                    else
                    {
                        XtraMessageBox.Show("You can return maximum "+Max_Item_Qty+" quantity of this item !");
                        item_qty_inp.Focus();
                    }

                }
            }
        }

