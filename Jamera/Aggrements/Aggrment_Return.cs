        public void Load_Sale_Data(string Ref_No)
        {
            Aggrement agg = aggrements_controller.Get_Aggrement_By_Ref_No(Ref_No);
            if (agg.Aggrement_Id > 0)
            {
                this.returning_aggrement = agg;
                aggrement = agg;
                this.TargetAgreementId = agg.Aggrement_Id; // Store this globally

                // FIX FOR CMB SELECTION: Ensure data source is filled and types match
                customer_cmb.EditValue = agg.Customer_Id;

                // Use a safe conversion to match the ValueMember of the lookup
                store_cmb.EditValue = Convert.ToDecimal(agg.Store_Id);

                if(agg.Guardian_Id > 0)
                {
                    guarrantor_cmb.EditValue = agg.Guardian_Id;
                }
                else
                {
                    guarrantor_cmb.Clear();
                }
                
               
                sale_date_picker.DateTime = Convert.ToDateTime(agg.Date);
                remaining_bal_inp.Text = agg.Current_Balance.ToString();

                // Total Receipts = (Total Price - Current Balance)
                total_reciepts_inp.Text = (agg.Total_Amount - (agg.Current_Balance + agg.Sale_Return_Amount)).ToString();

                // Load only items that haven't been fully returned yet
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["store_items"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Sql = $@"SELECT itm.id as 'Code', itm.name as 'Item', si.sale_rate as 'Sale Rate', 
                      (si.sold_qty - si.returned_quantity) as 'Sold Qty' 
                      FROM sale_items si 
                      JOIN items itm ON si.item_id = itm.id 
                      WHERE si.agreement_id = {agg.Aggrement_Id} AND (si.sold_qty - si.returned_quantity) > 0";
                query.Name = "store_items";
                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();
                emi_amounts_table.Clear();
                rem_emi_amounts_table.Clear();
                emi_amounts_table = agg.Aggrement_Dues_Table;
                emi_dues_container.DataSource = emi_amounts_table;

                item_cmb.Enabled = true;
            }
            else
            {
                XtraMessageBox.Show("Agreement not found with this reference number.");
                this.returning_aggrement = null;
            }
        }


