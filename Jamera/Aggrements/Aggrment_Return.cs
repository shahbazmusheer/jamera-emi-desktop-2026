        public void setEvaluatedValues()
        {
            try
            {
                double qty = 0;
                double sale_rate_val = 0;
                double item_total_paid = 0;
                double total = 0;
                double remaining = 0;

                // Use TryParse to safely extract values. If parsing fails, the variable remains 0.
                double.TryParse(item_qty_inp.Text, out qty);
                double.TryParse(sale_rate_inp.Text, out sale_rate_val);
                double.TryParse(item_total_paid_inp.Text, out item_total_paid);

                // Perform Calculations
                total = qty * sale_rate_val;
                remaining = total - item_total_paid;

                // Output to UI with consistent decimal formatting
                item_total.Text = total.ToString("0.00");
                item_rem_inp.Text = remaining.ToString("0.00");
            }
            catch (Exception ex)
            {
                // Fallback in case of unexpected errors
                //item_total.Text = "0.00";
                item_rem_inp.Text = "0.00";
                // Optional: Log the error if needed
                // Console.WriteLine("Calculation Error: " + ex.Message);
            }
        }
