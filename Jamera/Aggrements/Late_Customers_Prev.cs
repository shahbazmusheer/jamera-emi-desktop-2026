        public void Send_Msg()
        {
            Messages_List.Clear();
            Int32[] selectedRowHandles = gridView3.GetSelectedRows();
            ColumnView view = gridControl1.MainView as ColumnView;
            GridColumn colCode = view.Columns["Code"];
            GridColumn colOfficePhone = view.Columns["Office Phone"];
            GridColumn colHomePhone = view.Columns["Home Phone"];
            GridColumn colName = view.Columns["Name"];
            GridColumn colRefNo = view.Columns["Ref.No"];
            GridColumn colDueDate = view.Columns["Due Date"];
            GridColumn colDueAmount = view.Columns["Due Amount"];

            for (int i = 0; i < selectedRowHandles.Length; i++)
            {
                int selectedRowHandle = selectedRowHandles[i];
                if (selectedRowHandle >= 0)
                {
                    int user_id = Convert.ToInt32(view.GetRowCellDisplayText(selectedRowHandles[i], colCode));
                    String office_phone = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colOfficePhone));
                    String home_phone = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colHomePhone));
                    String name = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colName));
                    String ref_no = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colRefNo));
                    String due_date = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colDueDate));
                    String due_amount = Convert.ToString(view.GetRowCellDisplayText(selectedRowHandles[i], colDueAmount));
                    String group_name = "Customers ( Debitors )";
                    string Message_Text = message_inp.Text;
                    string replaced_name_str = Message_Text.Replace("[NAME]",name);
                    string replaced_ref_no_str = replaced_name_str.Replace("[REF_NO]", ref_no);
                    string replaced_due_date_str = null;
                    if (messages_type_cmb.Text == "English")
                    {
                        replaced_due_date_str = replaced_ref_no_str.Replace("[DUE_DATE]", due_date);
                    }
                    else
                    {
                        due_date = Convert.ToDateTime(due_date).ToString("yyyy-MM-dd");
                        replaced_due_date_str = replaced_ref_no_str.Replace("[DUE_DATE]", due_date);
                    }
                    
                    string replaced_due_amount_str = replaced_due_date_str.Replace("[DUE_AMOUNT]", due_amount);
                    Message_Text = null;
                    Message_Text = replaced_due_amount_str;
                    if (phones_options_cmb.Text == "Both")
                    {
                        if (home_phone != "")
                        {
                            Messages.Message message = new Messages.Message();
                            message.ACCOUNT_ID = user_id;
                            message.RECIEVER_NUMBER = home_phone;
                            message.Group = group_name;
                            message.Message_Text = Message_Text;
                            message.Message_Type = messages_type_cmb.Text;
                            Messages_List.Add(message);
                        }
                        if (office_phone != "")
                        {
                            Messages.Message message = new Messages.Message();
                            message.ACCOUNT_ID = user_id;
                            message.RECIEVER_NUMBER = office_phone;
                            message.Group = group_name;
                            message.Message_Text = Message_Text;
                            message.Message_Type = messages_type_cmb.Text;
                            Messages_List.Add(message);
                        }
                    }
                    else if (phones_options_cmb.Text == "Home Phone")
                    {
                        if (home_phone != "")
                        {
                            Messages.Message message = new Messages.Message();
                            message.ACCOUNT_ID = user_id;
                            message.RECIEVER_NUMBER = home_phone;
                            message.Group = group_name;
                            message.Message_Text = Message_Text;
                            message.Message_Type = messages_type_cmb.Text;
                            Messages_List.Add(message);
                        }
                    }
                    else if (phones_options_cmb.Text == "Office Phone")
                    {
                        if (office_phone != "")
                        {
                            Messages.Message message = new Messages.Message();
                            message.ACCOUNT_ID = user_id;
                            message.RECIEVER_NUMBER = office_phone;
                            message.Group = group_name;
                            message.Message_Text = Message_Text;
                            message.Message_Type = messages_type_cmb.Text;
                            Messages_List.Add(message);
                        }
                    }
                }
                Thread.Sleep(1000);
            }
            if (SMS_Thread.ThreadState == ThreadState.Unstarted)
            {
                progress_panel.Visible = true;
                //messages_groups_cmb.Enabled = false;
                send_btn.Enabled = false;
                message_inp.ReadOnly = true;
                gridView3.OptionsBehavior.Editable = false;
                SMS_Thread.Start();
            }
            else if (SMS_Thread.ThreadState == ThreadState.Aborted || SMS_Thread.ThreadState == ThreadState.Stopped)
            {
                progress_panel.Visible = true;
                //messages_groups_cmb.Enabled = false;
                send_btn.Enabled = false;
                gridView3.OptionsBehavior.Editable = false;
                //CheckBoxRowSelect
                //gridView3.OptionsSelection.MultiSelectMode = DevExpress.XtraGrid.Views.Grid.GridMultiSelectMode.RowSelect;
                message_inp.ReadOnly = true;
                SMS_Thread = new Thread(Send_Message_To_Numbers);
                SMS_Thread.Start();
            }
            //Send Messages List TO Thread
        }
