        private void gridView1_CustomColumnSort(object sender, DevExpress.XtraGrid.Views.Base.CustomColumnSortEventArgs e)
        {
            if (e.Column.FieldName == "Date")
            {
                // 1. Get the Ref.No values for the rows being compared
                object refObj1 = gridView1.GetListSourceRowCellValue(e.ListSourceRowIndex1, "Ref.No");
                object refObj2 = gridView1.GetListSourceRowCellValue(e.ListSourceRowIndex2, "Ref.No");

                if (refObj1 == null || refObj2 == null) return;

                string s1 = refObj1.ToString();
                string s2 = refObj2.ToString();

                try
                {
                    // 2. Split the strings: F12-2026-01 -> ["F12", "2026", "01"]
                    string[] p1 = s1.Split('-');
                    string[] p2 = s2.Split('-');

                    // 3. Validation: Ensure both have the 3 expected parts
                    if (p1.Length == 3 && p2.Length == 3)
                    {
                        // Compare Year (The middle part: index 1)
                        int year1 = int.Parse(p1[1]);
                        int year2 = int.Parse(p2[1]);
                        int yearResult = year1.CompareTo(year2);

                        if (yearResult != 0)
                        {
                            e.Result = yearResult;
                        }
                        else
                        {
                            // Years are the same, compare the Serial (The last part: index 2)
                            int ser1 = int.Parse(p1[2]);
                            int ser2 = int.Parse(p2[2]);
                            e.Result = ser1.CompareTo(ser2);
                        }

                        e.Handled = true;
                    }
                }
                catch
                {
                    // If any parsing fails (e.g. invalid format), fall back to standard string sort
                    e.Result = string.Compare(s1, s2);
                    e.Handled = true;
                }
            }
        }

