        public void ExecuteResponsiveSearch()
        {
            // 1. Define the Base Select and Joins
            string baseQuery = @"
        SELECT TOP 5000 
            stores.area_code as 'Area Code',
            stores.name as 'Area',
            aggrements.date as 'Date',
            aggrements.id as 'Code',
            aggrements.ref_no as 'Ref.No',
            accounts.id as 'Cust.Code',
            accounts.name as 'Customer',
            guardians.name as 'Guarantor',
            aggrements.current_balance as 'Balance',
            items.id as 'Item.Code',
            items.name as 'Item',
            sale_items.advance_rate as 'Advance',
            sale_items.emi_price as 'Monthly EMI',
            sale_items.sale_rate as 'Rate',
            sale_items.sold_qty as 'Qty',
            sale_items.net_total as 'Total' 
        FROM dbo.aggrements aggrements 
        LEFT JOIN dbo.accounts accounts ON accounts.id = aggrements.customer_id 
        INNER JOIN dbo.stores stores ON stores.id = aggrements.store_id 
        LEFT JOIN dbo.accounts guardians ON guardians.id = aggrements.guardian_id 
        LEFT JOIN sale_items ON aggrements.id = sale_items.agreement_id 
        LEFT JOIN items ON sale_items.item_id = items.id";

            // 2. Build Dynamic Filters
            List<string> filters = new List<string>();

            // A. Search by Ref.No (If input is not empty and other checks are off)
            if (!string.IsNullOrEmpty(aggrement_id_inp.Text))
            {
                filters.Add($"aggrements.ref_no = '{aggrement_id_inp.Text}'");
            }

            // B. Search by Customer
            if (by_customer_check.Checked && customer_search_cmb.EditValue != null && customer_search_cmb.Text != "")
            {
                filters.Add($"aggrements.customer_id = {Convert.ToInt32(customer_search_cmb.EditValue)}");
            }

            // C. Search by Store
            if (stores_check.Checked && stores_cmb.EditValue != null && stores_cmb.Text != "")
            {
                filters.Add($"aggrements.store_id = {Convert.ToInt32(stores_cmb.EditValue)}");
            }

            // D. Search by Item
            if (item_chkbx.Checked && items_cmb.EditValue != null && items_cmb.Text != "")
            {
                filters.Add($"items.id = {Convert.ToInt32(items_cmb.EditValue)}");
            }

            // E. Search by Date Range
            if (by_date_check.Checked && !string.IsNullOrEmpty(from_date_picker.Text) && !string.IsNullOrEmpty(to_date_picker.Text))
            {
                filters.Add($"(CONVERT(DATETIME, aggrements.date, 103) >= CONVERT(DATETIME, '{from_date_picker.Text}', 103) " +
                            $"AND CONVERT(DATETIME, aggrements.date, 103) <= CONVERT(DATETIME, '{to_date_picker.Text}', 103))");
            }

            // 3. Assemble Final SQL
            string whereClause = filters.Count > 0 ? " WHERE " + string.Join(" AND ", filters) : "";
            string finalSql = baseQuery + whereClause + " ORDER BY aggrements.id DESC";

            // 4. Update the SqlDataSource
            try
            {
                sqlDataSource1.Queries.Remove(sqlDataSource1.Queries["Query"]);
                CustomSqlQuery query = new CustomSqlQuery();
                query.Name = "Query";
                query.Sql = finalSql;

                sqlDataSource1.Queries.Add(query);
                sqlDataSource1.RebuildResultSchema();
                sqlDataSource1.Fill();

                // Re-configure grouping to handle the new data structure
                ConfigureGridGrouping();
            }
            catch (Exception ex)
            {
                XtraMessageBox.Show("Search Error: " + ex.Message);
            }
        }
