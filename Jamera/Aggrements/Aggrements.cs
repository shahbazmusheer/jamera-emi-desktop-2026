        private void gridView1_DoubleClick(object sender, EventArgs e)
        {
            if (gridView1.DataRowCount > 0)
            {

                GridHitInfo hitInfo = gridView1.CalcHitInfo((e as MouseEventArgs).Location);
                if (!(hitInfo.InGroupRow))
                {
                    int aggrement_id = Convert.ToInt32(gridView1.GetFocusedRowCellValue(gridView1.Columns["Code"]));
                    Edit_Aggrement edit_aggrement = new Edit_Aggrement(aggrement_id);
                    UC_Opener_Form form = new UC_Opener_Form("Agreement Details", edit_aggrement);
                    edit_aggrement.uc_opener = form;
                    form.Show(this);
                }
            }
        }

        private void by_customer_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_customer_check.Checked)
            {
                customer_search_cmb.Enabled = true;
                aggrement_id_inp.Text = null;
                aggrement_id_inp.Enabled = false;
            }
            else
            {
                customer_search_cmb.Text = null;
                customer_search_cmb.Enabled = false;
                if(by_date_check.Checked != true && stores_check.Checked != true)
                {
                    aggrement_id_inp.Enabled = true;
                    by_date_check.Enabled = true;
                }
            }
        }

        private void by_date_check_CheckedChanged(object sender, EventArgs e)
        {
            if (by_date_check.Checked)
            {
                from_date_picker.Enabled = true;
                to_date_picker.Enabled = true;
                aggrement_id_inp.Text = null;
                aggrement_id_inp.Enabled = false;
